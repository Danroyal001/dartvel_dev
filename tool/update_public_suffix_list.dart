// Regenerates dartvel_core's copy of the Public Suffix List.
//
//   dart tool/update_public_suffix_list.dart            # fetches the list
//   dart tool/update_public_suffix_list.dart list.dat   # from a local copy
//
// Writes packages/dartvel_core/lib/src/web/public_suffix_list.dart: every
// rule of both sections (ICANN and private, because browsers apply both), in
// lowercase ASCII with internationalised labels in their punycode form, the
// form a request's host arrives in. Imports only dart: libraries, so it runs
// without resolving the root package.
import 'dart:convert';
import 'dart:io';

const String _source = 'https://publicsuffix.org/list/public_suffix_list.dat';
const String _target =
    'packages/dartvel_core/lib/src/web/public_suffix_list.dart';

Future<void> main(List<String> args) async {
  final String text = args.isEmpty
      ? await _fetch(Uri.parse(_source))
      : File(args.first).readAsStringSync();
  final String version = RegExp(r'^// VERSION: (.+)$', multiLine: true)
          .firstMatch(text)
          ?.group(1)
          ?.trim() ??
      'unknown';
  final List<String> rules = <String>[];
  for (final String raw in const LineSplitter().convert(text)) {
    final String line = raw.trim();
    if (line.isEmpty || line.startsWith('//')) continue;
    // A rule ends at the first whitespace.
    final String rule = line.split(RegExp(r'\s')).first.toLowerCase();
    final bool exception = rule.startsWith('!');
    final String name = exception ? rule.substring(1) : rule;
    final String ascii = name.split('.').map(_punycodeLabel).join('.');
    rules.add(exception ? '!$ascii' : ascii);
  }
  final StringBuffer out = StringBuffer()
    ..writeln('// GENERATED by tool/update_public_suffix_list.dart from')
    ..writeln('// $_source')
    ..writeln('// (VERSION: $version). Do not edit by hand; run the tool.')
    ..writeln('//')
    ..writeln('// The list is subject to the Mozilla Public License, v. 2.0:')
    ..writeln('// https://mozilla.org/MPL/2.0/.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln('library;')
    ..writeln()
    ..writeln('/// The list\'s own version stamp.')
    ..writeln("const String dvPublicSuffixListVersion = '$version';")
    ..writeln()
    ..writeln('/// Every rule, newline-separated: `a.b`, `*.a.b` or `!a.b`.')
    ..writeln("const String dvPublicSuffixRules = '''")
    ..writeln(rules.join('\n'))
    ..writeln("''';");
  File(_target).writeAsStringSync(out.toString());
  stdout.writeln('${rules.length} rules (VERSION $version) -> $_target');
}

Future<String> _fetch(Uri uri) async {
  final HttpClient client = HttpClient();
  try {
    final HttpClientResponse response =
        await (await client.getUrl(uri)).close();
    if (response.statusCode != 200) {
      throw StateError('$uri answered ${response.statusCode}.');
    }
    return await response.transform(utf8.decoder).join();
  } finally {
    client.close(force: true);
  }
}

/// [label] in punycode (RFC 3492) with the `xn--` prefix, or unchanged when
/// it is already ASCII.
String _punycodeLabel(String label) {
  final List<int> input = label.runes.toList();
  if (input.every((int c) => c < 0x80)) return label;
  const int base = 36, tMin = 1, tMax = 26, skew = 38, damp = 700;
  int n = 128, delta = 0, bias = 72;
  final StringBuffer output = StringBuffer();
  for (final int c in input) {
    if (c < 0x80) output.writeCharCode(c);
  }
  final int basic = output.length;
  int handled = basic;
  if (basic > 0) output.write('-');
  String digit(int d) => String.fromCharCode(d < 26 ? 97 + d : 22 + d);
  int adapt(int delta, int points, bool first) {
    delta = first ? delta ~/ damp : delta ~/ 2;
    delta += delta ~/ points;
    int k = 0;
    while (delta > ((base - tMin) * tMax) ~/ 2) {
      delta ~/= base - tMin;
      k += base;
    }
    return k + (base - tMin + 1) * delta ~/ (delta + skew);
  }

  while (handled < input.length) {
    int m = 0x7fffffff;
    for (final int c in input) {
      if (c >= n && c < m) m = c;
    }
    delta += (m - n) * (handled + 1);
    n = m;
    for (final int c in input) {
      if (c < n) delta++;
      if (c == n) {
        int q = delta;
        for (int k = base;; k += base) {
          final int t = k <= bias ? tMin : (k >= bias + tMax ? tMax : k - bias);
          if (q < t) break;
          output.write(digit(t + (q - t) % (base - t)));
          q = (q - t) ~/ (base - t);
        }
        output.write(digit(q));
        bias = adapt(delta, handled + 1, handled == basic);
        delta = 0;
        handled++;
      }
    }
    delta++;
    n++;
  }
  return 'xn--$output';
}
