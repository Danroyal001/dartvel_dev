/// The `dartvel:` object of a project, whichever way it is written.
///
/// `dartvel:` is either a YAML map in `pubspec.yaml` or the path of a Dart
/// file whose public class extends `DartvelConfig` (package:dartvel_core/config.dart).
/// Both end up as the same map here: the Dart class is run once and asked for
/// `toPubspec()`, so every reader of the configuration sees one shape and a
/// key cannot work in one spelling and be ignored in the other.
library;

import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:crypto/crypto.dart';
import 'package:path/path.dart' as p;
import 'package:yaml/yaml.dart';

/// What reading the section found.
class DVDartvelSection {
  const DVDartvelSection(
    this.values, {
    this.problems = const <String>[],
    this.fromDartConfig,
  });

  /// The `dartvel:` object. Empty when the project has none.
  final Map<Object?, Object?> values;

  /// Why the Dart config could not be read, when it could not.
  final List<String> problems;

  /// The Dart config file the values came from, or null for YAML.
  final String? fromDartConfig;
}

/// Reads the `dartvel:` section of the project at [root]. Never throws.
DVDartvelSection dvDartvelSection(String root) {
  final File pubspec = File(p.join(root, 'pubspec.yaml'));
  if (!pubspec.existsSync())
    return const DVDartvelSection(<Object?, Object?>{});
  Object? document;
  try {
    document = loadYaml(pubspec.readAsStringSync());
  } on Object {
    return const DVDartvelSection(<Object?, Object?>{});
  }
  final Object? dartvel = document is Map ? document['dartvel'] : null;
  if (dartvel is Map) return DVDartvelSection(dartvel);
  if (dartvel is String) return dvEvaluateDartConfig(root, dartvel);
  return const DVDartvelSection(<Object?, Object?>{});
}

/// The `dartvel:` object a Dart config file describes.
///
/// The class is imported by a small program the build writes under
/// `.dart_tool/dartvel/` and asked for `toPubspec()`. The answer is cached
/// against a digest of the file, the project sources it imports and the
/// resolved package configuration, so a build reads it once and an edit to
/// an imported helper is never answered from a stale cache.
DVDartvelSection dvEvaluateDartConfig(String root, String relativePath) {
  final File configFile = File(p.join(root, relativePath));
  if (!configFile.existsSync()) {
    return DVDartvelSection(
      const <Object?, Object?>{},
      problems: <String>[
        'dartvel: points at $relativePath, which is not there.',
      ],
      fromDartConfig: relativePath,
    );
  }
  final String source = configFile.readAsStringSync();
  final Match? declaration = RegExp(
    r'class\s+(?:const\s+)?([A-Z][A-Za-z0-9_]*)(?:\s*\([^)]*\))?\s+extends\s+DartvelConfig\b',
  ).firstMatch(source);
  if (declaration == null) {
    return DVDartvelSection(
      const <Object?, Object?>{},
      problems: <String>[
        '$relativePath must declare a public class extending DartvelConfig.',
      ],
      fromDartConfig: relativePath,
    );
  }
  final String className = declaration.group(1)!;
  final Directory work = Directory(p.join(root, '.dart_tool', 'dartvel'))
    ..createSync(recursive: true);
  final String stamp = '${_configSourcesDigest(root, configFile)}:$className';
  final File cache = File(p.join(work.path, 'dart_config.json'));
  if (cache.existsSync()) {
    try {
      final Object? cached = jsonDecode(cache.readAsStringSync());
      if (cached is Map &&
          cached['stamp'] == stamp &&
          cached['values'] is Map) {
        return DVDartvelSection(
          cached['values'] as Map<Object?, Object?>,
          fromDartConfig: relativePath,
        );
      }
    } on FormatException {
      // A cache that will not parse is rebuilt below.
    }
  }
  final File probe = File(p.join(work.path, 'dart_config_probe.dart'));
  final String importPath = p
      .relative(configFile.path, from: work.path)
      .replaceAll(r'\', '/');
  probe.writeAsStringSync('''
// GENERATED by dartvel. Reads the project's Dart config as the build sees it.
import 'dart:convert';
import '$importPath' as config;

void main() => print(jsonEncode(const config.$className().toPubspec()));
''');
  // The VM running this when it is the Dart SDK's, else `dart` from PATH: a
  // compiled dartvel binary is not a Dart VM and cannot run a program.
  final String dart =
      p.basenameWithoutExtension(Platform.resolvedExecutable) == 'dart'
      ? Platform.resolvedExecutable
      : 'dart';
  final ProcessResult result = Process.runSync(
    dart,
    <String>['run', probe.path],
    workingDirectory: root,
    runInShell: Platform.isWindows,
  );
  if (result.exitCode != 0) {
    return DVDartvelSection(
      const <Object?, Object?>{},
      problems: <String>[
        'Could not read $relativePath: ${'${result.stderr}'.trim().split('\n').take(6).join(' ')} '
            '(the class needs a const constructor with no arguments).',
      ],
      fromDartConfig: relativePath,
    );
  }
  final String output = '${result.stdout}'.trim().split('\n').last;
  try {
    final Object? values = jsonDecode(output);
    if (values is! Map) throw const FormatException('not an object');
    cache.writeAsStringSync(
      jsonEncode(<String, Object?>{'stamp': stamp, 'values': values}),
    );
    return DVDartvelSection(values, fromDartConfig: relativePath);
  } on FormatException {
    return DVDartvelSection(
      const <Object?, Object?>{},
      problems: <String>['$relativePath did not describe a dartvel: object.'],
      fromDartConfig: relativePath,
    );
  }
}

/// A digest of every project source the config file reaches, so editing a
/// helper it imports is a different answer and not a stale cached one.
///
/// Relative `import`/`export`/`part` URIs and `package:<this package>/` URIs
/// are followed transitively; other packages are pinned by the resolved
/// package configuration, which is part of the digest too.
String _configSourcesDigest(String root, File configFile) {
  final String? self = dvPackageName(root);
  final RegExp directive = RegExp(
    r'''^\s*(?:import|export|part)\s+['"]([^'"]+)['"]''',
    multiLine: true,
  );
  final List<String> pending = <String>[p.normalize(configFile.absolute.path)];
  final Set<String> seen = <String>{};
  while (pending.isNotEmpty) {
    final String path = pending.removeLast();
    if (!seen.add(path)) continue;
    final File file = File(path);
    if (!file.existsSync()) continue;
    final String source = file.readAsStringSync();
    for (final Match m in directive.allMatches(source)) {
      final String uri = m.group(1)!;
      if (uri.startsWith('dart:')) continue;
      if (uri.startsWith('package:')) {
        if (self == null || !uri.startsWith('package:$self/')) continue;
        pending.add(
          p.normalize(
            p.join(root, 'lib', uri.substring('package:$self/'.length)),
          ),
        );
      } else if (!uri.contains(':')) {
        pending.add(p.normalize(p.join(p.dirname(path), uri)));
      }
    }
  }
  final File packages = File(p.join(root, '.dart_tool', 'package_config.json'));
  final BytesBuilder bytes = BytesBuilder(copy: false);
  final List<String> ordered = seen.toList()..sort();
  for (final String path in <String>[...ordered, packages.path]) {
    final File file = File(path);
    if (!file.existsSync()) continue;
    bytes
      ..add(utf8.encode(p.relative(path, from: root)))
      ..add(const <int>[0])
      ..add(file.readAsBytesSync())
      ..add(const <int>[0]);
  }
  return '${sha256.convert(bytes.takeBytes())}';
}

/// The package name in the project's pubspec, or null.
String? dvPackageName(String root) {
  final File pubspec = File(p.join(root, 'pubspec.yaml'));
  if (!pubspec.existsSync()) return null;
  try {
    final Object? document = loadYaml(pubspec.readAsStringSync());
    final Object? name = document is Map ? document['name'] : null;
    return name is String ? name : null;
  } on Object {
    return null;
  }
}
