/// StoreKit 2 for `DV.Purchases` on iOS and macOS.
///
/// StoreKit 2 is a Swift-only, async API: `Product`, `Transaction` and
/// `AppStore` have no Objective-C classes behind them, so there is nothing
/// for `objc_getClass` to find and nothing Dart can message. What Dart can
/// reach is Swift compiled into the application, which is what this writes:
/// one `@objc` class in `Runner`, beside `AppDelegate.swift`, spliced into
/// the application target's Sources phase the same way the WidgetCenter
/// reload shim is.
///
/// The class speaks JSON strings and is polled rather than called back.
/// Every StoreKit 2 call is `async` and completes on a thread of Swift's
/// choosing; a block or a function pointer into Dart from that thread is the
/// hardest part of an FFI bridge to get right and to see going wrong.
/// `start` returns a request id at once, the work runs in a `Task`, and
/// `poll` hands back the answer when it is there. Transactions that arrive
/// outside a purchase -- an approved Ask to Buy, a renewal, a purchase on
/// another device -- queue up for `drainUpdates`.
///
/// Nothing here verifies a purchase. The JWS StoreKit returns is handed to
/// the application's server whether StoreKit verified it or not, because
/// the server is the one place a receipt check means anything.
library;

import 'dart:io';

import 'package:dartvel_core/dartvel.dart'
    show
        dvStoreKitClass,
        dvStoreKitDrainSelector,
        dvStoreKitListenSelector;
import 'package:path/path.dart' as p;

import 'apple_widget_reload.dart' show dvApplePbxprojWithRunnerSwift;

/// The file the shim is written to, inside the `Runner` folder.
const String dvAppleStoreKitFileName = 'DartvelStoreKit.swift';

/// The prefix every pbxproj object this adds carries. Its own, so the
/// widget reload shim and this are added and removed independently.
const String dvAppleStoreKitIdPrefix = 'DA97E1DA5701';

/// Whether `dartvel.purchases` is declared: a map of settings, or `true`.
///
/// Declared rather than inferred, because linking StoreKit into an
/// application that sells nothing is a review question nobody needs to be
/// asked.
bool dvPurchasesDeclared(Object? dartvelSection) {
  final Object? purchases =
      dartvelSection is Map ? dartvelSection['purchases'] : null;
  return purchases is Map || purchases == true;
}

/// [pbxproj] with the shim compiled into the application, or without it.
String dvApplePbxprojWithStoreKit(String pbxproj, {required bool include}) =>
    dvApplePbxprojWithRunnerSwift(
      pbxproj,
      fileName: dvAppleStoreKitFileName,
      idPrefix: dvAppleStoreKitIdPrefix,
      include: include,
    );

/// Writes or removes the shim for [platform] (`ios` or `macos`) under
/// [root], from the project's `dartvel` pubspec section. Returns whether the
/// project now has it.
///
/// A project without `<platform>/Runner.xcodeproj` is left alone: there is
/// nothing to compile the shim into, and `dartvel build` has already said
/// so for the platform as a whole.
bool dvWriteAppleStoreKit(String root, String platform, Object? dartvelSection) {
  final bool declared = dvPurchasesDeclared(dartvelSection);
  final File project =
      File(p.join(root, platform, 'Runner.xcodeproj', 'project.pbxproj'));
  final File shim = File(p.join(root, platform, 'Runner', dvAppleStoreKitFileName));
  if (!project.existsSync()) return false;

  if (declared) {
    shim.parent.createSync(recursive: true);
    shim.writeAsStringSync(dvAppleStoreKitSource());
  } else if (shim.existsSync()) {
    // Taken away with the declaration. A Swift file left behind after its
    // build-file entry went is one Xcode does not compile and does not
    // mention, sitting in the project folder for ever.
    shim.deleteSync();
  }

  final String before = project.readAsStringSync();
  final String after = dvApplePbxprojWithStoreKit(before, include: declared);
  if (after != before) project.writeAsStringSync(after);
  return declared;
}

/// The shim, as Swift.
///
/// `@objc(name)` rather than a bare `@objc`: Swift mangles a type name
/// unless it is given an explicit Objective-C one, and a mangled name is a
/// class `objc_getClass` cannot find.
///
/// The availability guards are not optional. StoreKit 2 starts at iOS 15
/// and macOS 12, a Flutter application's deployment target is usually lower,
/// and without the guard the file does not compile -- at the Xcode step,
/// after everything in Dart has passed.
String dvAppleStoreKitSource() => '''
// GENERATED by dartvel build from dartvel.purchases. Do not edit: the next
// build writes it again.
//
// StoreKit 2 is Swift-only and async, so Dart cannot message it. This class
// is the boundary: JSON strings in, a request id back, the answer polled.
// It verifies nothing -- the signed transaction goes to the application's
// server, verified by StoreKit or not, and the server decides.
import Foundation
#if canImport(StoreKit)
import StoreKit
#endif

@objc($dvStoreKitClass)
public final class $dvStoreKitClass: NSObject {
    private static let lock = NSLock()
    private static var answers: [String: String] = [:]
    private static var pendingUpdates: [[String: Any]] = []
    private static var listening = false
    private static var requests = 0
    private static var listener: Any?

    static let unavailable = "StoreKit 2 needs iOS 15 or macOS 12"

    /// Starts listening to Transaction.updates. StoreKit delivers what
    /// completed while the application was closed only to a listener.
    @objc public static func $dvStoreKitListenSelector() {
        startListening()
    }

    /// Begins one operation and answers its request id at once.
    @objc public static func start(_ request: NSString) -> NSString {
        startListening()
        lock.lock()
        requests += 1
        let id = "storekit-\\(requests)"
        lock.unlock()
        guard let data = (request as String).data(using: .utf8),
              let json = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any] else {
            answer(id, ["error": "the request is not a JSON object"])
            return id as NSString
        }
        #if canImport(StoreKit)
        if #available(iOS 15.0, macOS 12.0, tvOS 15.0, *) {
            Task.detached {
                let result = await DartvelStoreKitOperations.run(json)
                $dvStoreKitClass.answer(id, result)
            }
            return id as NSString
        }
        #endif
        answer(id, ["error": unavailable])
        return id as NSString
    }

    /// The answer to request [id] once it is done, else nil. Each answer is
    /// handed out once.
    @objc public static func poll(_ id: NSString) -> NSString? {
        lock.lock()
        defer { lock.unlock() }
        guard let text = answers.removeValue(forKey: id as String) else { return nil }
        return text as NSString
    }

    /// The transactions Transaction.updates delivered since the last call.
    @objc public static func $dvStoreKitDrainSelector() -> NSString {
        startListening()
        lock.lock()
        let drained = pendingUpdates
        pendingUpdates.removeAll()
        lock.unlock()
        return encode(drained) as NSString
    }

    static func answer(_ id: String, _ result: [String: Any]) {
        let text = encode(result)
        lock.lock()
        answers[id] = text
        lock.unlock()
    }

    static func queue(_ update: [String: Any]) {
        lock.lock()
        pendingUpdates.append(update)
        lock.unlock()
    }

    static func encode(_ value: Any) -> String {
        guard JSONSerialization.isValidJSONObject(value),
              let data = try? JSONSerialization.data(withJSONObject: value),
              let text = String(data: data, encoding: .utf8) else {
            return "{\\"error\\":\\"the answer could not be encoded\\"}"
        }
        return text
    }

    private static func startListening() {
        lock.lock()
        if listening {
            lock.unlock()
            return
        }
        listening = true
        lock.unlock()
        #if canImport(StoreKit)
        if #available(iOS 15.0, macOS 12.0, tvOS 15.0, *) {
            listener = Task.detached {
                for await update in Transaction.updates {
                    $dvStoreKitClass.queue(DartvelStoreKitOperations.describe(update))
                }
            }
        }
        #endif
    }
}

#if canImport(StoreKit)
@available(iOS 15.0, macOS 12.0, tvOS 15.0, *)
enum DartvelStoreKitOperations {
    static func run(_ request: [String: Any]) async -> [String: Any] {
        do {
            switch request["op"] as? String ?? "" {
            case "available":
                return ["available": AppStore.canMakePayments]
            case "listings":
                return ["listings": try await listings(request["ids"] as? [String] ?? [])]
            case "purchase":
                return try await purchase(request)
            case "owned":
                return ["transactions": try await owned(sync: request["sync"] as? Bool ?? false)]
            case "finish":
                return await finish(request["transactionId"] as? String ?? "")
            default:
                return ["error": "unknown operation"]
            }
        } catch {
            return ["error": String(describing: error)]
        }
    }

    static func listings(_ ids: [String]) async throws -> [[String: Any]] {
        var out: [[String: Any]] = []
        for product in try await Product.products(for: ids) {
            let currency = product.priceFormatStyle.currencyCode
            var listing: [String: Any] = [
                "storeProductId": product.id,
                "title": product.displayName,
                "description": product.description,
                "displayPrice": product.displayPrice,
                "currency": currency,
            ]
            if let milliunits = milliunits(product.price) {
                listing["priceMilliunits"] = milliunits
            }
            if let subscription = product.subscription {
                listing["period"] = iso(subscription.subscriptionPeriod)
                var offers: [[String: Any]] = []
                let eligible = await subscription.isEligibleForIntroOffer
                if let intro = subscription.introductoryOffer {
                    let kind = intro.paymentMode == .freeTrial ? "freeTrial" : "introductory"
                    offers.append(describe(intro, kind: kind, currency: currency, eligible: eligible))
                }
                for offer in subscription.promotionalOffers {
                    offers.append(describe(offer, kind: "promotional", currency: currency, eligible: true))
                }
                if #available(iOS 18.0, macOS 15.0, tvOS 18.0, *) {
                    for offer in subscription.winBackOffers {
                        offers.append(describe(offer, kind: "winBack", currency: currency, eligible: true))
                    }
                }
                listing["offers"] = offers
            }
            out.append(listing)
        }
        return out
    }

    static func describe(_ offer: Product.SubscriptionOffer, kind: String, currency: String, eligible: Bool) -> [String: Any] {
        var out: [String: Any] = [
            "id": offer.id ?? kind,
            "kind": kind,
            "displayPrice": offer.displayPrice,
            "period": iso(offer.period),
            "periods": offer.periodCount,
            "eligible": eligible,
            "currency": currency,
        ]
        if let milliunits = milliunits(offer.price) {
            out["priceMilliunits"] = milliunits
        }
        return out
    }

    static func iso(_ period: Product.SubscriptionPeriod) -> String {
        let unit: String
        switch period.unit {
        case .day: unit = "D"
        case .week: unit = "W"
        case .month: unit = "M"
        case .year: unit = "Y"
        @unknown default: unit = "D"
        }
        return "P\\(period.value)\\(unit)"
    }

    /// The price in thousandths of the currency's major unit, exactly, or
    /// nil when it is not a whole number of them: refused rather than
    /// rounded, so a button never shows a price the sheet does not charge.
    static func milliunits(_ price: Decimal) -> Int? {
        let scaled = NSDecimalNumber(decimal: price).multiplying(byPowerOf10: 3)
        let whole = scaled.rounding(accordingToBehavior: NSDecimalNumberHandler(
            roundingMode: .plain, scale: 0, raiseOnExactness: false,
            raiseOnOverflow: false, raiseOnUnderflow: false, raiseOnDivideByZero: false))
        guard whole.compare(scaled) == .orderedSame else { return nil }
        return whole.intValue
    }

    static func purchase(_ request: [String: Any]) async throws -> [String: Any] {
        guard let id = request["storeProductId"] as? String,
              let product = try await Product.products(for: [id]).first else {
            return ["outcome": "failed", "reason": "the App Store has no product with this identifier"]
        }
        var options: Set<Product.PurchaseOption> = []
        if let token = request["appAccountToken"] as? String, let uuid = UUID(uuidString: token) {
            options.insert(.appAccountToken(uuid))
        }
        if let quantity = request["quantity"] as? Int, quantity > 1 {
            options.insert(.quantity(quantity))
        }
        if let offer = request["offer"] as? [String: Any], let offerId = offer["id"] as? String {
            let kind = offer["kind"] as? String ?? ""
            if kind == "promotional" {
                guard let signature = request["offerSignature"] as? [String: Any],
                      let keyId = signature["keyId"] as? String,
                      let nonceText = signature["nonce"] as? String,
                      let nonce = UUID(uuidString: nonceText),
                      let signatureText = signature["signature"] as? String,
                      let signatureData = Data(base64Encoded: signatureText),
                      let timestamp = (signature["timestamp"] as? NSNumber)?.intValue else {
                    return ["outcome": "failed", "reason": "a promotional offer needs the server's signature"]
                }
                options.insert(.promotionalOffer(offerID: offerId, keyID: keyId,
                    nonce: nonce, signature: signatureData, timestamp: timestamp))
            } else if kind == "winBack" {
                if #available(iOS 18.0, macOS 15.0, tvOS 18.0, *) {
                    guard let winBack = product.subscription?.winBackOffers.first(where: { \$0.id == offerId }) else {
                        return ["outcome": "failed", "reason": "the App Store lists no such win-back offer"]
                    }
                    options.insert(.winBackOffer(winBack))
                } else {
                    return ["outcome": "failed", "reason": "win-back offers need iOS 18 or macOS 15"]
                }
            }
            // An introductory offer or free trial is applied by the App Store
            // itself to an eligible customer; there is no option to pass.
        }
        switch try await product.purchase(options: options) {
        case .success(let verification):
            return ["outcome": "purchased", "transaction": describe(verification)]
        case .pending:
            return ["outcome": "pending"]
        case .userCancelled:
            return ["outcome": "cancelled"]
        @unknown default:
            return ["outcome": "failed", "reason": "the App Store answered with an unknown result"]
        }
    }

    static func transaction(of verification: VerificationResult<Transaction>) -> Transaction {
        switch verification {
        case .verified(let transaction):
            return transaction
        case .unverified(let transaction, _):
            // Kept: the server verifies the JWS and is the one that decides.
            return transaction
        }
    }

    static func describe(_ verification: VerificationResult<Transaction>) -> [String: Any] {
        let paid = transaction(of: verification)
        return [
            "storeProductId": paid.productID,
            "transactionId": String(paid.id),
            "receipt": verification.jwsRepresentation,
            "state": "purchased",
            "quantity": paid.purchasedQuantity,
            "productType": paid.productType.rawValue,
        ]
    }

    static func owned(sync: Bool) async throws -> [[String: Any]] {
        if sync {
            try await AppStore.sync()
        }
        var seen = Set<UInt64>()
        var out: [[String: Any]] = []
        for await verification in Transaction.currentEntitlements {
            if seen.insert(transaction(of: verification).id).inserted {
                out.append(describe(verification))
            }
        }
        // Unfinished consumables are not entitlements, and are exactly what a
        // crash between payment and verification leaves behind.
        for await verification in Transaction.unfinished {
            if seen.insert(transaction(of: verification).id).inserted {
                out.append(describe(verification))
            }
        }
        return out
    }

    static func finish(_ id: String) async -> [String: Any] {
        for await verification in Transaction.unfinished {
            let candidate = transaction(of: verification)
            if String(candidate.id) == id {
                await candidate.finish()
                return ["finished": true]
            }
        }
        // Already finished, or never this device's: nothing left to do.
        return ["finished": false]
    }
}
#endif
''';
