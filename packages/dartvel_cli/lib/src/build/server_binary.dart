/// `dartvel build server`: the backend compiled to one executable file.
///
/// The monolith in the specification is a single native backend binary, and
/// what surrounds it already expects one at build/server: the image
/// `dartvel deploy` writes copies build/ and runs /app/server, and the units
/// `dartvel infra` renders start /opt/<app>/server.
///
/// `dart compile exe` alone does not make that file. The HTTP server is a
/// Rust library the backend loads through FFI, and a compiled program has no
/// package to load it from. So the build writes the library's bytes into a
/// generated source the entry point hands to `embedNativeServerLibrary`, and
/// the result runs with nothing beside it.
library;

import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

/// Where the output goes, relative to the project.
String dvServerBinaryPath({bool windows = false}) =>
    p.join('build', windows ? 'server.exe' : 'server');

/// The platform directory and file name dartvel_shelf ships its native
/// library under, for this host.
({String subdir, String name}) dvHostServerLibrary() {
  final String version = Platform.version;
  if (Platform.isMacOS) {
    return (
      subdir: version.contains('arm64') ? 'macos-arm64' : 'macos-x64',
      name: 'libdartvel_shelf.dylib',
    );
  }
  if (Platform.isWindows) {
    return (
      subdir: version.contains('ARM64') ? 'windows-arm64' : 'windows-x64',
      name: 'dartvel_shelf.dll',
    );
  }
  return (
    subdir: version.contains('aarch64') ? 'linux-arm64' : 'linux-x64',
    name: 'libdartvel_shelf.so',
  );
}

/// The native library a server build embeds, or why there is none.
class DVServerLibraryLookup {
  const DVServerLibraryLookup.found(File this.file) : problem = null;
  const DVServerLibraryLookup.missing(String this.problem) : file = null;

  final File? file;
  final String? problem;
}

/// Finds dartvel_shelf's library for [subdir] through the project's
/// resolved packages, which is the copy the project actually builds against.
DVServerLibraryLookup dvLocateServerLibrary(
  String root, {
  required String subdir,
  required String name,
}) {
  final File config = File(p.join(root, '.dart_tool', 'package_config.json'));
  Map<String, Object?>? shelf;
  if (config.existsSync()) {
    try {
      final Object? decoded = jsonDecode(config.readAsStringSync());
      final Object? packages = decoded is Map ? decoded['packages'] : null;
      if (packages is List) {
        for (final Object? entry in packages) {
          if (entry is Map && entry['name'] == 'dartvel_shelf') {
            shelf = entry.cast<String, Object?>();
          }
        }
      }
    } on FormatException {
      shelf = null;
    }
  }
  if (shelf == null) {
    return const DVServerLibraryLookup.missing(
      'this project does not resolve dartvel_shelf, which is the server a '
      'backend binary runs. Add it to dependencies and run pub get.',
    );
  }
  final Uri base = config.parent.uri;
  final Uri packageRoot = base.resolve('${shelf['rootUri']}'.endsWith('/')
      ? '${shelf['rootUri']}'
      : '${shelf['rootUri']}/');
  final File library =
      File(p.join(File.fromUri(packageRoot).path, 'lib', 'native', subdir, name));
  if (!library.existsSync()) {
    return DVServerLibraryLookup.missing(
      'dartvel_shelf has no native server library for $subdir (looked for '
      '${library.path}). A server binary embeds that library, so it can only '
      'be built on a host the library has been built for.',
    );
  }
  return DVServerLibraryLookup.found(library);
}

/// The generated source carrying the library, compressed and base64-encoded.
String dvServerLibrarySource(List<int> library) {
  final String encoded = base64.encode(gzip.encode(library));
  return '// GENERATED by dartvel build server -- do not edit.\n'
      '//\n'
      '// The native server library, gzip-compressed and base64-encoded, so the\n'
      '// compiled backend carries it inside the one file.\n'
      "const String dartvelServerNativeLibrary = '$encoded';\n";
}

/// The binary's entry point: embed the library, then run the backend.
const String dvServerBinaryEntrypoint = '''
// GENERATED by dartvel build server -- do not edit.
//
// dartvel_server.dart with the native server library inside it, compiled
// with dart compile exe into build/server.
import 'dart:convert';
import 'dart:io';

import 'package:dartvel_shelf/dartvel_shelf.dart' show embedNativeServerLibrary;

import 'dartvel_server.dart' as backend;
import 'dartvel_server_native.g.dart';

Future<void> main(List<String> arguments) {
  embedNativeServerLibrary(
    gzip.decode(base64.decode(dartvelServerNativeLibrary)),
  );
  return backend.main(arguments);
}
''';

/// Runs a process; [Process.run] outside tests.
typedef DVServerBinaryRun = Future<ProcessResult> Function(
  String executable,
  List<String> arguments, {
  String? workingDirectory,
});

/// What a server build did.
class DVServerBinaryResult {
  const DVServerBinaryResult({
    required this.ok,
    required this.lines,
    this.binary,
  });

  final bool ok;
  final List<String> lines;
  final File? binary;
}

/// Writes the entry point and compiles build/server. Generation has already
/// run: `.dart_tool/dartvel_server.dart` is what this compiles around.
Future<DVServerBinaryResult> dvBuildServerBinary({
  required String root,
  required File library,
  required DVServerBinaryRun run,
  String dart = 'dart',
}) async {
  final File server = File(p.join(root, '.dart_tool', 'dartvel_server.dart'));
  if (!server.existsSync()) {
    return const DVServerBinaryResult(ok: false, lines: <String>[
      'No generated backend at .dart_tool/dartvel_server.dart. Run '
          '`dartvel routes` first.',
    ]);
  }
  File(p.join(root, '.dart_tool', 'dartvel_server_native.g.dart'))
      .writeAsStringSync(dvServerLibrarySource(library.readAsBytesSync()));
  final File entry =
      File(p.join(root, '.dart_tool', 'dartvel_server_binary.dart'))
        ..writeAsStringSync(dvServerBinaryEntrypoint);

  final String output =
      p.join(root, dvServerBinaryPath(windows: Platform.isWindows));
  Directory(p.dirname(output)).createSync(recursive: true);
  final ProcessResult compiled = await run(
    dart,
    <String>['compile', 'exe', entry.path, '-o', output],
    workingDirectory: root,
  );
  if (compiled.exitCode != 0) {
    return DVServerBinaryResult(ok: false, lines: <String>[
      'dart compile exe exited ${compiled.exitCode}:',
      ...'${compiled.stdout}\n${compiled.stderr}'
          .split('\n')
          .where((String l) => l.trim().isNotEmpty),
    ]);
  }
  final File binary = File(output);
  final double megabytes = binary.lengthSync() / (1024 * 1024);
  return DVServerBinaryResult(
    ok: true,
    binary: binary,
    lines: <String>[
      '${dvServerBinaryPath(windows: Platform.isWindows)} '
          '(${megabytes.toStringAsFixed(1)} MB), the whole backend in one file.',
      'Run it: DARTVEL_PORT=8080 ./${dvServerBinaryPath(windows: Platform.isWindows)}',
    ],
  );
}
