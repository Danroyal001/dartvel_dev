/// Drag and drop on iOS and iPadOS, as Swift `dartvel build ios` compiles
/// into the application.
///
/// UIKit delivers drops to a `UIDropInteraction` and starts drags from a
/// `UIDragInteraction`, both added to a view, both reporting through a
/// delegate protocol, and the files arrive through `NSItemProvider`
/// callbacks on a background queue whose file is deleted when the callback
/// returns. None of that is a C function, and a delegate is an object Dart
/// cannot be; so, as with the widget reload shim, what Dart reaches is a
/// small `@objc` class compiled in here, messaged by name through the
/// Objective-C runtime.
///
/// What crosses is JSON. A drop calls the Dart function `start:` was given
/// with a `strdup`ed string Dart frees; a draggable widget tells the bridge
/// what it carries when the finger goes down (`setPending:`), because UIKit
/// starts the drag from its own long press and asks for the items then.
///
/// Drops work in Split View, Slide Over, Stage Manager and on an external
/// display, between this application and another, on iPad; on iPhone, iOS 15
/// and later let a drag go between applications too. Nothing is declared in
/// Info.plist for any of it.
library;

import 'package:dartvel_core/dartvel.dart' show dvIosDragDropClass;

import 'apple_widget_reload.dart' show dvApplePbxprojWithSwiftFile;

/// The file the bridge is written to, inside the `Runner` folder.
const String dvIosDragDropFileName = 'DartvelDragDrop.swift';

/// Its own prefix, so it is added and removed independently of the widget
/// shim.
const String dvIosDragDropIdPrefix = 'DA97D2D1D2D3';

/// The class selectors the Dart runtime sends.
const List<String> dvIosDragDropSelectors = <String>['start:', 'stop', 'setPending:'];

/// [pbxproj] with the bridge compiled into the application.
String dvIosPbxprojWithDragDrop(String pbxproj) => dvApplePbxprojWithSwiftFile(
      pbxproj,
      fileName: dvIosDragDropFileName,
      idPrefix: dvIosDragDropIdPrefix,
      include: true,
    );

String dvIosDragDropSource() => '''
// GENERATED by dartvel build. Do not edit: the next build writes it again.
//
// Drag and drop for DV.Platform.dragDrop: drops into the window from Files,
// Photos, Safari or any other application beside this one, and drags out of
// it, through UIDropInteraction and UIDragInteraction.

import Foundation
import UIKit
import UniformTypeIdentifiers

@objc($dvIosDragDropClass)
public final class DartvelDragDrop: NSObject, UIDropInteractionDelegate,
  UIDragInteractionDelegate
{
  private static let shared = DartvelDragDrop()

  private typealias Callback = @convention(c) (UnsafeMutablePointer<CChar>) -> Void
  private var callback: Callback?
  private var drop: UIDropInteraction?
  private var drag: UIDragInteraction?
  private var pending: [String: Any]?

  /// Starts taking drops; [pointer] is the Dart function each event goes to.
  @objc(start:)
  public static func start(_ pointer: UnsafeMutableRawPointer) {
    let callback = unsafeBitCast(pointer, to: Callback.self)
    onMain {
      shared.callback = callback
      guard let view = flutterView() else { return }
      if shared.drop == nil {
        let interaction = UIDropInteraction(delegate: shared)
        view.addInteraction(interaction)
        shared.drop = interaction
      }
      shared.installDrag(on: view)
    }
  }

  @objc(stop)
  public static func stop() {
    onMain {
      if let interaction = shared.drop {
        interaction.view?.removeInteraction(interaction)
      }
      shared.drop = nil
      shared.callback = nil
    }
  }

  /// What a drag starting now carries, as JSON, or nil for nothing.
  @objc(setPending:)
  public static func setPending(_ json: UnsafePointer<CChar>?) {
    var payload: [String: Any]? = nil
    if let json = json,
      let data = String(cString: json).data(using: .utf8),
      let decoded = try? JSONSerialization.jsonObject(with: data) as? [String: Any]
    {
      payload = decoded
    }
    onMain {
      shared.pending = payload
      if let view = flutterView() { shared.installDrag(on: view) }
    }
  }

  private func installDrag(on view: UIView) {
    if drag != nil { return }
    let interaction = UIDragInteraction(delegate: self)
    // Off by default on iPhone; a draggable widget asked for it.
    interaction.isEnabled = true
    view.addInteraction(interaction)
    drag = interaction
  }

  private static func onMain(_ work: @escaping () -> Void) {
    if Thread.isMainThread { work() } else { DispatchQueue.main.async(execute: work) }
  }

  /// The view Flutter draws into: the root view controller's view of the
  /// foreground scene's key window.
  private static func flutterView() -> UIView? {
    let scenes = UIApplication.shared.connectedScenes.compactMap { \$0 as? UIWindowScene }
    let windows = scenes.flatMap { \$0.windows }
    let window = windows.first { \$0.isKeyWindow } ?? windows.first
    return window?.rootViewController?.view
  }

  private func send(_ event: [String: Any]) {
    guard let callback = callback,
      let data = try? JSONSerialization.data(withJSONObject: event),
      let text = String(data: data, encoding: .utf8),
      let copy = strdup(text)
    else { return }
    // Dart frees it.
    callback(copy)
  }

  // MARK: Drops

  public func dropInteraction(
    _ interaction: UIDropInteraction, canHandle session: UIDropSession
  ) -> Bool {
    // Every drag: what the application takes is decided in Dart, by kind,
    // per widget.
    return true
  }

  public func dropInteraction(
    _ interaction: UIDropInteraction, sessionDidUpdate session: UIDropSession
  ) -> UIDropProposal {
    if let view = interaction.view {
      let point = session.location(in: view)
      send(["kind": "hover", "x": Double(point.x), "y": Double(point.y)])
    }
    return UIDropProposal(operation: .copy)
  }

  public func dropInteraction(
    _ interaction: UIDropInteraction, sessionDidExit session: UIDropSession
  ) {
    send(["kind": "leave"])
  }

  public func dropInteraction(
    _ interaction: UIDropInteraction, sessionDidEnd session: UIDropSession
  ) {
    send(["kind": "leave"])
  }

  public func dropInteraction(
    _ interaction: UIDropInteraction, performDrop session: UIDropSession
  ) {
    let point = interaction.view.map { session.location(in: \$0) } ?? .zero
    let folder = FileManager.default.temporaryDirectory
      .appendingPathComponent("dartvel-drops", isDirectory: true)
      .appendingPathComponent(UUID().uuidString, isDirectory: true)
    try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
    let group = DispatchGroup()
    let lock = NSLock()
    var items = [[String: Any]?](repeating: nil, count: session.items.count)
    for (index, item) in session.items.enumerated() {
      let provider = item.itemProvider
      group.enter()
      DartvelDragDrop.load(provider, into: folder) { entry in
        lock.lock()
        items[index] = entry
        lock.unlock()
        group.leave()
      }
    }
    group.notify(queue: .main) {
      self.send([
        "kind": "drop", "x": Double(point.x), "y": Double(point.y),
        "items": items.compactMap { \$0 },
      ])
    }
  }

  /// One dropped item: a web link, plain text, or a file copied into
  /// [folder] before the provider deletes its own copy.
  private static func load(
    _ provider: NSItemProvider, into folder: URL, done: @escaping ([String: Any]?) -> Void
  ) {
    let types = provider.registeredTypeIdentifiers
    let isFile = types.contains { type in
      type != "public.url" && type != "public.plain-text" && type != "public.utf8-plain-text"
        && type != "public.text"
    }
    if !isFile && provider.canLoadObject(ofClass: URL.self) {
      _ = provider.loadObject(ofClass: URL.self) { url, _ in
        guard let url = url else { return done(nil) }
        done(["url": url.absoluteString])
      }
      return
    }
    if !isFile && provider.canLoadObject(ofClass: String.self) {
      _ = provider.loadObject(ofClass: String.self) { text, _ in
        done(text.map { ["text": \$0] })
      }
      return
    }
    guard let type = types.first else { return done(nil) }
    provider.loadFileRepresentation(forTypeIdentifier: type) { url, _ in
      guard let url = url else { return done(nil) }
      let name = provider.suggestedName.map { suggested -> String in
        suggested.contains(".") || url.pathExtension.isEmpty
          ? suggested : suggested + "." + url.pathExtension
      } ?? url.lastPathComponent
      let target = folder.appendingPathComponent(name)
      do {
        try? FileManager.default.removeItem(at: target)
        try FileManager.default.copyItem(at: url, to: target)
      } catch {
        return done(nil)
      }
      var entry: [String: Any] = ["path": target.path, "name": name, "uti": type]
      if #available(iOS 14.0, *), let mime = UTType(type)?.preferredMIMEType {
        entry["mimeType"] = mime
      }
      if let size = try? FileManager.default.attributesOfItem(atPath: target.path)[.size] as? NSNumber {
        entry["size"] = size.intValue
      }
      done(entry)
    }
  }

  // MARK: Drags out

  public func dragInteraction(
    _ interaction: UIDragInteraction, itemsForBeginning session: UIDragSession
  ) -> [UIDragItem] {
    guard let payload = pending else { return [] }
    var items: [UIDragItem] = []
    var label: String? = nil
    if let text = payload["text"] as? String, !text.isEmpty {
      items.append(UIDragItem(itemProvider: NSItemProvider(object: text as NSString)))
      label = text
    }
    for case let link as String in (payload["urls"] as? [Any]) ?? [] {
      guard let url = URL(string: link) else { continue }
      items.append(UIDragItem(itemProvider: NSItemProvider(object: url as NSURL)))
      if label == nil { label = link }
    }
    for case let file as [String: Any] in (payload["files"] as? [Any]) ?? [] {
      guard let path = file["path"] as? String,
        let provider = NSItemProvider(contentsOf: URL(fileURLWithPath: path))
      else { continue }
      let name = (file["name"] as? String) ?? (path as NSString).lastPathComponent
      provider.suggestedName = name
      items.append(UIDragItem(itemProvider: provider))
      if label == nil { label = name }
    }
    let shown = label ?? ""
    for item in items {
      item.previewProvider = { UIDragPreview(view: DartvelDragDrop.badge(shown)) }
    }
    return items
  }

  public func dragInteraction(
    _ interaction: UIDragInteraction, previewForLifting item: UIDragItem,
    session: UIDragSession
  ) -> UITargetedDragPreview? {
    // A label, not a snapshot of the whole Flutter view, which is what the
    // default would lift.
    guard let view = interaction.view else { return nil }
    let text = (pending?["text"] as? String)
      ?? ((pending?["urls"] as? [Any])?.first as? String)
      ?? (((pending?["files"] as? [Any])?.first as? [String: Any])?["name"] as? String)
      ?? ""
    let target = UIDragPreviewTarget(container: view, center: session.location(in: view))
    return UITargetedDragPreview(
      view: DartvelDragDrop.badge(text), parameters: UIDragPreviewParameters(), target: target)
  }

  public func dragInteraction(
    _ interaction: UIDragInteraction, session: UIDragSession,
    didEndWith operation: UIDropOperation
  ) {
    pending = nil
  }

  private static func badge(_ text: String) -> UIView {
    let label = UILabel()
    label.text = "  " + text.replacingOccurrences(of: "\\n", with: " ") + "  "
    label.font = UIFont.preferredFont(forTextStyle: .subheadline)
    label.textColor = .white
    label.backgroundColor = UIColor(white: 0.13, alpha: 0.92)
    label.layer.cornerRadius = 8
    label.layer.masksToBounds = true
    label.lineBreakMode = .byTruncatingTail
    let size = label.sizeThatFits(CGSize(width: 260, height: 40))
    label.frame = CGRect(x: 0, y: 0, width: min(size.width, 260), height: 40)
    return label
  }
}
''';
