/// Where a link lands on iOS.
///
/// A generated home widget's tap is a `widgetURL` carrying the route the
/// widget was generated for. WidgetKit delivers it to the containing
/// application, and on iOS nothing in Dartvel was listening: the app opened
/// at its home route, which looks like it worked and is a shortcut rather
/// than a widget. Android had the same bug until `deepLinks.initial` landed
/// there.
///
/// The URL arrives at the app delegate, so this writes into
/// `AppDelegate.swift` -- a file the developer owns and the one place iOS
/// hands a launch to. That constrains what may be written: marked, so a
/// second build replaces rather than repeats; surgical, so nothing the
/// Flutter template already does is disturbed; and reversible, so a project
/// that stops asking for it gets its file back exactly as it was. A delegate
/// this cannot read is left alone rather than mangled -- the feature is four
/// lines somebody can add by hand, and their file is not.
library;

import 'package:dartvel_core/dartvel.dart' show dvIosLaunchUrlKey;

// The key is core's, because the other half of this -- the Flutter runtime
// reading the launch back through the Objective-C runtime -- is in another
// package, and two spellings of it is a launch captured and never read.
export 'package:dartvel_core/dartvel.dart' show dvIosLaunchUrlKey;

const String _markStart = '  // dartvel.deeplinks: begin';
const String _markEnd = '  // dartvel.deeplinks: end';

/// [source] with the launch capture in it, or without it.
String dvIosAppDelegate(String source, {required bool enabled}) {
  final RegExp block = RegExp(
      '${RegExp.escape(_markStart)}.*?${RegExp.escape(_markEnd)}\n',
      dotAll: true);
  final String stripped = source.replaceAll(block, '');
  if (!enabled) return stripped;

  // The class body, or nothing. Somebody who has rewritten their delegate
  // has a file this does not understand, and writing into it anyway trades
  // a missing feature for a build that does not compile.
  if (!stripped.contains('class AppDelegate')) return stripped;
  final int close = stripped.lastIndexOf('}');
  if (close < 0) return stripped;

  final StringBuffer out = StringBuffer()
    ..writeln(_markStart)
    ..writeln('  // GENERATED by dartvel build. Do not edit: the next build')
    ..writeln('  // writes it again.')
    ..writeln('  //')
    ..writeln('  // Two methods, because there are two launches. A cold')
    ..writeln('  // launch carries the URL in the launch options and never')
    ..writeln('  // reaches open(url:); a warm one arrives there and has no')
    ..writeln('  // launch options. An implementation with one of them works')
    ..writeln('  // in whichever case somebody happened to try.')
    ..writeln('  //')
    ..writeln('  // willFinishLaunching rather than didFinishLaunching: the')
    ..writeln('  // Flutter template overrides the second, and a class with')
    ..writeln('  // two overrides of one method does not compile.')
    ..writeln('  override func application(')
    ..writeln('    _ application: UIApplication,')
    ..writeln('    willFinishLaunchingWithOptions launchOptions:')
    ..writeln('      [UIApplication.LaunchOptionsKey: Any]? = nil')
    ..writeln('  ) -> Bool {')
    ..writeln('    if let url = launchOptions?[.url] as? URL {')
    ..writeln('      UserDefaults.standard.set(')
    ..writeln('        url.absoluteString, forKey: "$dvIosLaunchUrlKey")')
    ..writeln('    }')
    ..writeln('    return super.application(')
    ..writeln('      application, willFinishLaunchingWithOptions: launchOptions)')
    ..writeln('  }')
    ..writeln()
    ..writeln('  override func application(')
    ..writeln('    _ app: UIApplication,')
    ..writeln('    open url: URL,')
    ..writeln('    options: [UIApplication.OpenURLOptionsKey: Any] = [:]')
    ..writeln('  ) -> Bool {')
    ..writeln('    UserDefaults.standard.set(')
    ..writeln('      url.absoluteString, forKey: "$dvIosLaunchUrlKey")')
    // super, or every plugin registered for a URL stops seeing one.
    ..writeln('    return super.application(app, open: url, options: options)')
    ..writeln('  }')
    ..writeln(_markEnd);

  return '${stripped.substring(0, close)}${out.toString()}'
      '${stripped.substring(close)}';
}
