/// Asking the application which pages its models stand for.
library dartvel_cli.build.static_paths_runner;

import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

import '../commands/db_command.dart' show dvDatabaseSettings;
import '../utils/logger.dart';
import 'static_generation.dart';

/// The database a build resolves model pages against, and how the resolver
/// process is told about it.
class DVStaticPathsDatabase {
  const DVStaticPathsDatabase(
    this.description, {
    this.environment = const <String, String>{},
  });

  /// What it is, for a person reading the build log.
  final String description;

  /// Added to the resolver's environment. Empty for `DATABASE_URL`, which the
  /// resolver inherits as it is.
  final Map<String, String> environment;
}

/// The database the application's model pages are read from at build time:
/// `DATABASE_URL` when it is set, else the SQLite file `dartvel.database`
/// names when it exists. Null when there is neither.
///
/// Never a new empty file. Model pages resolved against a database nobody
/// wrote to are no pages, reported as success.
DVStaticPathsDatabase? dvStaticPathsDatabase(
  String root,
  Map<String, String> environment,
) {
  final String? url = environment['DATABASE_URL']?.trim();
  if (url != null && url.isNotEmpty) {
    return const DVStaticPathsDatabase('DATABASE_URL');
  }
  final ({String provider, String path}) settings = dvDatabaseSettings(root);
  if (settings.provider != 'sqlite') return null;
  final String file = p.isAbsolute(settings.path)
      ? settings.path
      : p.join(root, settings.path);
  if (!File(file).existsSync()) return null;
  return DVStaticPathsDatabase(
    p.relative(file, from: root),
    environment: <String, String>{'DARTVEL_STATIC_PATHS_SQLITE': file},
  );
}

/// The SQLite file `dartvel.database` names, for a message saying what to
/// create.
String _databaseHint(String root) => dvDatabaseSettings(root).path;

/// The entrypoint written into the project and run by `flutter test`.
///
/// It configures `DV.Database` first. It used to resolve with nothing
/// configured, so every `generatePublicPages` model failed with "DV.Database
/// has no configured adapter" whatever database the project had.
String dvStaticPathsEntrySource(String package) =>
    "// Generated by `dartvel build`: written, run and deleted.\n"
    "import 'dart:convert';\n"
    "import 'dart:io';\n"
    "\n"
    "import 'package:dartvel_core/dartvel.dart' show DVDatabaseConnection;\n"
    "import 'package:$package/dartvel_client/dartvel_client.dart';\n"
    "import 'package:flutter_test/flutter_test.dart';\n"
    "\n"
    "void main() {\n"
    "  test('resolve static paths', () async {\n"
    "  // The database the models live in: the SQLite file the build found,\n"
    "  // or DATABASE_URL. With neither, nothing is configured and a provider\n"
    "  // that needs one reports it.\n"
    "  final sqlite = Platform.environment['DARTVEL_STATIC_PATHS_SQLITE'];\n"
    "  final connection = DVDatabaseConnection.fromEnvironment(Platform.environment);\n"
    "  if (sqlite != null && sqlite.isNotEmpty) {\n"
    "    DV.Database.configure(SqliteDVDatabaseAdapter.file(sqlite));\n"
    "  } else if (connection != null) {\n"
    "    DV.Database.configure(connection.open());\n"
    "  }\n"
    "  final resolved = await resolveDartvelStaticPaths(\n"
    "    onError: (name, error) =>\n"
    "        print('DARTVEL_STATIC_PATHS_ERROR \$name: \$error'),\n"
    "  );\n"
    "  final entries = <Map<String, Object?>>[\n"
    "    for (final provider in dartvelStaticPaths)\n"
    "      <String, Object?>{\n"
    "        'route': provider.route,\n"
    "        'values': resolved[provider.name] ?? const <String>[],\n"
    "      },\n"
    "  ];\n"
    "  // One line on stdout, so the caller does not have to guess where the\n"
    "  // output ends among whatever the application logs while starting.\n"
    "  print('DARTVEL_STATIC_PATHS ' + jsonEncode(entries));\n"
    "  });\n"
    "}\n";

/// What the build log says about providers that did not resolve, from the
/// resolver's [stdout].
///
/// With no [database], the providers that failed for want of one are named
/// together in one line saying how to give them one -- rather than a
/// `Bad state` per model, which read as a crash. Anything else is said as
/// it is.
List<String> dvStaticPathsReport(
  String stdout, {
  required DVStaticPathsDatabase? database,
  required String databaseHint,
}) {
  const String prefix = 'DARTVEL_STATIC_PATHS_ERROR ';
  final List<String> lines = <String>[];
  final List<String> needDatabase = <String>[];
  for (final String line in stdout.split('\n')) {
    if (!line.startsWith(prefix)) continue;
    final String error = line.substring(prefix.length).trim();
    final int colon = error.indexOf(':');
    if (database == null &&
        colon > 0 &&
        error.contains('DV.Database has no configured adapter')) {
      needDatabase.add(error.substring(0, colon));
      continue;
    }
    lines.add(error);
  }
  if (needDatabase.isNotEmpty) {
    lines.insert(
      0,
      'Model pages not resolved (${needDatabase.join(', ')}): there is no '
      'database at build time. Set DATABASE_URL, or create $databaseHint with '
      'dartvel db migrate, to write them.',
    );
  }
  return lines;
}

/// Resolves the static paths for a root once per build.
///
/// Several build steps need the pages -- the service worker, the route
/// pages, the semantics capture -- and each ran the application's resolver
/// again, which is a `flutter test` compile each time and printed every
/// provider error once per step.
class DVStaticPathsCache {
  DVStaticPathsCache([this._resolve = dvResolveStaticPaths]);

  final Future<List<String>> Function(String root) _resolve;
  final Map<String, Future<List<String>>> _resolved =
      <String, Future<List<String>>>{};

  Future<List<String>> resolve(String root) =>
      _resolved.putIfAbsent(root, () => _resolve(root));
}

/// Resolve every static-path provider by running the application.
///
/// The paths are not knowable from source. `Post.publicStaticPaths()` reads
/// the database, and a custom resolver is arbitrary Dart -- so the only thing
/// that can answer is the application itself, with its own dependencies and
/// its own configuration.
///
/// A short entrypoint is written into the project, run, and removed. It prints
/// one line of JSON, which is the whole contract between the two processes.
///
/// Returns an empty list when there is no manifest, when the entrypoint fails,
/// or when nothing resolves. A build that cannot enumerate model pages should
/// still produce the pages it does know about rather than failing outright.
Future<List<String>> dvResolveStaticPaths(String root) async {
  final File manifest = File(
    p.join(root, 'lib', 'dartvel_client', 'static_paths.g.dart'),
  );
  if (!manifest.existsSync()) return const <String>[];

  // Under test/, and named _test.dart, because it is run by `flutter test`.
  //
  // Plain `dart run` cannot compile it: the client barrel reaches Flutter and
  // its FFI bindings, and the VM's FFI transformer crashes on them outside a
  // Flutter context -- "type 'InvalidType' is not a subtype of type
  // 'FunctionType'", which says nothing about the cause. flutter test compiles
  // Flutter code, which is the whole reason this is a test rather than a
  // script.
  final Directory temp = Directory(p.join(root, 'test', 'dartvel_generated'))
    ..createSync(recursive: true);
  final File entry =
      File(p.join(temp.path, 'resolve_static_paths_test.dart'));
  final String package = _packageName(root) ?? 'app';

  // Imported through the barrel rather than the generated file directly,
  // because that is the import application code is told to use and the one
  // that keeps working when the file moves.
  entry.writeAsStringSync(dvStaticPathsEntrySource(package));
  final DVStaticPathsDatabase? database =
      dvStaticPathsDatabase(root, Platform.environment);

  try {
    final ProcessResult result = await Process.run(
      'flutter',
      <String>['test', p.relative(entry.path, from: root), '--reporter',
          'expanded'],
      workingDirectory: root,
      runInShell: true,
      environment: database?.environment,
    );
    if (result.exitCode != 0) {
      // Said out loud. Silently generating fewer pages than the site has is
      // the kind of failure nobody notices until a page is missing.
      Logger.log('   Could not resolve model pages: the resolver exited '
          '${result.exitCode}.');
      final String error = '${result.stderr}'.trim();
      if (error.isNotEmpty) Logger.log('   ${error.split('\n').first}');
      return const <String>[];
    }

    // Providers that could not resolve, named. A model page usually needs the
    // database at build time, and a site quietly missing every one of those
    // pages is worse than a build that says which provider failed and why.
    for (final String line in dvStaticPathsReport('${result.stdout}',
        database: database, databaseHint: _databaseHint(root))) {
      Logger.log('   $line');
    }

    final String marker = '${result.stdout}'.split('\n').firstWhere(
          (String line) => line.startsWith('DARTVEL_STATIC_PATHS '),
          orElse: () => '',
        );
    if (marker.isEmpty) return const <String>[];

    final Object? decoded =
        jsonDecode(marker.substring('DARTVEL_STATIC_PATHS '.length));
    if (decoded is! List) return const <String>[];

    final Set<String> paths = <String>{};
    for (final Object? item in decoded) {
      if (item is Map) {
        paths.addAll(dvStaticPathsFor(item.cast<String, Object?>()));
      }
    }
    return paths.toList()..sort();
  } on ProcessException catch (error) {
    Logger.log('   Could not run the static-path resolver: ${error.message}');
    return const <String>[];
  } finally {
    if (entry.existsSync()) entry.deleteSync();
  }
}

String? _packageName(String root) {
  final File pubspec = File(p.join(root, 'pubspec.yaml'));
  if (!pubspec.existsSync()) return null;
  for (final String line in pubspec.readAsLinesSync()) {
    if (line.startsWith('name:')) return line.substring(5).trim();
  }
  return null;
}
