/// The Studio a web-server build carries, compiled.
///
/// The admin root used to hold a static manifest: the project graph as four
/// read-only tables. The Studio people actually use -- a model's records and
/// their edit form, the page builder, who holds a grant -- is Flutter, and
/// lived only in the admin pages the build leaves out of the client when the
/// backend serves the admin. So the build compiles `DVStudioApp` on its own,
/// as a second web application whose base is the mount, and puts it in the
/// admin root. The manifest stays beside it as `graph.json`, which Studio's
/// Routes, Functions and Jobs sections read.
///
/// It is one application for the whole project rather than one per target,
/// and it imports nothing of the application's own: what it knows about the
/// project it asks the backend, which knows the models it was generated with.
library;

import 'dart:io';

import 'package:path/path.dart' as p;

import 'server_binary.dart' show DVServerBinaryRun;

/// What compiling Studio did.
class DVStudioBuildResult {
  const DVStudioBuildResult({required this.ok, required this.lines});

  final bool ok;
  final List<String> lines;
}

/// The entry point Studio is compiled from.
String dvStudioEntrySource({required String appName}) => '''
// GENERATED by dartvel build -- the Studio this build serves at its admin
// mount. Not part of the application: it is compiled on its own into
// build/web/__admin, and reads everything it shows from the backend.
import 'package:dartvel_flutter/dartvel_flutter.dart';
import 'package:flutter/widgets.dart';

void main() {
  runApp(DVStudioApp(
    client: DVStudioClient(dvStudioBrowserTransport()),
    title: ${_dartString('Studio · $appName')},
  ));
}
''';

String _dartString(String value) =>
    "'${value.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

String _html(String value) => value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');

/// The shell Studio opens in.
///
/// Dartvel's own rather than the application's `web/index.html`, which is
/// the site's: its splash, its manifest, its analytics. The base is the
/// mount, so every file Studio asks for resolves under it.
String dvStudioIndexHtml({required String mount, required String appName}) =>
    '''
<!DOCTYPE html>
<html lang="en">
<head>
  <base href="${_html('$mount/')}">
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex, nofollow">
  <meta name="referrer" content="same-origin">
  <title>Studio · ${_html(appName)}</title>
  <style>html,body{margin:0;height:100%;background:#F3F3F7}</style>
</head>
<body>
  <script src="flutter_bootstrap.js" async></script>
</body>
</html>
''';

/// Compiles Studio for [mount] and makes [adminRoot] that Studio.
///
/// [adminRoot] already holds the manifest step's files. `graph.json` is kept;
/// the static page that read it is replaced. A compile that fails leaves the
/// root as it was and fails the build: a binary that quietly carried the
/// read-only manifest instead of Studio is the thing being fixed.
Future<DVStudioBuildResult> dvBuildStudio({
  required String root,
  required String mount,
  required String adminRoot,
  required String appName,
  required DVServerBinaryRun run,
  String flutter = 'flutter',
}) async {
  final File entry = File(p.join(root, '.dart_tool', 'dartvel_studio_main.dart'))
    ..createSync(recursive: true)
    ..writeAsStringSync(dvStudioEntrySource(appName: appName));
  final Directory output = Directory(p.join(root, 'build', 'dartvel_studio'));
  if (output.existsSync()) output.deleteSync(recursive: true);

  final ProcessResult result = await run(
    flutter,
    <String>[
      'build',
      'web',
      '-t',
      entry.path,
      '--release',
      '--base-href',
      '$mount/',
      // Served by a backend that may have no route to the internet, so the
      // renderer is carried rather than fetched from gstatic.
      '--no-web-resources-cdn',
      '--no-wasm-dry-run',
      '-o',
      output.path,
    ],
    workingDirectory: root,
  );
  if (result.exitCode != 0) {
    return DVStudioBuildResult(ok: false, lines: <String>[
      'Compiling Studio (flutter build web) exited ${result.exitCode}:',
      ...'${result.stdout}\n${result.stderr}'
          .split('\n')
          .where((String line) => line.trim().isNotEmpty),
    ]);
  }
  if (!File(p.join(output.path, 'main.dart.js')).existsSync()) {
    return DVStudioBuildResult(ok: false, lines: <String>[
      'Compiling Studio wrote no main.dart.js to ${output.path}.',
    ]);
  }

  final Directory admin = Directory(adminRoot)..createSync(recursive: true);
  // Only the static page goes. graph.json is what the Routes, Functions and
  // Jobs sections read.
  for (final String stale in <String>['index.html', 'admin.css', 'admin.js']) {
    final File file = File(p.join(admin.path, stale));
    if (file.existsSync()) file.deleteSync();
  }
  int files = 0;
  for (final FileSystemEntity entity
      in output.listSync(recursive: true, followLinks: false)) {
    if (entity is! File) continue;
    final String relative = p.relative(entity.path, from: output.path);
    final File target = File(p.join(admin.path, relative));
    target.parent.createSync(recursive: true);
    entity.copySync(target.path);
    files += 1;
  }
  File(p.join(admin.path, 'index.html'))
      .writeAsStringSync(dvStudioIndexHtml(mount: mount, appName: appName));
  output.deleteSync(recursive: true);

  return DVStudioBuildResult(ok: true, lines: <String>[
    'Studio compiled for $mount ($files files).',
  ]);
}
