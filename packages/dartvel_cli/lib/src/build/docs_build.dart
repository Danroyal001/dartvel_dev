/// The documentation site a build carries, compiled.
///
/// `dartvel docs` writes `docs.json` and `graph.json`; the application that draws
/// them is `DVDocsApp` from `dartvel_flutter`. This compiles it on its own, as a
/// second web application whose base is the mount, and puts it in the docs root.
/// The payload stays beside it as `docs.json`, which the app reads at startup.
///
/// It is one application for the whole project rather than one per target, and
/// it imports nothing of the application's own: what it knows about the project
/// it reads from the document the build wrote.
library;

import 'dart:io';

import 'package:path/path.dart' as p;

import 'server_binary.dart' show DVServerBinaryRun;

/// What compiling the docs site did.
class DVDocsBuildResult {
  const DVDocsBuildResult({required this.ok, required this.lines});

  final bool ok;
  final List<String> lines;
}

/// The entry point the docs site is compiled from.
String dvDocsEntrySource({required String appName, required String base}) => '''
// GENERATED by dartvel build -- the documentation site this build serves at its
// docs mount. Not part of the application: it is compiled on its own into
// build/web/__docs, and reads everything it shows from docs.json beside it.
import 'package:dartvel_flutter/dartvel_flutter.dart';
import 'package:flutter/widgets.dart';

void main() {
  runApp(DVDocsApp(
    source: dvDocsBrowserSource(base: ${_dartString(base)}),
    title: ${_dartString('Documentation · $appName')},
    base: ${_dartString(base)},
  ));
}
''';

String _dartString(String value) =>
    "'${value.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

String _html(String value) => value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');

/// The shell the docs site opens in.
///
/// Dartvel's own rather than the application's `web/index.html`, which is the
/// site's: its splash, its manifest, its analytics. The base is the mount, so
/// every file the docs site asks for resolves under it.
String dvDocsIndexHtml({required String mount, required String appName}) => '''
<!DOCTYPE html>
<html lang="en">
<head>
  <base href="${_html('$mount/')}">
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex, nofollow">
  <meta name="referrer" content="same-origin">
  <title>Documentation · ${_html(appName)}</title>
  <meta name="color-scheme" content="light dark">
  <style>html,body{margin:0;height:100%;background:#F3F3F7}@media (prefers-color-scheme: dark){html,body{background:#111116}}</style>
</head>
<body>
  <script src="flutter_bootstrap.js" async></script>
</body>
</html>
''';

/// Compiles the documentation site for [mount] and makes [docsRoot] that site.
///
/// [docsRoot] already holds `docs.json` and `graph.json` from `dvDocsBuildInto`.
/// A compile that fails leaves the root as it was and fails the build: a site
/// that quietly carried only the payload instead of the app is the thing being
/// fixed.
Future<DVDocsBuildResult> dvBuildDocs({
  required String root,
  required String mount,
  required String docsRoot,
  required String appName,
  required DVServerBinaryRun run,
  String flutter = 'flutter',
}) async {
  final File entry = File(p.join(root, '.dart_tool', 'dartvel_docs_main.dart'))
    ..createSync(recursive: true)
    ..writeAsStringSync(dvDocsEntrySource(appName: appName, base: mount));
  final Directory output = Directory(p.join(root, 'build', 'dartvel_docs'));
  if (output.existsSync()) output.deleteSync(recursive: true);

  final ProcessResult result = await run(
    flutter,
    <String>[
      'build',
      'web',
      '-t',
      entry.path,
      '--release',
      '--base-href',
      '$mount/',
      // Served by a backend that may have no route to the internet, so the
      // renderer is carried rather than fetched from gstatic.
      '--no-web-resources-cdn',
      '--no-wasm-dry-run',
      '-o',
      output.path,
    ],
    workingDirectory: root,
  );
  if (result.exitCode != 0) {
    return DVDocsBuildResult(ok: false, lines: <String>[
      'Compiling documentation site (flutter build web) exited ${result.exitCode}:',
      ...'${result.stdout}\n${result.stderr}'
          .split('\n')
          .where((String line) => line.trim().isNotEmpty),
    ]);
  }
  if (!File(p.join(output.path, 'main.dart.js')).existsSync()) {
    return DVDocsBuildResult(ok: false, lines: <String>[
      'Compiling documentation site wrote no main.dart.js to ${output.path}.',
    ]);
  }

  final Directory docs = Directory(docsRoot)..createSync(recursive: true);
  int files = 0;
  for (final FileSystemEntity entity
      in output.listSync(recursive: true, followLinks: false)) {
    if (entity is! File) continue;
    final String relative = p.relative(entity.path, from: output.path);
    final File target = File(p.join(docs.path, relative));
    target.parent.createSync(recursive: true);
    entity.copySync(target.path);
    files += 1;
  }
  File(p.join(docs.path, 'index.html'))
      .writeAsStringSync(dvDocsIndexHtml(mount: mount, appName: appName));
  output.deleteSync(recursive: true);

  return DVDocsBuildResult(ok: true, lines: <String>[
    'Documentation site compiled for $mount ($files files).',
  ]);
}