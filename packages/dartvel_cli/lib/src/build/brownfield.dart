/// `dartvel build <target> --brownfield`: the project built as the artifact
/// an existing native application embeds.
///
/// Flutter's add-to-app already runs a Flutter module inside an Android, iOS
/// or macOS host, and Dartvel extends it rather than reimplementing it: the
/// build hands the work to Flutter's own `build aar`, `build ios-framework`
/// and `build macos-framework`, and adds what a Dartvel project needs on top
/// -- an entry point per project that boots the Dartvel runtime as an
/// embedded entry (no single-instance lock, no argv; the host owns the
/// process), and a staged module for the one command that only builds
/// modules.
library;

import 'dart:io';

import 'package:path/path.dart' as p;

/// Where the brownfield entry is written, relative to the project root.
const String dvBrownfieldEntryPath = 'lib/dartvel_client/brownfield.g.dart';

/// The Dart entry point a host starts an engine at for [package]:
/// `dartvelEmbeddedEntry_<project>`, the name the spec gives it.
///
/// With several projects in one host on an engine group, each engine is
/// started at its own project's entry point; one project alone can also be
/// started at `main`, which runs the same entry.
String dvBrownfieldEntryName(String package) => 'dartvelEmbeddedEntry_$package';

/// The source of the brownfield entry for [package].
///
/// `main` is the embedded entry too: a host that starts the default entry
/// point (Android's FlutterActivity, iOS's FlutterViewController with no
/// entry named) gets the project as an embedded entry, never the desktop
/// launch negotiation that would take a single-instance lock in someone
/// else's process.
String dvBrownfieldEntrySource(String package) => '''
// GENERATED by dartvel build --brownfield – do not edit.
//
// The entry points a native host starts this project at. Both boot the
// Dartvel runtime as DVEntry.embedded('$package').
import 'package:$package/dartvel_client/application.g.dart';

void main() => dartvelRunEmbedded('$package');

@pragma('vm:entry-point')
void ${dvBrownfieldEntryName(package)}() => dartvelRunEmbedded('$package');
''';

/// A target with no brownfield build yet, or none possible.
class DVBrownfieldRefusal implements Exception {
  DVBrownfieldRefusal(this.message);

  final String message;

  @override
  String toString() => message;
}

/// What `--brownfield` runs for one target.
class DVBrownfieldPlan {
  DVBrownfieldPlan({
    required this.platform,
    required this.flutterArguments,
    required this.output,
    this.stagesModule = false,
    this.needsMacHost = false,
  });

  final String platform;

  /// The `flutter` arguments, run in the project (or the staged module).
  final List<String> flutterArguments;

  /// Where the host-ready artifact ends up, relative to the project root.
  final String output;

  /// Whether the build runs in a staged module rather than the project:
  /// `flutter build aar` builds only a module, and only its lib/main.dart.
  final bool stagesModule;

  /// Apple frameworks are built by Xcode, so only on a Mac.
  final bool needsMacHost;
}

/// The three build modes Flutter's framework commands take as negatable
/// flags, with only [buildMode] on: a release build does not also spend
/// minutes on a debug and a profile one nobody asked for.
List<String> _onlyMode(String buildMode) {
  final String mode = buildMode.replaceFirst(RegExp(r'^--'), '');
  return <String>[
    for (final String each in <String>['debug', 'profile', 'release'])
      each == mode ? '--$each' : '--no-$each',
  ];
}

/// Plans `dartvel build <platform> --brownfield` for [package].
///
/// [buildMode] is `--release`, `--profile` or `--debug`. Throws
/// [DVBrownfieldRefusal] for a target with no brownfield build, rather than
/// quietly building an ordinary app the host cannot embed.
DVBrownfieldPlan dvBrownfieldPlan({
  required String platform,
  required String package,
  required String buildMode,
}) {
  final List<String> modes = _onlyMode(buildMode);
  final String output = p.join('build', 'brownfield', platform);
  switch (platform) {
    case 'android':
      // No --target: Flutter compiles the module's lib/main.dart and cannot
      // be told otherwise, so the staged module's main.dart is the entry.
      final List<String> ordered = <String>[
        modes.firstWhere((String m) => m.endsWith('debug')),
        modes.firstWhere((String m) => m.endsWith('profile')),
        modes.firstWhere((String m) => m.endsWith('release')),
      ];
      return DVBrownfieldPlan(
        platform: platform,
        flutterArguments: <String>['build', 'aar', ...ordered],
        output: output,
        stagesModule: true,
      );
    case 'ios':
    case 'macos':
      return DVBrownfieldPlan(
        platform: platform,
        flutterArguments: <String>[
          'build',
          '$platform-framework',
          '--target',
          dvBrownfieldEntryPath,
          ...modes,
          '--output',
          output,
        ],
        output: output,
        stagesModule: true,
        needsMacHost: true,
      );
    case 'web':
      throw DVBrownfieldRefusal(
        'dartvel build web --brownfield is not built yet. The web host '
        'uses Flutter\'s multi-view embedding, which needs the router kept '
        'off the host page\'s address bar first. Android, iOS and macOS '
        'build today.',
      );
    case 'linux':
    case 'windows':
      throw DVBrownfieldRefusal(
        'dartvel build $platform --brownfield is not built yet. Flutter\'s '
        'add-to-app covers Android, iOS, macOS and the web; a $platform host '
        'needs the desktop embedder API, which comes after the web. '
        'Android, iOS and macOS build today.',
      );
    default:
      throw DVBrownfieldRefusal(
        'dartvel build $platform --brownfield: $platform has no embedder API '
        'a host application can start an engine through (DV-BROWNFIELD-003).',
      );
  }
}

/// Top-level entries of a project that a staged module does not take: the
/// project's own native folders (a module has ephemeral .android and .ios
/// hosts of its own), build output, and what pub writes.
const Set<String> _notStaged = <String>{
  'pubspec.yaml', 'pubspec.lock', 'lib', 'build', '.dart_tool', 'android',
  'ios', 'macos', 'linux', 'windows', 'web', '.android', '.ios', '.git',
  '.idea', '.packages', '.flutter-plugins', '.flutter-plugins-dependencies',
};

/// Stages [root] as a Flutter module under build/brownfield/module and
/// returns it.
///
/// The module keeps the package name, so every `package:` import resolves as
/// it does in the project; its lib/main.dart is the brownfield entry and the
/// rest of lib, the assets and anything else at the top are links to the
/// project's own files. The project itself is never changed.
Directory dvStageBrownfieldModule({required String root, required String package}) {
  final Directory module = Directory(p.join(root, 'build', 'brownfield', 'module'));
  if (module.existsSync()) module.deleteSync(recursive: true);
  Directory(p.join(module.path, 'lib')).createSync(recursive: true);

  final String pubspec = File(p.join(root, 'pubspec.yaml')).readAsStringSync();
  File(p.join(module.path, 'pubspec.yaml'))
      .writeAsStringSync(_modulePubspec(pubspec, root: root, package: package));
  final File lock = File(p.join(root, 'pubspec.lock'));
  if (lock.existsSync()) lock.copySync(p.join(module.path, 'pubspec.lock'));

  for (final FileSystemEntity entry in Directory(root).listSync(followLinks: false)) {
    final String name = p.basename(entry.path);
    if (_notStaged.contains(name)) continue;
    // A file is copied and a directory linked: Flutter commands run in the
    // module rewrite files such as analysis_options.yaml in place, and
    // through a link that would change the project, which staging promises
    // never to do.
    if (entry is File) {
      entry.copySync(p.join(module.path, name));
    } else {
      Link(p.join(module.path, name)).createSync(p.absolute(entry.path));
    }
  }
  final Directory lib = Directory(p.join(root, 'lib'));
  if (lib.existsSync()) {
    for (final FileSystemEntity entry in lib.listSync(followLinks: false)) {
      final String name = p.basename(entry.path);
      if (name == 'main.dart') continue;
      Link(p.join(module.path, 'lib', name)).createSync(p.absolute(entry.path));
    }
  }
  File(p.join(module.path, 'lib', 'main.dart'))
      .writeAsStringSync(dvBrownfieldEntrySource(package));
  return module;
}

/// The project's pubspec as a module's: `path:` dependencies made absolute,
/// since the module sits three folders down, and a `module:` section under
/// `flutter:` with the identifiers Flutter needs for the host artifacts.
String _modulePubspec(String pubspec, {required String root, required String package}) {
  final String identifier = 'dev.dartvel.brownfield.$package';
  final List<String> lines = <String>[];
  bool sawFlutterSection = false;
  for (final String line in pubspec.split('\n')) {
    final RegExpMatch? path = RegExp(r'^(\s+path:\s*)(\S.*?)\s*$').firstMatch(line);
    if (path != null && !p.isAbsolute(path.group(2)!)) {
      lines.add('${path.group(1)}${p.normalize(p.join(p.absolute(root), path.group(2)!))}');
      continue;
    }
    lines.add(line);
    if (line == 'flutter:') {
      sawFlutterSection = true;
      lines
        ..add('  module:')
        ..add('    androidX: true')
        ..add('    androidPackage: $identifier')
        ..add('    iosBundleIdentifier: $identifier');
    }
  }
  if (!sawFlutterSection) {
    if (lines.isNotEmpty && lines.last.isNotEmpty) lines.add('');
    lines
      ..add('flutter:')
      ..add('  module:')
      ..add('    androidX: true')
      ..add('    androidPackage: $identifier')
      ..add('    iosBundleIdentifier: $identifier');
  }
  return lines.join('\n');
}

/// Runs `executable` with `arguments` in `directory` and returns its exit
/// code, streaming its output to the person waiting.
typedef DVBrownfieldRunner = Future<int> Function(
    String executable, List<String> arguments, String directory);

/// The package name in [root]'s pubspec.yaml.
String _packageName(String root) {
  final RegExpMatch? name = RegExp(r'^name:\s*([A-Za-z_][A-Za-z0-9_]*)\s*$', multiLine: true)
      .firstMatch(File(p.join(root, 'pubspec.yaml')).readAsStringSync());
  if (name == null) throw StateError('pubspec.yaml in $root has no name');
  return name.group(1)!;
}

/// Builds [platform] as a brownfield artifact after the client has been
/// generated, returning the exit code: 0 built, 69 refused, else Flutter's.
///
/// The host-ready artifact is moved out of the staged module to
/// build/brownfield/<platform>, beside a HOST.md saying how a host adds it
/// and which entry point to start.
Future<int> dvRunBrownfieldBuild({
  required String root,
  required String platform,
  required String buildMode,
  required DVBrownfieldRunner run,
  required void Function(String) log,
}) async {
  final String package = _packageName(root);
  final DVBrownfieldPlan plan;
  try {
    plan = dvBrownfieldPlan(platform: platform, package: package, buildMode: buildMode);
  } on DVBrownfieldRefusal catch (refusal) {
    log('❌ ${refusal.message}');
    return 69; // EX_UNAVAILABLE
  }
  final String? hostProblem = dvBrownfieldHostProblem(plan);
  if (hostProblem != null) {
    log('❌ $hostProblem');
    return 69;
  }
  final Directory module = dvStageBrownfieldModule(root: root, package: package);
  log('📦 Staged $package as a Flutter module for $platform add-to-app.');
  final int resolved = await run('flutter', <String>['pub', 'get'], module.path);
  if (resolved != 0) return resolved;
  final int built = await run('flutter', plan.flutterArguments, module.path);
  if (built != 0) return built;

  final Directory out = Directory(p.join(root, plan.output));
  if (out.existsSync()) out.deleteSync(recursive: true);
  out.createSync(recursive: true);
  final Directory produced = platform == 'android'
      ? Directory(p.join(module.path, 'build', 'host', 'outputs', 'repo'))
      : Directory(p.join(module.path, plan.output));
  if (!produced.existsSync()) {
    log('❌ Flutter reported success and wrote nothing at ${produced.path}.');
    return 1;
  }
  produced.renameSync(platform == 'android' ? p.join(out.path, 'repo') : p.join(out.path, 'frameworks'));
  File(p.join(out.path, 'HOST.md')).writeAsStringSync(dvBrownfieldHostNotes(plan, package));
  log('✅ ${plan.output}: add it to the host as HOST.md there says.');
  return 0;
}

/// Why this machine cannot build [plan], or null when it can.
String? dvBrownfieldHostProblem(DVBrownfieldPlan plan) =>
    plan.needsMacHost && !Platform.isMacOS
        ? 'dartvel build ${plan.platform} --brownfield builds Apple frameworks '
            'with Xcode, which needs a Mac. Run it there or with --cloud.'
        : null;

/// How a host adds the artifact and starts the project, per platform.
String dvBrownfieldHostNotes(DVBrownfieldPlan plan, String package) {
  final String entry = dvBrownfieldEntryName(package);
  final String identifier = 'dev.dartvel.brownfield.$package';
  final String body = switch (plan.platform) {
    'android' => '''
In the host's settings.gradle(.kts), add the repository in `repo/` and
Flutter's engine repository:

    maven { url = uri("<path to>/build/brownfield/android/repo") }
    maven { url = uri("https://storage.googleapis.com/download.flutter.io") }

and depend on the module in the app's build.gradle(.kts):

    releaseImplementation("$identifier:flutter_release:1.0")

Start the project at its own entry point, so several projects can share an
engine group:

    val engine = FlutterEngineGroup(context).createAndRunEngine(
        context,
        DartExecutor.DartEntrypoint(
            FlutterInjector.instance().flutterLoader().findAppBundlePath(),
            "$entry"))

A FlutterActivity or FlutterFragment with no entry point named runs `main`,
which starts the same embedded entry.''',
    _ => '''
`frameworks/` holds the XCFrameworks: App, Flutter (or FlutterMacOS) and the
plugins. Embed and sign them in the host target, then start the project at
its own entry point:

    let engine = FlutterEngine(name: "$package")
    engine.run(withEntrypoint: "$entry")''',
  };
  return '''
# $package, embedded in a native host

Built by `dartvel build ${plan.platform} --brownfield` through Flutter's
add-to-app. The entry point is `$entry`; it boots the Dartvel runtime as an
embedded entry, so the host keeps its process, its window and its back stack.

$body
''';
}

/// Why `dartvel build <platform> --brownfield` cannot run here, checked
/// before any generation (a build that cannot finish is never started), or
/// null when it can.
String? dvBrownfieldPreflight({required String root, required String platform}) {
  try {
    return dvBrownfieldHostProblem(
        dvBrownfieldPlan(platform: platform, package: _packageName(root), buildMode: '--release'));
  } on DVBrownfieldRefusal catch (refusal) {
    return refusal.message;
  }
}
