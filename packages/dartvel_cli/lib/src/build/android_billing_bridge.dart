/// Google Play Billing for `DV.Purchases`, as Java the build writes into the
/// generated Android project.
///
/// Play Billing is a Java library made of builders, listener interfaces and a
/// service connection, and every answer comes back on a callback. Reaching
/// each of those from Dart through jnigen means implementing Java interfaces
/// from Dart and receiving calls on whatever thread Play picks, which is the
/// part of JNI hardest to get right and hardest to see going wrong. So the
/// work is done here, in Java that `javac` checks when Gradle builds, and
/// Dart reaches it through three static methods: `start` an operation,
/// `poll` for its answer, and `drainUpdates` for purchases that finished
/// outside one (a pending payment completing, a purchase on another device).
/// That is the shape the capture bridge already uses, for the same reason.
///
/// Nothing here grants anything. The bridge never acknowledges a purchase:
/// the server does, after Google's own API has confirmed it, because a
/// purchase acknowledged on the device is one Play will not refund even when
/// the server refuses its receipt. It does consume a consumable, once the
/// server has accepted it, because Play will not sell the same consumable
/// again until it is consumed.
///
/// Written only when `pubspec.yaml` declares `dartvel.purchases`. An
/// application that sells nothing gets no billing library, and so no
/// `com.android.vending.BILLING` permission on its store listing -- the
/// library's manifest adds it.
library dartvel_cli.build.android_billing_bridge;

import 'package:dartvel_core/dartvel.dart'
    show dvAndroidBillingBridgeClass, dvAndroidBillingLibrary;

/// Where the bridge is written, relative to the project root.
const String dvAndroidBillingBridgePath =
    'android/app/src/main/java/$dvAndroidBillingBridgeClass.java';

/// Whether [dartvelSection] (the pubspec's `dartvel:` map) declares
/// purchases: a map of settings, or `true`.
bool dvPurchasesDeclared(Object? dartvelSection) {
  if (dartvelSection is! Map) return false;
  final Object? purchases = dartvelSection['purchases'];
  return purchases is Map || purchases == true;
}

const String _gradleStart = '// dartvel.purchases: start';
const String _gradleEnd = '// dartvel.purchases: end';

/// [gradle] (the app module's build script) with the Play Billing dependency
/// when [include], and without it otherwise.
///
/// A marked block of its own at the end of the file rather than a line
/// spliced into an existing `dependencies` block: Gradle merges any number
/// of them, Flutter's template has none to splice into, and a block of its
/// own is one a later build can find and take back out exactly. Rewritten
/// rather than appended, so a second build does not declare the library
/// twice.
String dvAndroidGradleWithBilling(
  String gradle, {
  required bool include,
  required bool kotlinScript,
}) {
  final String stripped = _stripGradle(gradle);
  if (!include) return stripped;
  final String dependency = kotlinScript
      ? 'implementation("$dvAndroidBillingLibrary")'
      : 'implementation "$dvAndroidBillingLibrary"';
  final String separator = stripped.endsWith('\n') ? '' : '\n';
  return '$stripped$separator'
      '\n$_gradleStart\n'
      '// Google Play Billing, for DV.Purchases. Written by dartvel build from\n'
      '// dartvel.purchases in pubspec.yaml; removed when that is.\n'
      'dependencies {\n'
      '    $dependency\n'
      '}\n'
      '$_gradleEnd\n';
}

String _stripGradle(String gradle) {
  final int start = gradle.indexOf(_gradleStart);
  if (start < 0) return gradle;
  final int end = gradle.indexOf(_gradleEnd, start);
  if (end < 0) return gradle;
  int cut = start;
  // The blank line written in front of the block goes with it.
  if (cut >= 2 && gradle.substring(cut - 2, cut) == '\n\n') cut -= 1;
  int after = end + _gradleEnd.length;
  if (after < gradle.length && gradle[after] == '\n') after += 1;
  return gradle.substring(0, cut) + gradle.substring(after);
}

/// The bridge, as Java.
String dvAndroidBillingBridgeSource() => r'''
// GENERATED by dartvel build from dartvel.purchases. Do not edit: the next
// build writes it again.
//
// Google Play Billing for DV.Purchases, reached from Dart over JNI. Dart
// starts an operation, polls for its answer, and drains the purchases that
// arrived outside one. Every answer is a JSON object; a failure is
// {"error": "..."} rather than an exception thrown across JNI.
package dev.dartvel.jni;

import android.app.Activity;
import android.content.Context;
import android.os.Handler;
import android.os.Looper;

import com.android.billingclient.api.BillingClient;
import com.android.billingclient.api.BillingClientStateListener;
import com.android.billingclient.api.BillingFlowParams;
import com.android.billingclient.api.BillingResult;
import com.android.billingclient.api.ConsumeParams;
import com.android.billingclient.api.PendingPurchasesParams;
import com.android.billingclient.api.ProductDetails;
import com.android.billingclient.api.Purchase;
import com.android.billingclient.api.PurchasesUpdatedListener;
import com.android.billingclient.api.QueryProductDetailsParams;
import com.android.billingclient.api.QueryProductDetailsResult;
import com.android.billingclient.api.QueryPurchasesParams;

import org.json.JSONArray;
import org.json.JSONException;
import org.json.JSONObject;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ConcurrentLinkedQueue;
import java.util.concurrent.atomic.AtomicLong;

public final class DartvelBilling {
  private DartvelBilling() {}

  /// Answers waiting to be polled, by request id.
  private static final Map<String, String> answers = new ConcurrentHashMap<>();

  /// Purchases that arrived with no purchase call waiting for them.
  private static final ConcurrentLinkedQueue<JSONObject> updates =
      new ConcurrentLinkedQueue<>();

  private static final AtomicLong nextId = new AtomicLong();

  /// Every call goes through the main thread. launchBillingFlow must, the
  /// listeners are delivered there, and Flutter's Dart thread is not always
  /// it.
  private static final Handler main = new Handler(Looper.getMainLooper());

  /// Product details by product id, from the last listing. A purchase needs
  /// the ProductDetails object itself, not only its id.
  private static final Map<String, ProductDetails> details =
      new ConcurrentHashMap<>();

  /// "subs" or "inapp" by product id, so a purchase's receipt can say which
  /// it was: Play's Purchase does not.
  private static final Map<String, String> types = new ConcurrentHashMap<>();

  private static BillingClient client;
  private static boolean connecting;
  private static final List<Runnable> whenConnected = new ArrayList<>();
  private static final List<String> failWhenRefused = new ArrayList<>();

  /// The purchase call waiting on PurchasesUpdatedListener, and its product.
  private static String purchaseRequest;
  private static String purchaseProduct;

  /// Starts [request] (a JSON object with an "op") and answers its id.
  public static String start(String request) {
    final String id = Long.toString(nextId.incrementAndGet());
    main.post(() -> {
      try {
        dispatch(id, new JSONObject(request));
      } catch (Throwable error) {
        fail(id, "the request could not be handled: " + error);
      }
    });
    return id;
  }

  /// The answer to request [id], or null while it is still running.
  public static String poll(String id) {
    return answers.remove(id);
  }

  /// Every purchase that arrived outside a purchase call since the last
  /// drain, as a JSON array of transactions.
  public static String drainUpdates() {
    final JSONArray out = new JSONArray();
    JSONObject next;
    while ((next = updates.poll()) != null) out.put(next);
    return out.toString();
  }

  private static void dispatch(String id, JSONObject request)
      throws JSONException {
    switch (request.getString("op")) {
      case "available":
        connected(id, () -> answer(id, object("available", true)));
        break;
      case "listings":
        listings(id, request.getJSONArray("ids"));
        break;
      case "purchase":
        purchase(id, request);
        break;
      case "owned":
        owned(id);
        break;
      case "finish":
        finish(id, request);
        break;
      default:
        fail(id, "unknown operation " + request.getString("op"));
    }
  }

  // -- the connection ---------------------------------------------------------

  private static BillingClient client() {
    if (client != null) return client;
    final Context context = DartvelContext.context();
    if (context == null) return null;
    client = BillingClient.newBuilder(context)
        .setListener(listener)
        // Pending payments (cash, slow bank transfers) for one-time
        // products and prepaid plans. Without it Play refuses to show them.
        .enablePendingPurchases(PendingPurchasesParams.newBuilder()
            .enableOneTimeProducts()
            .enablePrepaidPlans()
            .build())
        // Reconnects on its own after the Play Store process restarts,
        // rather than every call after that failing with
        // SERVICE_DISCONNECTED.
        .enableAutoServiceReconnection()
        .build();
    return client;
  }

  /// Runs [then] once connected, or answers [id] with why not.
  private static void connected(String id, Runnable then) {
    final BillingClient billing = client();
    if (billing == null) {
      fail(id, "there is no application Context yet");
      return;
    }
    if (billing.isReady()) {
      then.run();
      return;
    }
    whenConnected.add(then);
    failWhenRefused.add(id);
    if (connecting) return;
    connecting = true;
    billing.startConnection(new BillingClientStateListener() {
      @Override
      public void onBillingSetupFinished(BillingResult result) {
        main.post(() -> {
          connecting = false;
          final List<Runnable> ready = new ArrayList<>(whenConnected);
          final List<String> waiting = new ArrayList<>(failWhenRefused);
          whenConnected.clear();
          failWhenRefused.clear();
          if (result.getResponseCode() == BillingClient.BillingResponseCode.OK) {
            for (Runnable run : ready) run.run();
          } else {
            for (String waiter : waiting) {
              answer(waiter, unavailable(result));
            }
          }
        });
      }

      @Override
      public void onBillingServiceDisconnected() {
        // enableAutoServiceReconnection reconnects on the next call.
        main.post(() -> connecting = false);
      }
    });
  }

  private static JSONObject unavailable(BillingResult result) {
    final JSONObject out = new JSONObject();
    try {
      out.put("available", false);
      out.put("error", "Play Billing is unavailable (" + result.getResponseCode()
          + ": " + result.getDebugMessage() + ")");
    } catch (JSONException ignored) {
      // put never throws for a String key and a String or boolean value.
    }
    return out;
  }

  // -- listings ---------------------------------------------------------------

  private static void listings(String id, JSONArray ids) {
    connected(id, () -> {
      final JSONArray out = new JSONArray();
      final List<String> wanted = new ArrayList<>();
      for (int i = 0; i < ids.length(); i++) wanted.add(ids.optString(i));
      if (wanted.isEmpty()) {
        answerListings(id, out);
        return;
      }
      // Asked as both kinds, because the Dart side declares products by id
      // and Play answers a query only for the type it was asked about. A
      // product listed under the wrong type is simply absent from that
      // answer.
      query(wanted, BillingClient.ProductType.SUBS, (subs) -> {
        for (ProductDetails product : subs) out.put(listing(product));
        query(wanted, BillingClient.ProductType.INAPP, (inapp) -> {
          for (ProductDetails product : inapp) out.put(listing(product));
          answerListings(id, out);
        }, id);
      }, id);
    });
  }

  private interface DetailsAnswer {
    void with(List<ProductDetails> products);
  }

  private static void query(List<String> ids, String type, DetailsAnswer then,
      String id) {
    final List<QueryProductDetailsParams.Product> products = new ArrayList<>();
    for (String productId : ids) {
      products.add(QueryProductDetailsParams.Product.newBuilder()
          .setProductId(productId)
          .setProductType(type)
          .build());
    }
    client.queryProductDetailsAsync(
        QueryProductDetailsParams.newBuilder().setProductList(products).build(),
        (BillingResult result, QueryProductDetailsResult answer) -> main.post(() -> {
          if (result.getResponseCode() != BillingClient.BillingResponseCode.OK) {
            fail(id, "Play could not list products (" + result.getResponseCode()
                + ": " + result.getDebugMessage() + ")");
            return;
          }
          final List<ProductDetails> found = answer.getProductDetailsList();
          for (ProductDetails product : found) {
            details.put(product.getProductId(), product);
            types.put(product.getProductId(), type.equals(
                BillingClient.ProductType.SUBS) ? "subs" : "inapp");
          }
          then.with(found);
        }));
  }

  private static void answerListings(String id, JSONArray listings) {
    answer(id, object("listings", listings));
  }

  /// One product as a listing: micros and the currency rather than a
  /// number, so Dart converts them to minor units exactly.
  private static JSONObject listing(ProductDetails product) {
    final JSONObject out = new JSONObject();
    try {
      out.put("storeProductId", product.getProductId());
      out.put("title", product.getName());
      out.put("description", product.getDescription());
      final ProductDetails.OneTimePurchaseOfferDetails once =
          product.getOneTimePurchaseOfferDetails();
      if (once != null) {
        out.put("displayPrice", once.getFormattedPrice());
        out.put("priceMicros", Long.toString(once.getPriceAmountMicros()));
        out.put("currency", once.getPriceCurrencyCode());
      }
      final JSONArray offers = new JSONArray();
      final List<ProductDetails.SubscriptionOfferDetails> plans =
          product.getSubscriptionOfferDetails();
      if (plans != null) {
        for (ProductDetails.SubscriptionOfferDetails plan : plans) {
          final List<ProductDetails.PricingPhase> phases =
              plan.getPricingPhases().getPricingPhaseList();
          if (phases.isEmpty()) continue;
          final ProductDetails.PricingPhase first = phases.get(0);
          final ProductDetails.PricingPhase last = phases.get(phases.size() - 1);
          if (plan.getOfferId() == null && !out.has("displayPrice")) {
            // The base plan's recurring phase is the product's own price.
            out.put("displayPrice", last.getFormattedPrice());
            out.put("priceMicros", Long.toString(last.getPriceAmountMicros()));
            out.put("currency", last.getPriceCurrencyCode());
            out.put("period", last.getBillingPeriod());
          }
          final JSONObject offer = new JSONObject();
          offer.put("id", plan.getOfferId() != null ? plan.getOfferId()
              : plan.getBasePlanId());
          offer.put("basePlanId", plan.getBasePlanId());
          offer.put("kind", kindOf(plan, first));
          offer.put("token", plan.getOfferToken());
          offer.put("displayPrice", first.getFormattedPrice());
          offer.put("priceMicros", Long.toString(first.getPriceAmountMicros()));
          offer.put("currency", first.getPriceCurrencyCode());
          offer.put("period", first.getBillingPeriod());
          offer.put("periods", Math.max(1, first.getBillingCycleCount()));
          offer.put("tags", new JSONArray(plan.getOfferTags()));
          // Play lists only the offers this account is eligible for.
          offer.put("eligible", true);
          offers.put(offer);
        }
      }
      out.put("offers", offers);
      if (!out.has("displayPrice")) out.put("displayPrice", "");
    } catch (JSONException ignored) {
      // put never throws for these keys and values.
    }
    return out;
  }

  /// Play has no offer kinds, only phases and tags. A base plan is the
  /// plan; a first phase at no charge is a trial; a tag naming a promotion
  /// marks a developer-determined offer; anything else is introductory.
  private static String kindOf(ProductDetails.SubscriptionOfferDetails plan,
      ProductDetails.PricingPhase first) {
    if (plan.getOfferId() == null) return "basePlan";
    if (first.getPriceAmountMicros() == 0) return "freeTrial";
    for (String tag : plan.getOfferTags()) {
      final String lower = tag.toLowerCase();
      if (lower.contains("promo") || lower.contains("developer")) {
        return "promotional";
      }
      if (lower.contains("winback") || lower.contains("win-back")) return "winBack";
    }
    return "introductory";
  }

  // -- purchase ---------------------------------------------------------------

  private static void purchase(String id, JSONObject request) {
    connected(id, () -> {
      final String productId = request.optString("storeProductId");
      final ProductDetails product = details.get(productId);
      if (product == null) {
        // Listed first, so the sheet opens on what Play says the product is.
        final List<String> one = Collections.singletonList(productId);
        query(one, BillingClient.ProductType.SUBS, (subs) -> {
          if (!subs.isEmpty()) {
            launch(id, request, subs.get(0));
            return;
          }
          query(one, BillingClient.ProductType.INAPP, (inapp) -> {
            if (inapp.isEmpty()) {
              fail(id, "Play does not sell \"" + productId + "\" to this account");
              return;
            }
            launch(id, request, inapp.get(0));
          }, id);
        }, id);
        return;
      }
      launch(id, request, product);
    });
  }

  private static void launch(String id, JSONObject request, ProductDetails product) {
    final Activity activity = DartvelContext.activity();
    if (activity == null) {
      fail(id, "no Activity is resumed, so there is nothing to open the "
          + "purchase sheet over");
      return;
    }
    if (purchaseRequest != null) {
      fail(id, "another purchase sheet is already open");
      return;
    }
    final BillingFlowParams.ProductDetailsParams.Builder item =
        BillingFlowParams.ProductDetailsParams.newBuilder()
            .setProductDetails(product);
    final List<ProductDetails.SubscriptionOfferDetails> plans =
        product.getSubscriptionOfferDetails();
    if (plans != null && !plans.isEmpty()) {
      // A subscription is bought through an offer token: the one asked for,
      // or the base plan's.
      String token = null;
      final JSONObject offer = request.optJSONObject("offer");
      if (offer != null) token = offer.optString("token", null);
      if (token == null) {
        for (ProductDetails.SubscriptionOfferDetails plan : plans) {
          if (plan.getOfferId() == null) token = plan.getOfferToken();
        }
        if (token == null) token = plans.get(0).getOfferToken();
      }
      item.setOfferToken(token);
    }
    final BillingFlowParams.Builder params = BillingFlowParams.newBuilder()
        .setProductDetailsParamsList(Collections.singletonList(item.build()));
    final String account = request.optString("appAccountToken", "");
    // Play's obfuscated account id: the server refuses a purchase whose id
    // names another account.
    if (!account.isEmpty()) params.setObfuscatedAccountId(account);
    purchaseRequest = id;
    purchaseProduct = product.getProductId();
    final BillingResult launched = client.launchBillingFlow(activity, params.build());
    if (launched.getResponseCode() != BillingClient.BillingResponseCode.OK) {
      purchaseRequest = null;
      purchaseProduct = null;
      answer(id, outcome(launched, null));
    }
  }

  private static final PurchasesUpdatedListener listener =
      (BillingResult result, List<Purchase> purchases) -> main.post(() -> {
        final String waiting = purchaseRequest;
        final String product = purchaseProduct;
        Purchase answered = null;
        if (purchases != null) {
          for (Purchase purchase : purchases) {
            if (waiting != null && answered == null
                && purchase.getProducts().contains(product)) {
              answered = purchase;
            } else {
              // Not what the open sheet asked for: a pending payment that
              // completed, a purchase made elsewhere.
              updates.add(transaction(purchase));
            }
          }
        }
        if (waiting == null) return;
        purchaseRequest = null;
        purchaseProduct = null;
        answer(waiting, outcome(result, answered));
      });

  private static JSONObject outcome(BillingResult result, Purchase purchase) {
    final JSONObject out = new JSONObject();
    try {
      final int code = result.getResponseCode();
      if (code == BillingClient.BillingResponseCode.OK && purchase != null) {
        if (purchase.getPurchaseState() == Purchase.PurchaseState.PENDING) {
          out.put("outcome", "pending");
        } else {
          out.put("outcome", "purchased");
          out.put("transaction", transaction(purchase));
        }
      } else if (code == BillingClient.BillingResponseCode.USER_CANCELED) {
        out.put("outcome", "cancelled");
      } else if (code == BillingClient.BillingResponseCode.ITEM_ALREADY_OWNED) {
        out.put("outcome", "failed");
        out.put("reason", "this account already owns it; restore purchases "
            + "to bring it back");
      } else {
        out.put("outcome", "failed");
        out.put("reason", "Play answered " + code + ": " + result.getDebugMessage());
      }
    } catch (JSONException ignored) {
      // put never throws for these keys and values.
    }
    return out;
  }

  /// A purchase as Dart's DVStoreDeviceTransaction reads it, with the
  /// receipt the server's Play adapter verifies.
  private static JSONObject transaction(Purchase purchase) {
    final JSONObject out = new JSONObject();
    try {
      final String productId = purchase.getProducts().isEmpty()
          ? "" : purchase.getProducts().get(0);
      final String orderId = purchase.getOrderId();
      final String type = types.get(productId);
      final JSONObject receipt = new JSONObject();
      receipt.put("purchaseToken", purchase.getPurchaseToken());
      receipt.put("productId", productId);
      // Known when this process listed the product; otherwise the server
      // reads the kind from the products the application declares.
      if (type != null) receipt.put("type", type);
      if (orderId != null) receipt.put("orderId", orderId);
      out.put("storeProductId", productId);
      out.put("transactionId", orderId != null ? orderId : purchase.getPurchaseToken());
      out.put("receipt", receipt.toString());
      out.put("state", purchase.getPurchaseState() == Purchase.PurchaseState.PENDING
          ? "pending" : "purchased");
      out.put("quantity", purchase.getQuantity());
    } catch (JSONException ignored) {
      // put never throws for these keys and values.
    }
    return out;
  }

  // -- owned and finish -------------------------------------------------------

  private static void owned(String id) {
    connected(id, () -> {
      final JSONArray out = new JSONArray();
      queryOwned(BillingClient.ProductType.SUBS, out, id, () ->
          queryOwned(BillingClient.ProductType.INAPP, out, id, () -> {
            answer(id, object("transactions", out));
          }));
    });
  }

  private static void queryOwned(String type, JSONArray out, String id,
      Runnable then) {
    client.queryPurchasesAsync(
        QueryPurchasesParams.newBuilder().setProductType(type).build(),
        (BillingResult result, List<Purchase> purchases) -> main.post(() -> {
          if (result.getResponseCode() != BillingClient.BillingResponseCode.OK) {
            fail(id, "Play could not list purchases (" + result.getResponseCode()
                + ": " + result.getDebugMessage() + ")");
            return;
          }
          final String kind =
              type.equals(BillingClient.ProductType.SUBS) ? "subs" : "inapp";
          for (Purchase purchase : purchases) {
            for (String productId : purchase.getProducts()) types.put(productId, kind);
            out.put(transaction(purchase));
          }
          then.run();
        }));
  }

  private static void finish(String id, JSONObject request) {
    if (!request.optBoolean("consume", false)) {
      // Acknowledgement is the server's, after Google has confirmed the
      // purchase. Nothing to do here for a subscription or a one-time
      // product that is kept.
      answer(id, new JSONObject());
      return;
    }
    final String token = request.optString("purchaseToken", "");
    connected(id, () -> client.consumeAsync(
        ConsumeParams.newBuilder().setPurchaseToken(token).build(),
        (BillingResult result, String consumedToken) -> main.post(() -> {
          if (result.getResponseCode() == BillingClient.BillingResponseCode.OK) {
            answer(id, new JSONObject());
          } else {
            fail(id, "Play did not consume the purchase (" + result.getResponseCode()
                + ": " + result.getDebugMessage() + ")");
          }
        })));
  }

  // -- answers ----------------------------------------------------------------

  private static void answer(String id, JSONObject value) {
    answers.put(id, value.toString());
  }

  /// A one-key object. JSONObject.put declares a checked exception it never
  /// throws for a String key, and a lambda cannot let one through.
  private static JSONObject object(String key, Object value) {
    final JSONObject out = new JSONObject();
    try {
      out.put(key, value);
    } catch (JSONException ignored) {
      // Not thrown for a String key and a non-null value.
    }
    return out;
  }

  private static void fail(String id, String reason) {
    final JSONObject out = new JSONObject();
    try {
      out.put("error", reason);
    } catch (JSONException ignored) {
      // put never throws for a String key and value.
    }
    answers.put(id, out.toString());
  }
}
