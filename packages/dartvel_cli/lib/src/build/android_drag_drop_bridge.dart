package dev.dartvel.jni;

// GENERATED by dartvel build. Drag and drop for DV.Platform.dragDrop:
// drops into the window, from this application or another one, and drags
// out of it to another application.

import android.app.Activity;
import android.content.ClipData;
import android.content.ClipDescription;
import android.content.ContentResolver;
import android.content.Context;
import android.database.Cursor;
import android.graphics.Canvas;
import android.graphics.Color;
import android.graphics.Paint;
import android.graphics.Point;
import android.graphics.RectF;
import android.net.Uri;
import android.os.Build;
import android.os.Looper;
import android.os.ParcelFileDescriptor;
import android.provider.OpenableColumns;
import android.view.DragAndDropPermissions;
import android.view.DragEvent;
import android.view.View;
import android.view.ViewGroup;

import java.io.File;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.ConcurrentLinkedQueue;

import org.json.JSONArray;
import org.json.JSONException;
import org.json.JSONObject;

public final class DartvelDragDrop {
  private DartvelDragDrop() {}

  private static final ConcurrentLinkedQueue<String> events =
      new ConcurrentLinkedQueue<String>();

  // Held until the next drop or until the window stops taking drops: a
  // dropped file is read when the application asks, which is after the drop
  // event has returned, and the grant has to outlive it.
  private static Object permissions;

  private static volatile String lastError;

  /// The next drag event as JSON, or null when there is none.
  public static String next() {
    return events.poll();
  }

  /// Why the last call failed, or null.
  public static String lastError() {
    return lastError;
  }

  /// Takes drops anywhere on the activity's window.
  public static boolean accept(final Activity activity) {
    if (activity == null) {
      lastError = "no Activity is resumed";
      return false;
    }
    onUi(activity, new Runnable() {
      public void run() {
        activity.getWindow().getDecorView().setOnDragListener(
            new Listener(activity));
      }
    });
    return true;
  }

  /// Stops taking drops on the activity's window.
  public static boolean stop(final Activity activity) {
    if (activity == null) return true;
    onUi(activity, new Runnable() {
      public void run() {
        activity.getWindow().getDecorView().setOnDragListener(null);
        releasePermissions();
      }
    });
    return true;
  }

  /// Opens a dropped file for reading and hands the descriptor to Dart, which
  /// reads it through /proc/self/fd and gives it back with [close].
  public static int open(Activity activity, String uri) {
    try {
      ParcelFileDescriptor descriptor = activity.getContentResolver()
          .openFileDescriptor(Uri.parse(uri), "r");
      if (descriptor == null) {
        lastError = "the provider returned no file for " + uri;
        return -1;
      }
      return descriptor.detachFd();
    } catch (Exception error) {
      lastError = String.valueOf(error);
      return -1;
    }
  }

  public static void close(int descriptor) {
    try {
      ParcelFileDescriptor.adoptFd(descriptor).close();
    } catch (Exception ignored) {
      // Already closed.
    }
  }

  /// The directory a drag's files are written to before it starts, served
  /// by DartvelCaptureFiles.
  public static String outgoingDirectory(Context context) {
    File directory = DartvelCaptureFiles.directory(context);
    directory.mkdirs();
    return directory.getAbsolutePath();
  }

  /// Starts a drag out of the window carrying the payload's text, links and
  /// files. Has to be called while a finger or the mouse is still down.
  public static boolean startDrag(final Activity activity, String json) {
    if (activity == null) {
      lastError = "no Activity is resumed";
      return false;
    }
    if (Build.VERSION.SDK_INT < 24) {
      lastError = "dragging to another application needs Android 7.0 (API 24)";
      return false;
    }
    final ClipData clip;
    final String label;
    try {
      JSONObject payload = new JSONObject(json);
      List<String> types = new ArrayList<String>();
      List<ClipData.Item> items = new ArrayList<ClipData.Item>();
      String first = null;
      String text = payload.optString("text", null);
      if (text != null && text.length() > 0) {
        items.add(new ClipData.Item(text));
        types.add(ClipDescription.MIMETYPE_TEXT_PLAIN);
        first = text;
      }
      JSONArray urls = payload.optJSONArray("urls");
      for (int index = 0; urls != null && index < urls.length(); index++) {
        String url = urls.getString(index);
        items.add(new ClipData.Item(url));
        if (!types.contains(ClipDescription.MIMETYPE_TEXT_URILIST)) {
          types.add(ClipDescription.MIMETYPE_TEXT_URILIST);
        }
        if (first == null) first = url;
      }
      JSONArray files = payload.optJSONArray("files");
      for (int index = 0; files != null && index < files.length(); index++) {
        JSONObject file = files.getJSONObject(index);
        String path = file.optString("path", null);
        if (path == null) continue;
        items.add(new ClipData.Item(
            DartvelCaptureFiles.uriFor(activity, new File(path))));
        String type = file.optString("mimeType", "application/octet-stream");
        if (!types.contains(type)) types.add(type);
        if (first == null) first = file.optString("name", new File(path).getName());
      }
      if (items.isEmpty()) {
        lastError = "the drag carried nothing";
        return false;
      }
      label = first;
      clip = new ClipData(new ClipDescription(label,
          types.toArray(new String[0])), items.get(0));
      for (int index = 1; index < items.size(); index++) {
        clip.addItem(items.get(index));
      }
    } catch (JSONException error) {
      lastError = String.valueOf(error);
      return false;
    }
    final int flags = View.DRAG_FLAG_GLOBAL | View.DRAG_FLAG_GLOBAL_URI_READ;
    if (Looper.myLooper() == Looper.getMainLooper()) {
      return begin(activity, clip, label, flags);
    }
    activity.runOnUiThread(new Runnable() {
      public void run() {
        begin(activity, clip, label, flags);
      }
    });
    return true;
  }

  private static boolean begin(Activity activity, ClipData clip, String label,
      int flags) {
    View view = flutterView(activity);
    boolean started = view.startDragAndDrop(clip, new Shadow(activity, label),
        null, flags);
    if (!started) {
      lastError = "Android declined to start the drag: no pointer was down";
    }
    return started;
  }

  /// The view Flutter draws into: the content view's first child.
  private static View flutterView(Activity activity) {
    View content = activity.findViewById(android.R.id.content);
    if (content instanceof ViewGroup && ((ViewGroup) content).getChildCount() > 0) {
      return ((ViewGroup) content).getChildAt(0);
    }
    return activity.getWindow().getDecorView();
  }

  private static void onUi(Activity activity, Runnable work) {
    if (Looper.myLooper() == Looper.getMainLooper()) {
      work.run();
    } else {
      activity.runOnUiThread(work);
    }
  }

  private static void releasePermissions() {
    if (permissions != null && Build.VERSION.SDK_INT >= 24) {
      ((DragAndDropPermissions) permissions).release();
    }
    permissions = null;
  }

  private static final class Listener implements View.OnDragListener {
    private final Activity activity;

    Listener(Activity activity) {
      this.activity = activity;
    }

    public boolean onDrag(View view, DragEvent event) {
      try {
        switch (event.getAction()) {
          case DragEvent.ACTION_DRAG_STARTED:
            // Interested in every drag: what the application takes is
            // decided in Dart, by kind, per widget.
            return true;
          case DragEvent.ACTION_DRAG_ENTERED:
          case DragEvent.ACTION_DRAG_LOCATION:
            events.add(position("hover", view, event).toString());
            return true;
          case DragEvent.ACTION_DRAG_EXITED:
          case DragEvent.ACTION_DRAG_ENDED:
            events.add(new JSONObject().put("kind", "leave").toString());
            return true;
          case DragEvent.ACTION_DROP:
            events.add(drop(view, event).toString());
            return true;
          default:
            return false;
        }
      } catch (JSONException error) {
        lastError = String.valueOf(error);
        return false;
      }
    }

    /// The event's position relative to the view Flutter draws into, in
    /// physical pixels; Dart divides by the device pixel ratio.
    private JSONObject position(String kind, View view, DragEvent event)
        throws JSONException {
      int[] flutter = new int[2];
      int[] receiving = new int[2];
      flutterView(activity).getLocationInWindow(flutter);
      view.getLocationInWindow(receiving);
      return new JSONObject()
          .put("kind", kind)
          .put("x", event.getX() + receiving[0] - flutter[0])
          .put("y", event.getY() + receiving[1] - flutter[1]);
    }

    private JSONObject drop(View view, DragEvent event) throws JSONException {
      JSONObject out = position("drop", view, event);
      ClipData clip = event.getClipData();
      JSONArray items = new JSONArray();
      if (clip == null) return out.put("items", items);
      boolean anyContent = false;
      for (int index = 0; index < clip.getItemCount(); index++) {
        Uri uri = clip.getItemAt(index).getUri();
        if (uri != null && ContentResolver.SCHEME_CONTENT.equals(uri.getScheme())) {
          anyContent = true;
        }
      }
      // Without this, reading a content:// URI another application dropped
      // throws SecurityException.
      if (anyContent && Build.VERSION.SDK_INT >= 24) {
        releasePermissions();
        permissions = activity.requestDragAndDropPermissions(event);
      }
      ContentResolver resolver = activity.getContentResolver();
      for (int index = 0; index < clip.getItemCount(); index++) {
        ClipData.Item item = clip.getItemAt(index);
        JSONObject entry = new JSONObject();
        Uri uri = item.getUri();
        CharSequence text = item.getText();
        if (uri != null) {
          entry.put("uri", uri.toString());
          if (ContentResolver.SCHEME_CONTENT.equals(uri.getScheme())) {
            describe(resolver, uri, entry);
          }
        } else if (text != null) {
          entry.put("text", text.toString());
        } else {
          CharSequence coerced = item.coerceToText(activity);
          if (coerced != null && coerced.length() > 0) {
            entry.put("text", coerced.toString());
          }
        }
        items.put(entry);
      }
      return out.put("items", items);
    }

    /// The name, type and size of a content URI, as its provider reports.
    private void describe(ContentResolver resolver, Uri uri, JSONObject entry)
        throws JSONException {
      String type = resolver.getType(uri);
      if (type != null) entry.put("mimeType", type);
      Cursor cursor = null;
      try {
        cursor = resolver.query(uri, new String[] {
          OpenableColumns.DISPLAY_NAME, OpenableColumns.SIZE,
        }, null, null, null);
        if (cursor != null && cursor.moveToFirst()) {
          int name = cursor.getColumnIndex(OpenableColumns.DISPLAY_NAME);
          int size = cursor.getColumnIndex(OpenableColumns.SIZE);
          if (name >= 0 && !cursor.isNull(name)) {
            entry.put("name", cursor.getString(name));
          }
          if (size >= 0 && !cursor.isNull(size)) {
            entry.put("size", cursor.getLong(size));
          }
        }
      } catch (Exception error) {
        // A provider that will not describe the file still lets it be read.
        lastError = String.valueOf(error);
      } finally {
        if (cursor != null) cursor.close();
      }
    }
  }

  /// What the finger carries: a rounded label naming what is dragged.
  private static final class Shadow extends View.DragShadowBuilder {
    private final float density;
    private final Paint fill = new Paint(Paint.ANTI_ALIAS_FLAG);
    private final Paint ink = new Paint(Paint.ANTI_ALIAS_FLAG);
    private final String label;
    private final int width;
    private final int height;

    Shadow(Context context, String text) {
      super();
      density = context.getResources().getDisplayMetrics().density;
      fill.setColor(Color.argb(230, 32, 33, 36));
      ink.setColor(Color.WHITE);
      ink.setTextSize(14 * density);
      String shown = text.replace('\n', ' ');
      float limit = 240 * density;
      if (ink.measureText(shown) > limit) {
        int fits = ink.breakText(shown, true, limit - ink.measureText("…"), null);
        shown = shown.substring(0, Math.max(1, fits)) + "…";
      }
      label = shown;
      width = (int) (ink.measureText(label) + 24 * density);
      height = (int) (40 * density);
    }

    @Override
    public void onProvideShadowMetrics(Point size, Point touch) {
      size.set(Math.max(1, width), Math.max(1, height));
      touch.set(width / 2, height / 2);
    }

    @Override
    public void onDrawShadow(Canvas canvas) {
      float radius = 8 * density;
      canvas.drawRoundRect(new RectF(0, 0, width, height), radius, radius, fill);
      canvas.drawText(label, 12 * density,
          height / 2f - (ink.descent() + ink.ascent()) / 2f, ink);
    }
  }
}
