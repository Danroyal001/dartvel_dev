/// Drag and drop on Android, as the Java `dartvel build android` writes into
/// the application.
///
/// Android delivers a drag to a `View.OnDragListener`, on the UI thread, as a
/// sequence of `DragEvent`s; a drop from another application in split screen,
/// a freeform window or a desktop window carries `content://` URIs that are
/// readable only after `Activity.requestDragAndDropPermissions`. Dragging out
/// is `View.startDragAndDrop` with `DRAG_FLAG_GLOBAL`, so the drag can leave
/// the window, and `DRAG_FLAG_GLOBAL_URI_READ`, so the receiving application
/// can read the files it carries.
///
/// It is Java for the reason the capture bridge is: a listener interface, a
/// `DragShadowBuilder` subclass and a cursor are each a binding that would
/// have to be generated and right before Dart could express them, and `javac`
/// checks this at build time. The Dart side polls a queue of JSON events
/// rather than taking a callback from the UI thread, as the capture bridge
/// does.
///
/// Files a drag carries out are served by `DartvelCaptureFiles`, the
/// provider the capture bridge already declares on every Android build, so
/// drag and drop adds no manifest entry of its own.
library dartvel_cli.build.android_drag_drop_bridge;

/// Where the generated file goes, relative to the project root.
const String dvAndroidDragDropPath =
    'android/app/src/main/java/dev/dartvel/jni/DartvelDragDrop.java';

