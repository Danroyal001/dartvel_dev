/// The Android half of a home widget.
///
/// `@DVHomeWidget` generates the page and the route; that is the Dart half
/// and it was all there was. A widget nobody can put on a home screen is a
/// page at `/widgets/<id>` and a promise — the annotation says "home widget"
/// and Android is never told the application has one.
///
/// What Android needs is an AppWidgetProvider, the metadata that describes
/// the widget to the launcher, a layout to draw, and a receiver in the
/// manifest. None can be added at run time, so all four are the build's.
///
/// What is drawn is a RemoteViews layout, not the Flutter widget. Android
/// composes a home screen out of the launcher's own process, which cannot
/// host a Flutter engine — a widget that claimed to render the Flutter tree
/// would be claiming something the platform does not offer. What the
/// specification does ask for is that a home widget can launch and navigate
/// to a page in the application, and that is exactly what a tap does: a deep
/// link to the route Dartvel generated for it.
library;

import 'package:dartvel_core/dartvel.dart' show DVHomeWidgetSpec;

const String _markStart = '        <!-- dartvel.homeWidgets: begin -->';
const String _markEnd = '        <!-- dartvel.homeWidgets: end -->';

/// The resource name for a widget's layout and metadata.
///
/// Android resource names take letters, digits and underscores. An
/// identifier as a file name is an aapt error at the end of a build, and
/// silently different names in the manifest and on disk is worse.
String dvAndroidWidgetResource(String id) =>
    'dartvel_widget_${id.replaceAll(RegExp('[^A-Za-z0-9]'), '_')}';

/// [manifest] with a receiver per widget, or without them when there are
/// none.
///
/// Marked, so a second build replaces the block rather than adding another:
/// two providers under one name is a manifest the packager refuses, from a
/// build that succeeded.
String dvAndroidHomeWidgetManifest(
  String manifest,
  List<DVHomeWidgetSpec> widgets,
) {
  final RegExp block = RegExp(
      '\n${RegExp.escape(_markStart)}.*?${RegExp.escape(_markEnd)}',
      dotAll: true);
  final String stripped = manifest.replaceAll(block, '');
  if (widgets.isEmpty) return stripped;

  final StringBuffer out = StringBuffer()..writeln(_markStart);
  for (final DVHomeWidgetSpec widget in widgets) {
    final String resource = dvAndroidWidgetResource(widget.id);
    out
      ..writeln('        <receiver')
      ..writeln('            android:name=".${widget.name}Provider"')
      ..writeln('            android:exported="false">')
      ..writeln('            <intent-filter>')
      ..writeln('                <action android:name="android.appwidget.action.APPWIDGET_UPDATE"/>')
      ..writeln('            </intent-filter>')
      ..writeln('            <meta-data')
      ..writeln('                android:name="android.appwidget.provider"')
      ..writeln('                android:resource="@xml/$resource"/>')
      ..writeln('        </receiver>');
  }
  out.write(_markEnd);

  final int close = stripped.lastIndexOf('    </application>');
  if (close < 0) return stripped;
  return '${stripped.substring(0, close)}${out.toString()}\n${stripped.substring(close)}';
}

/// The provider for one widget.
///
/// It draws the layout and wires the tap. The tap is the point: the
/// specification says a home widget can launch and navigate to a page in the
/// application, and this is the whole of that on Android — a deep link to
/// the route Dartvel generated.
String dvAndroidHomeWidgetProviderSource(
  String package,
  DVHomeWidgetSpec widget,
) {
  final String resource = dvAndroidWidgetResource(widget.id);
  return '''
package $package;

// GENERATED by dartvel build from @DVHomeWidget. Do not edit: the next build
// writes it again.
//
// RemoteViews rather than the Flutter widget, because a home screen is
// composed in the launcher's process and that cannot host a Flutter engine.
// What the specification asks of a home widget is that it can launch and
// navigate to a page in the application, which is what the tap below does.
import android.app.PendingIntent;
import android.appwidget.AppWidgetManager;
import android.appwidget.AppWidgetProvider;
import android.content.ComponentName;
import android.content.Context;
import android.content.Intent;
import android.net.Uri;
import android.widget.RemoteViews;

public class ${widget.name}Provider extends AppWidgetProvider {
    @Override
    public void onUpdate(Context context, AppWidgetManager manager, int[] ids) {
        for (int id : ids) {
            RemoteViews views =
                    new RemoteViews(context.getPackageName(), R.layout.$resource);
            views.setTextViewText(R.id.${resource}_label, "${widget.id}");

            // The route this widget was generated for. A launch that opened
            // the application's home screen instead would be a shortcut, not
            // a widget.
            Intent open = new Intent(Intent.ACTION_VIEW,
                    Uri.parse("dartvel://widget${widget.route}"));
            open.setComponent(new ComponentName(context, "$package.MainActivity"));
            open.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);

            // FLAG_IMMUTABLE because nothing fills anything in afterwards,
            // and Android 12 and later refuse a PendingIntent that says
            // neither.
            PendingIntent tap = PendingIntent.getActivity(context, 0, open,
                    PendingIntent.FLAG_UPDATE_CURRENT | PendingIntent.FLAG_IMMUTABLE);
            views.setOnClickPendingIntent(R.id.${resource}_root, tap);

            manager.updateAppWidget(id, views);
        }
    }
}
''';
}

/// What the launcher reads to describe the widget before anybody places it.
///
/// A provider whose metadata points at a missing layout installs and then
/// crashes the launcher when somebody places it — on their home screen,
/// rather than in the build.
String dvAndroidHomeWidgetMetadata(DVHomeWidgetSpec widget) {
  final String resource = dvAndroidWidgetResource(widget.id);
  return '''
<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by dartvel build from @DVHomeWidget. -->
<appwidget-provider xmlns:android="http://schemas.android.com/apk/res/android"
    android:minWidth="110dp"
    android:minHeight="40dp"
    android:updatePeriodMillis="1800000"
    android:resizeMode="horizontal|vertical"
    android:widgetCategory="home_screen"
    android:initialLayout="@layout/$resource"/>
''';
}

/// The layout the provider draws.
String dvAndroidHomeWidgetLayout(DVHomeWidgetSpec widget) {
  final String resource = dvAndroidWidgetResource(widget.id);
  return '''
<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by dartvel build from @DVHomeWidget. -->
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/${resource}_root"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:orientation="vertical"
    android:padding="12dp">
    <TextView
        android:id="@+id/${resource}_label"
        android:layout_width="match_parent"
        android:layout_height="wrap_content"
        android:textSize="16sp"/>
</LinearLayout>
''';
}
