/// Telling WidgetKit that a published value has changed.
///
/// The application writes into the App Group container and the extension
/// reads it back when its provider's timeline says to, which the generated
/// provider sets fifteen minutes out. Until then the home screen shows the
/// previous value, and nothing distinguishes that from a publish that did
/// not work.
///
/// `WidgetCenter` closes it and Dart cannot reach it. It is a Swift-only API
/// with no Objective-C class behind it, so there is nothing for
/// `objc_getClass` to find -- the FFI bindings say as much, and said it was
/// where this stopped. What can be reached is Swift compiled into the
/// application, and that is what this writes: a small `@objc` class the Dart
/// runtime messages by name.
///
/// The wiring is where the silence is. A Swift file written into the project
/// folder and left out of the Runner target's Sources phase is never
/// compiled. The build succeeds, `objc_getClass` answers nil, and every
/// publish goes on being fifteen minutes late -- and nil is also the honest
/// answer for an application built with plain `flutter build`, which this
/// deliberately tolerates, so the two cannot be told apart at run time.
library;

import 'package:dartvel_core/dartvel.dart'
    show dvHomeWidgetAppleReloadClass, dvHomeWidgetAppleReloadSelector;

// One rule for finding the application target, shared with the extension
// splice. Two copies of a pbxproj query is how one of them goes on reading a
// file shape the other stopped believing in.
import 'apple_widget_target.dart' show dvAppleApplicationTargetId;

/// The file the shim is written to, inside the `Runner` folder.
const String dvAppleWidgetReloadFileName = 'DartvelWidgetCenter.swift';

/// The prefix every object this adds to the pbxproj carries.
///
/// Its own, rather than the extension target's, because the two are added
/// and removed independently: the extension is a target of its own and this
/// is two objects inside a target Flutter owns. Sharing a prefix would make
/// removing one remove the other.
const String dvAppleWidgetReloadIdPrefix = 'DA97E1DA97E2';

final String _fileRefId = '${dvAppleWidgetReloadIdPrefix}000000000001';
final String _buildFileId = '${dvAppleWidgetReloadIdPrefix}000000000002';

/// The shim, as Swift.
///
/// `@objc(name)` rather than a bare `@objc`, because Swift mangles a type
/// name unless it is given an explicit Objective-C one -- and a mangled name
/// is a class `objc_getClass` cannot find, which looks exactly like an
/// application built without this file.
///
/// The availability guard is not optional. WidgetKit starts at iOS 14 and
/// macOS 11, a Flutter application's deployment target is usually lower, and
/// without the guard the file does not compile -- at the Xcode step, after
/// everything in Dart has passed.
String dvAppleWidgetReloadSource() => '''
// GENERATED by dartvel build from @DVHomeWidget. Do not edit: the next build
// writes it again.
//
// What this exists for is a boundary rather than a feature. WidgetCenter is
// Swift-only and has no Objective-C class, so nothing in Dart can message
// it: the application could write a widget's new value into the shared
// container and had no way to say so, leaving the home screen on the
// previous value until the provider's timeline came round.
import Foundation
#if canImport(WidgetKit)
import WidgetKit
#endif

/// Reached from Dart through the Objective-C runtime, by this exact name.
///
/// The name is one constant in Dartvel that both halves read. Spelled twice,
/// the lookup answers nil for ever -- and nil is also what an application
/// built with plain `flutter build` answers, so nothing could tell them
/// apart.
@objc($dvHomeWidgetAppleReloadClass)
public final class $dvHomeWidgetAppleReloadClass: NSObject {
    /// Redraws every widget this application ships.
    ///
    /// Every one rather than a named kind: a publish knows the widget it
    /// wrote for, and asking WidgetKit for the wrong kind is a reload that
    /// does nothing and reports nothing. Reloading all of them costs a
    /// timeline call per widget on an application that has very few.
    @objc public static func $dvHomeWidgetAppleReloadSelector() {
        #if canImport(WidgetKit)
        if #available(iOS 14.0, macOS 11.0, *) {
            WidgetCenter.shared.reloadAllTimelines()
        }
        #endif
    }
}
''';

/// [pbxproj] with the shim compiled into the application, or without it.
///
/// [platform] is `ios` or `macos`. Both package the same WidgetKit
/// extension, so both have the same gap; a platform that got the extension
/// and not this would be stale rather than broken, which is the harder half
/// to notice.
String dvApplePbxprojWithWidgetReload(
  String pbxproj, {
  required bool hasWidgets,
  required String platform,
}) {
  final String stripped = _strip(pbxproj);
  if (!hasWidgets) return stripped;

  // Everything below hangs off the application target. A project without one
  // is not a project this understands, and writing into it anyway trades a
  // missing feature for one that will not open.
  final String? sources = _applicationSourcesPhaseId(stripped);
  if (sources == null) return stripped;

  const String path = dvAppleWidgetReloadFileName;

  String out = stripped;
  out = _beforeSectionEnd(out, 'PBXBuildFile', <String>[
    '\t\t$_buildFileId /* $path in Sources */ = {isa = PBXBuildFile; '
        'fileRef = $_fileRefId /* $path */; };',
  ]);
  out = _beforeSectionEnd(out, 'PBXFileReference', <String>[
    '\t\t$_fileRefId /* $path */ = {isa = PBXFileReference; '
        'lastKnownFileType = sourcecode.swift; path = $path; '
        'sourceTree = "<group>"; };',
  ]);
  // Into the application's own group, beside AppDelegate.swift, because that
  // is where the file is written on disk. A file reference whose group does
  // not match its path is one Xcode shows in the wrong place and cannot
  // open from the navigator.
  final String? group = _applicationGroupId(out);
  if (group != null) {
    out = _intoList(out, group, 'children', '\t\t\t\t$_fileRefId /* $path */,');
  }
  out = _intoList(
      out, sources, 'files', '\t\t\t\t$_buildFileId /* $path in Sources */,');
  return out;
}

/// [pbxproj] with everything this ever wrote taken back out.
///
/// Every object and every reference to one carries the prefix and is written
/// on one line, so removing them is removing lines. That is what makes a
/// project with the widgets taken away byte-identical to the one before they
/// were added -- which matters, because the pbxproj is checked in and a
/// build that rewrote it differently each time would put a diff on every
/// branch.
String _strip(String pbxproj) => pbxproj
    .split('\n')
    .where((String line) => !line.contains(dvAppleWidgetReloadIdPrefix))
    .join('\n');

/// The id of the Sources phase of the target that builds the `.app`.
///
/// Found through the target rather than by taking the first
/// PBXSourcesBuildPhase in the file: a project with a test target has two,
/// and compiling the shim into the tests would leave the application without
/// it and nothing to say so.
String? _applicationSourcesPhaseId(String pbxproj) {
  final String? target = dvAppleApplicationTargetId(pbxproj);
  if (target == null) return null;
  // The object's own line, which starts at exactly two tabs. Searching for
  // two tabs anywhere finds the reference to it inside a list first, because
  // a list entry is indented four and so contains a two-tab prefix -- and
  // from there the search for the object's body walks the wrong object.
  final int at = pbxproj.indexOf('\n\t\t$target ');
  if (at < 0) return null;
  final int end = pbxproj.indexOf('\n\t\t};', at);
  if (end < 0) return null;
  final String block = pbxproj.substring(at, end);
  final int phases = block.indexOf('buildPhases = (');
  if (phases < 0) return null;
  final int phasesEnd = block.indexOf(');', phases);
  if (phasesEnd < 0) return null;

  for (final RegExpMatch match
      in RegExp('([0-9A-F]{24})').allMatches(block.substring(phases, phasesEnd))) {
    final String id = match.group(1)!;
    final int object = pbxproj.indexOf('\n\t\t$id ');
    if (object < 0) continue;
    final int objectEnd = pbxproj.indexOf('\n\t\t};', object);
    if (objectEnd < 0) continue;
    if (pbxproj
        .substring(object, objectEnd)
        .contains('isa = PBXSourcesBuildPhase;')) {
      return id;
    }
  }
  return null;
}

/// The id of the group the application's own sources live in.
///
/// The `Runner` group, found by its path rather than by its name, because a
/// renamed target keeps the folder its files are actually in.
String? _applicationGroupId(String pbxproj) {
  final RegExp group = RegExp(
      r'\t\t([0-9A-F]{24}) /\*.*?\*/ = \{\n\t\t\tisa = PBXGroup;.*?\n\t\t\};',
      dotAll: true);
  for (final RegExpMatch match in group.allMatches(pbxproj)) {
    if (match.group(0)!.contains('path = Runner;')) return match.group(1);
  }
  return null;
}

/// [lines] inserted just before `/* End [section] section */`.
String _beforeSectionEnd(String pbxproj, String section, List<String> lines) {
  final String end = '/* End $section section */';
  final int at = pbxproj.indexOf(end);
  if (at < 0) return pbxproj;
  return '${pbxproj.substring(0, at)}${lines.join('\n')}\n'
      '${pbxproj.substring(at)}';
}

/// [entry] added to the end of `[key] = (` inside the object with [objectId].
String _intoList(String pbxproj, String objectId, String key, String entry) {
  final int object = pbxproj.indexOf('\n\t\t$objectId ');
  if (object < 0) return pbxproj;
  final int list = pbxproj.indexOf('$key = (', object);
  if (list < 0) return pbxproj;
  final int close = pbxproj.indexOf('\t\t\t);', list);
  if (close < 0) return pbxproj;
  return '${pbxproj.substring(0, close)}$entry\n${pbxproj.substring(close)}';
}
