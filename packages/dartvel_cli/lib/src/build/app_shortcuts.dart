/// `dartvel.appShortcuts` written where each platform reads it.
///
/// The declaration is one list (see `DVAppShortcut` in dartvel_core). What
/// each platform wants is different, and every part of it is generated:
///
/// * web: the manifest's `shortcuts`, which an installed web app shows on
///   its icon (Chrome and Edge on Android and the desktop);
/// * Android: `res/xml/dartvel_shortcuts.xml`, its labels in
///   `res/values/dartvel_shortcuts.xml`, and the `android.app.shortcuts`
///   meta-data inside the launcher activity, in a marked block;
/// * iOS: `UIApplicationShortcutItems` in `Info.plist`, and an app-delegate
///   method that hands the chosen action to Dart, both in marked blocks;
/// * Linux: `Actions=` and a `[Desktop Action]` group per shortcut in the
///   application's desktop entry.
///
/// Every shortcut opens its route through the launch link
/// `dartvel:///<route>`, the same path a home widget's tap and an app link
/// take, so a quick action opens its page on a cold launch and on a warm one
/// without a second mechanism to keep in step.
library;

import 'dart:io';

import 'package:dartvel_core/dartvel.dart' show DVAppShortcut, DVAppShortcutsConfig;
import 'package:path/path.dart' as p;

String _xml(String text) => text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');

/// The shortcuts a project declares under `dartvel:`.
DVAppShortcutsConfig dvAppShortcutsOf(Map<Object?, Object?> dartvelSection) =>
    DVAppShortcutsConfig.parse(dartvelSection['appShortcuts']);

/// Routes [shortcuts] name that are not among [routes]. A path-parameter
/// route (`/orders/:id`) matches a concrete path with a segment in its place.
List<String> dvAppShortcutUnknownRoutes(List<DVAppShortcut> shortcuts, Iterable<String> routes) {
  final List<RegExp> patterns = <RegExp>[
    for (final String route in routes)
      RegExp('^${route.split('/').map((String segment) => segment.startsWith(':') ? '[^/]+' : RegExp.escape(segment)).join('/')}\$'),
  ];
  return <String>[
    for (final DVAppShortcut shortcut in shortcuts)
      if (!patterns.any((RegExp pattern) => pattern.hasMatch(Uri.parse(shortcut.route).path)))
        '${shortcut.id}: ${shortcut.route}',
  ];
}

// -- Web ----------------------------------------------------------------------

/// The manifest's `shortcuts`. URLs are relative to the manifest, so an
/// application served under a base path keeps its shortcuts inside it.
List<Map<String, Object?>> dvPwaShortcuts(List<DVAppShortcut> shortcuts, {Map<String, int> iconSizes = const <String, int>{}}) =>
    <Map<String, Object?>>[
      for (final DVAppShortcut shortcut in shortcuts)
        <String, Object?>{
          'name': shortcut.title,
          'short_name': shortcut.title,
          if (shortcut.subtitle != null) 'description': shortcut.subtitle,
          'url': shortcut.route == '/' ? '.' : shortcut.route.substring(1),
          if (shortcut.icon != null)
            'icons': <Map<String, Object?>>[
              <String, Object?>{
                'src': shortcut.icon,
                if (iconSizes[shortcut.icon] != null) 'sizes': '${iconSizes[shortcut.icon]}x${iconSizes[shortcut.icon]}',
              },
            ],
        },
    ];

/// The edge of a square PNG at [path], or null when it is not a PNG.
int? dvPngSize(File file) {
  if (!file.existsSync()) return null;
  final List<int> head = file.openSync().readSync(24);
  const List<int> signature = <int>[0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];
  if (head.length < 24) return null;
  for (int index = 0; index < signature.length; index++) {
    if (head[index] != signature[index]) return null;
  }
  int read32(int offset) => (head[offset] << 24) | (head[offset + 1] << 16) | (head[offset + 2] << 8) | head[offset + 3];
  final int width = read32(16);
  final int height = read32(20);
  return width == height ? width : null;
}

// -- Android ------------------------------------------------------------------

/// `res/xml/dartvel_shortcuts.xml`: each shortcut an explicit VIEW intent at
/// the launcher activity, carrying the launch link.
String dvAndroidShortcutsXml(List<DVAppShortcut> shortcuts, {required String package, required String activity}) {
  final StringBuffer out = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln('<!-- GENERATED by dartvel build from dartvel.appShortcuts. Do not edit. -->')
    ..writeln('<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">');
  for (final DVAppShortcut shortcut in shortcuts) {
    final String key = _androidKey(shortcut.id);
    out
      ..writeln('    <shortcut')
      ..writeln('        android:shortcutId="${_xml(shortcut.id)}"')
      ..writeln('        android:enabled="true"')
      ..writeln('        android:icon="@mipmap/ic_launcher"')
      ..writeln('        android:shortcutShortLabel="@string/dartvel_shortcut_${key}_short"')
      ..writeln('        android:shortcutLongLabel="@string/dartvel_shortcut_${key}_long">')
      ..writeln('        <intent')
      ..writeln('            android:action="android.intent.action.VIEW"')
      ..writeln('            android:targetPackage="${_xml(package)}"')
      ..writeln('            android:targetClass="${_xml(activity)}"')
      ..writeln('            android:data="${_xml(shortcut.launchLink)}" />')
      ..writeln('    </shortcut>');
  }
  out.writeln('</shortcuts>');
  return out.toString();
}

/// `res/values/dartvel_shortcuts.xml`: the labels, because Android takes a
/// shortcut's label only as a string resource.
String dvAndroidShortcutStrings(List<DVAppShortcut> shortcuts) {
  final StringBuffer out = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln('<!-- GENERATED by dartvel build from dartvel.appShortcuts. Do not edit. -->')
    ..writeln('<resources>');
  for (final DVAppShortcut shortcut in shortcuts) {
    final String key = _androidKey(shortcut.id);
    out
      ..writeln('    <string name="dartvel_shortcut_${key}_short">${_androidText(shortcut.title)}</string>')
      ..writeln('    <string name="dartvel_shortcut_${key}_long">${_androidText(shortcut.subtitle ?? shortcut.title)}</string>');
  }
  out.writeln('</resources>');
  return out.toString();
}

String _androidKey(String id) => id.replaceAll('-', '_');

/// A string resource's text: XML-escaped, and apostrophes and quotes escaped
/// as aapt2 requires or it refuses the resource.
String _androidText(String text) => _xml(text).replaceAll('&apos;', r"\'").replaceAll('&quot;', r'\"');

const String _androidMarkStart = '            <!-- dartvel.appShortcuts: begin -->';
const String _androidMarkEnd = '            <!-- dartvel.appShortcuts: end -->';

/// [manifest] with the shortcuts meta-data inside its launcher activity, or
/// without it when [enabled] is false. Marked, so a later build replaces it.
String dvAndroidShortcutsManifest(String manifest, {required bool enabled}) {
  final RegExp block = RegExp('\n${RegExp.escape(_androidMarkStart)}.*?${RegExp.escape(_androidMarkEnd)}', dotAll: true);
  final String stripped = manifest.replaceAll(block, '');
  if (!enabled) return stripped;
  final int launcher = stripped.indexOf('android.intent.category.LAUNCHER');
  if (launcher < 0) return stripped;
  final int close = stripped.indexOf('</activity>', launcher);
  if (close < 0) return stripped;
  // Back to the start of the closing tag's line, so the block sits on its
  // own lines inside the activity.
  final int lineStart = stripped.lastIndexOf('\n', close) + 1;
  final String block2 = '$_androidMarkStart\n'
      '            <meta-data\n'
      '                android:name="android.app.shortcuts"\n'
      '                android:resource="@xml/dartvel_shortcuts" />\n'
      '$_androidMarkEnd\n';
  return '${stripped.substring(0, lineStart)}$block2${stripped.substring(lineStart)}';
}

/// The launcher activity's class, fully qualified, read from [manifest]: the
/// `<activity>` whose intent filter is MAIN/LAUNCHER.
String? dvAndroidLauncherActivity(String manifest, {required String package}) {
  final int launcher = manifest.indexOf('android.intent.category.LAUNCHER');
  if (launcher < 0) return null;
  final int open = manifest.lastIndexOf('<activity', launcher);
  if (open < 0) return null;
  final RegExpMatch? name = RegExp(r'android:name\s*=\s*"([^"]+)"').firstMatch(manifest.substring(open, launcher));
  if (name == null) return null;
  final String value = name.group(1)!;
  if (value.startsWith('.')) return '$package$value';
  return value.contains('.') ? value : '$package.$value';
}

// -- iOS ------------------------------------------------------------------------

const String _plistMarkStart = '\t<!-- dartvel.appShortcuts: begin -->';
const String _plistMarkEnd = '\t<!-- dartvel.appShortcuts: end -->';

/// [plist] with `UIApplicationShortcutItems` for [shortcuts] in its top
/// dictionary, or without it when there are none. The item type is the
/// launch link, which the app delegate hands to Dart as it is.
String dvIosShortcutItemsPlist(String plist, List<DVAppShortcut> shortcuts) {
  final RegExp block = RegExp('\n${RegExp.escape(_plistMarkStart)}.*?${RegExp.escape(_plistMarkEnd)}', dotAll: true);
  final String stripped = plist.replaceAll(block, '');
  if (shortcuts.isEmpty) return stripped;
  final StringBuffer out = StringBuffer()
    ..writeln(_plistMarkStart)
    ..writeln('\t<key>UIApplicationShortcutItems</key>')
    ..writeln('\t<array>');
  for (final DVAppShortcut shortcut in shortcuts) {
    out
      ..writeln('\t\t<dict>')
      ..writeln('\t\t\t<key>UIApplicationShortcutItemType</key>')
      ..writeln('\t\t\t<string>${_xml(shortcut.launchLink)}</string>')
      ..writeln('\t\t\t<key>UIApplicationShortcutItemTitle</key>')
      ..writeln('\t\t\t<string>${_xml(shortcut.title)}</string>');
    if (shortcut.subtitle != null) {
      out
        ..writeln('\t\t\t<key>UIApplicationShortcutItemSubtitle</key>')
        ..writeln('\t\t\t<string>${_xml(shortcut.subtitle!)}</string>');
    }
    out.writeln('\t\t</dict>');
  }
  out
    ..writeln('\t</array>')
    ..write(_plistMarkEnd);
  final int close = stripped.lastIndexOf('</dict>');
  if (close < 0) return stripped;
  return '${stripped.substring(0, close)}$out\n${stripped.substring(close)}';
}

const String _delegateMarkStart = '  // dartvel.appShortcuts: begin';
const String _delegateMarkEnd = '  // dartvel.appShortcuts: end';

/// [source] (`ios/Runner/AppDelegate.swift`) with the quick-action handler,
/// or without it when [enabled] is false.
///
/// It stores the action's launch link under [launchUrlKey], the key the
/// deep-link capture already uses and Dart already reads on launch and on
/// resume, so a quick action and a link arrive the same way. A delegate this
/// cannot read is left alone rather than mangled.
String dvIosQuickActionsDelegate(String source, {required bool enabled, required String launchUrlKey}) {
  final RegExp block = RegExp('${RegExp.escape(_delegateMarkStart)}.*?${RegExp.escape(_delegateMarkEnd)}\n', dotAll: true);
  final String stripped = source.replaceAll(block, '');
  if (!enabled) return stripped;
  if (!stripped.contains('class AppDelegate')) return stripped;
  final int close = stripped.lastIndexOf('}');
  if (close < 0) return stripped;
  final String handler = '$_delegateMarkStart\n'
      '  // GENERATED by dartvel build from dartvel.appShortcuts. Do not edit:\n'
      '  // the next build writes it again.\n'
      '  //\n'
      '  // The action\'s type is its launch link. Stored where the deep-link\n'
      '  // capture stores a link, so Dart opens it the same way: at launch,\n'
      '  // and when the application comes back to the foreground.\n'
      '  override func application(\n'
      '    _ application: UIApplication,\n'
      '    performActionFor shortcutItem: UIApplicationShortcutItem,\n'
      '    completionHandler: @escaping (Bool) -> Void\n'
      '  ) {\n'
      '    UserDefaults.standard.set(shortcutItem.type, forKey: "$launchUrlKey")\n'
      '    completionHandler(true)\n'
      '  }\n'
      '$_delegateMarkEnd\n';
  return '${stripped.substring(0, close)}$handler${stripped.substring(close)}';
}

// -- Linux --------------------------------------------------------------------

/// [desktopEntry] with an action per shortcut: `Actions=` in the main group
/// and a `[Desktop Action <id>]` group each, run as `<exec> <route>`. The
/// shared launcher reads a route argument, and a second launch hands it to
/// the running application.
String dvDesktopShortcutActions(String desktopEntry, List<DVAppShortcut> shortcuts, {required String exec}) {
  // Drop what an earlier build wrote: the Actions line and every action group.
  final List<String> kept = <String>[];
  bool inAction = false;
  for (final String line in desktopEntry.split('\n')) {
    if (line.startsWith('[Desktop Action ')) {
      inAction = true;
      continue;
    }
    if (line.startsWith('[')) inAction = false;
    if (inAction) continue;
    if (line.startsWith('Actions=')) continue;
    kept.add(line);
  }
  String entry = kept.join('\n').trimRight();
  if (shortcuts.isEmpty) return '$entry\n';
  String one(String value) => value.replaceAll(RegExp(r'[\r\n]+'), ' ');
  final String ids = shortcuts.map((DVAppShortcut shortcut) => shortcut.id).join(';');
  // Actions= belongs to [Desktop Entry]; it is the first group, so the line
  // goes before the first group that follows it, or at the end.
  final int nextGroup = entry.indexOf('\n[', entry.indexOf('[Desktop Entry]') + 1);
  entry = nextGroup < 0
      ? '$entry\nActions=$ids;'
      : '${entry.substring(0, nextGroup)}\nActions=$ids;${entry.substring(nextGroup)}';
  final StringBuffer out = StringBuffer(entry)..writeln();
  for (final DVAppShortcut shortcut in shortcuts) {
    out
      ..writeln()
      ..writeln('[Desktop Action ${shortcut.id}]')
      ..writeln('Name=${one(shortcut.title)}')
      ..writeln('Exec=${one(exec)} ${shortcut.route}');
  }
  return out.toString();
}

// -- Writers --------------------------------------------------------------------

/// What a writer did.
class DVAppShortcutsWrite {
  const DVAppShortcutsWrite({this.written = const <String>[], this.problems = const <String>[]});
  final List<String> written;
  final List<String> problems;
}

/// Writes the Android half under [root]: resources, and the meta-data in the
/// launcher activity. With no shortcuts, removes what an earlier build wrote.
DVAppShortcutsWrite dvWriteAndroidAppShortcuts(String root, List<DVAppShortcut> shortcuts, {required String? package}) {
  final File manifest = File(p.join(root, 'android', 'app', 'src', 'main', 'AndroidManifest.xml'));
  final File xml = File(p.join(root, 'android', 'app', 'src', 'main', 'res', 'xml', 'dartvel_shortcuts.xml'));
  final File strings = File(p.join(root, 'android', 'app', 'src', 'main', 'res', 'values', 'dartvel_shortcuts.xml'));
  if (!manifest.existsSync()) {
    return DVAppShortcutsWrite(problems: <String>[
      if (shortcuts.isNotEmpty) 'android/app/src/main/AndroidManifest.xml is not there, so dartvel.appShortcuts reaches nothing on Android. Run flutter create . to add the Android runner.',
    ]);
  }
  final String before = manifest.readAsStringSync();
  if (shortcuts.isEmpty) {
    final String after = dvAndroidShortcutsManifest(before, enabled: false);
    final List<String> written = <String>[];
    if (after != before) {
      manifest.writeAsStringSync(after);
      written.add('AndroidManifest.xml');
    }
    for (final File file in <File>[xml, strings]) {
      if (file.existsSync()) file.deleteSync();
    }
    return DVAppShortcutsWrite(written: written);
  }
  if (package == null) {
    return const DVAppShortcutsWrite(problems: <String>[
      'Could not read the Android application id, so dartvel.appShortcuts was not written for Android.',
    ]);
  }
  final String? activity = dvAndroidLauncherActivity(before, package: package);
  if (activity == null) {
    return const DVAppShortcutsWrite(problems: <String>[
      'AndroidManifest.xml has no launcher activity, so there is no icon to put dartvel.appShortcuts on.',
    ]);
  }
  xml.parent.createSync(recursive: true);
  xml.writeAsStringSync(dvAndroidShortcutsXml(shortcuts, package: package, activity: activity));
  strings.parent.createSync(recursive: true);
  strings.writeAsStringSync(dvAndroidShortcutStrings(shortcuts));
  final String after = dvAndroidShortcutsManifest(before, enabled: true);
  if (after != before) manifest.writeAsStringSync(after);
  return const DVAppShortcutsWrite(written: <String>[
    'res/xml/dartvel_shortcuts.xml',
    'res/values/dartvel_shortcuts.xml',
    'AndroidManifest.xml',
  ]);
}

/// Writes the iOS half under [root]: the plist items and the delegate method.
DVAppShortcutsWrite dvWriteIosAppShortcuts(String root, List<DVAppShortcut> shortcuts, {required String launchUrlKey}) {
  final File plist = File(p.join(root, 'ios', 'Runner', 'Info.plist'));
  final File delegate = File(p.join(root, 'ios', 'Runner', 'AppDelegate.swift'));
  if (!plist.existsSync()) {
    return DVAppShortcutsWrite(problems: <String>[
      if (shortcuts.isNotEmpty) 'ios/Runner/Info.plist is not there, so dartvel.appShortcuts reaches nothing on iOS. Run flutter create . to add the iOS runner.',
    ]);
  }
  final List<String> written = <String>[];
  final List<String> problems = <String>[];
  final String plistBefore = plist.readAsStringSync();
  final String plistAfter = dvIosShortcutItemsPlist(plistBefore, shortcuts);
  if (plistAfter != plistBefore) {
    plist.writeAsStringSync(plistAfter);
    written.add('ios/Runner/Info.plist');
  }
  if (delegate.existsSync()) {
    final String before = delegate.readAsStringSync();
    final String after = dvIosQuickActionsDelegate(before, enabled: shortcuts.isNotEmpty, launchUrlKey: launchUrlKey);
    if (after != before) {
      delegate.writeAsStringSync(after);
      written.add('ios/Runner/AppDelegate.swift');
    } else if (shortcuts.isNotEmpty && !before.contains('dartvel.appShortcuts: begin')) {
      problems.add('ios/Runner/AppDelegate.swift has no AppDelegate class this can add to, so a quick action opens the application at its start page.');
    }
  } else if (shortcuts.isNotEmpty) {
    problems.add('ios/Runner/AppDelegate.swift is not there, so a quick action opens the application at its start page.');
  }
  return DVAppShortcutsWrite(written: written, problems: problems);
}
