/// The JVM uncaught-exception handler for crash reporting on Android.
///
/// A Java or Kotlin crash never reaches Dart. `FlutterError.onError` and
/// `PlatformDispatcher.onError` see Dart errors; an exception thrown on a
/// native thread (a plugin's, a platform callback's, a `ContentProvider`'s)
/// ends the process without either being asked, so a crash reporter that
/// listens only there reports a healthy app to the people whose phones are
/// closing it.
///
/// The handler this writes is installed from the Context provider, which
/// Android creates before `Application.onCreate` returns -- earlier than the
/// Flutter engine, so a crash during startup is covered. It writes the crash
/// as a record in the directory the Dart crash store reads at the next launch
/// (`<filesDir>/dartvel-crashes/<id>.crash`), in that store's own format, and
/// then hands the exception to the handler that was there, so the process
/// dies the way Android intended and the system crash dialog and Play's
/// vitals still see it. Dart finds the record on the next run and sends it
/// like any other.
///
/// Frames are `jvm:<class>` with the method as the function and the line as
/// the line. R8 renames both, which is what the release's `mapping.txt`
/// (uploaded with `dartvel symbols upload`) reads back on the server.
library dartvel_cli.build.android_crash_handler;

import 'package:dartvel_core/dartvel.dart' show DVCrashFrame;

/// Where the handler is written, relative to the project root.
const String dvAndroidCrashHandlerPath =
    'android/app/src/main/java/dev/dartvel/jni/DartvelCrash.java';

/// The handler, as Java. [release] is the pubspec version, as the Dart side
/// reports it; [enabled] is whether `dartvel.crashes` has reporting on for
/// the build this is for -- when it does not, the class is still written (the
/// Context provider calls it) and installs nothing.
String dvAndroidCrashHandlerSource({
  required String release,
  required bool enabled,
}) {
  final String prefixes = DVCrashFrame.frameworkPrefixes
      .where((String prefix) => prefix.startsWith('jvm:'))
      .map((String prefix) => '"${_javaEscape(prefix.substring(4))}"')
      .join(', ');
  return _template
      .replaceAll('__ENABLED__', enabled ? 'true' : 'false')
      .replaceAll('__RELEASE__', '"${_javaEscape(release)}"')
      .replaceAll('__FRAMEWORK_PREFIXES__', prefixes);
}

/// [value] as the inside of a Java string literal: backslash, quote, and
/// everything outside printable ASCII as `\uXXXX`.
String _javaEscape(String value) {
  final StringBuffer out = StringBuffer();
  for (final int unit in value.codeUnits) {
    if (unit == 0x5c) {
      out.write(r'\\');
    } else if (unit == 0x22) {
      out.write(r'\"');
    } else if (unit < 0x20 || unit > 0x7e) {
      out.write('\\u${unit.toRadixString(16).padLeft(4, '0')}');
    } else {
      out.writeCharCode(unit);
    }
  }
  return out.toString();
}

const String _template = r'''
// GENERATED by dartvel build from dartvel.crashes. Do not edit: the next build
// writes it again.
//
// Records an uncaught Java or Kotlin exception in the directory the Dart crash
// store reads at the next launch, then hands the exception on to the handler
// that was already there, so the process ends as Android intended.
package dev.dartvel.jni;

import android.content.Context;

import java.io.File;
import java.io.FileOutputStream;
import java.nio.charset.Charset;
import java.security.SecureRandom;
import java.text.SimpleDateFormat;
import java.util.ArrayList;
import java.util.Date;
import java.util.List;
import java.util.Locale;
import java.util.TimeZone;
import java.util.concurrent.atomic.AtomicLong;

public final class DartvelCrash {
  private DartvelCrash() {}

  /// Whether dartvel.crashes has reporting on for this build.
  static final boolean ENABLED = __ENABLED__;

  /// The release Dart reports, so one release's Java and Dart crashes group
  /// and symbolicate together.
  static final String RELEASE = __RELEASE__;

  /// Frames from the platform, on nearly every stack: the same list the Dart
  /// reader keeps (DVCrashFrame.frameworkPrefixes), so a group is named by the
  /// application's frames.
  private static final String[] FRAMEWORK_PREFIXES = {__FRAMEWORK_PREFIXES__};

  /// A crash loop must not fill the device: past this many unsent records no
  /// more are written. Dart counts too (fullReportsPerRelease); this is the
  /// bound for a process that dies before Dart ever runs.
  private static final int MAX_RECORDS = 20;
  private static final int MAX_FRAMES = 100;
  private static final int MAX_CAUSE_FRAMES = 30;
  private static final int MAX_CAUSES = 5;
  private static final int MAX_MESSAGE = 2000;

  private static final AtomicLong counter = new AtomicLong();

  public static void install(Context context) {
    if (!ENABLED || context == null) return;
    install(context.getFilesDir());
  }

  static void install(File filesDir) {
    if (!ENABLED || filesDir == null) return;
    final Thread.UncaughtExceptionHandler previous =
        Thread.getDefaultUncaughtExceptionHandler();
    // Once: a second install would chain the handler onto itself and record
    // every crash twice.
    if (previous instanceof Handler) return;
    Thread.setDefaultUncaughtExceptionHandler(new Handler(filesDir, previous));
  }

  private static final class Handler implements Thread.UncaughtExceptionHandler {
    private final File filesDir;
    private final Thread.UncaughtExceptionHandler previous;

    Handler(File filesDir, Thread.UncaughtExceptionHandler previous) {
      this.filesDir = filesDir;
      this.previous = previous;
    }

    @Override
    public void uncaughtException(Thread thread, Throwable throwable) {
      try {
        record(filesDir, throwable);
      } catch (Throwable ignored) {
        // Recording must never replace the crash being recorded.
      }
      if (previous != null) previous.uncaughtException(thread, throwable);
    }
  }

  private static void record(File filesDir, Throwable throwable) throws Exception {
    final File directory = new File(filesDir, "dartvel-crashes");
    if (!directory.isDirectory() && !directory.mkdirs()) return;
    final String[] existing = directory.list();
    int unsent = 0;
    if (existing != null) {
      for (String name : existing) if (name.endsWith(".crash")) unsent++;
    }
    if (unsent >= MAX_RECORDS) return;

    final long now = System.currentTimeMillis();
    final String id = Long.toHexString(now * 1000L) + "-"
        + Long.toHexString(counter.getAndIncrement()) + "-" + randomHex(4);
    final String json = reportJson(RELEASE, installId(directory), throwable, now, id);
    final FileOutputStream stream =
        new FileOutputStream(new File(directory, id + ".crash"));
    try {
      stream.write(json.getBytes(Charset.forName("UTF-8")));
      stream.flush();
      // Written to the disk before the process goes, which is the whole of
      // what a crash handler is for.
      stream.getFD().sync();
    } finally {
      stream.close();
    }
  }

  /// The install id Dart keeps beside the records, or a new one written there
  /// in the shape Dart accepts, so a crash before Dart's first run and the
  /// ones after it belong to one install.
  private static String installId(File directory) {
    final File file = new File(directory, "install-id");
    try {
      if (file.isFile()) {
        final byte[] bytes = new byte[(int) Math.min(file.length(), 128)];
        final java.io.FileInputStream in = new java.io.FileInputStream(file);
        try {
          final int read = in.read(bytes);
          final String stored = new String(bytes, 0, Math.max(read, 0),
              Charset.forName("UTF-8")).trim();
          if (stored.matches("^[0-9a-f]{32}$")) return stored;
        } finally {
          in.close();
        }
      }
    } catch (Throwable ignored) {
      // A new id below.
    }
    final String created = randomHex(16);
    try {
      final FileOutputStream out = new FileOutputStream(file);
      try {
        out.write(created.getBytes(Charset.forName("UTF-8")));
      } finally {
        out.close();
      }
    } catch (Throwable ignored) {
      // This crash still has an id.
    }
    return created;
  }

  private static String randomHex(int bytes) {
    final byte[] random = new byte[bytes];
    new SecureRandom().nextBytes(random);
    final StringBuilder out = new StringBuilder();
    for (byte b : random) out.append(String.format("%02x", b & 0xff));
    return out.toString();
  }

  /// One frame of the record: the class, the method and the line, and the
  /// text of the Dart `DVCrashFrame` it becomes.
  private static final class Frame {
    final String function;
    final String uri;
    final int line;

    Frame(String function, String uri, int line) {
      this.function = function;
      this.uri = uri;
      this.line = line;
    }
  }

  /// The crash record, as the JSON `DVCrashReport.fromJson` reads. Pure: no
  /// Android, no files, so it can be run and compared with the Dart reader.
  static String reportJson(
      String release, String installId, Throwable throwable, long now, String id) {
    final List<Frame> frames = new ArrayList<Frame>();
    addFrames(frames, throwable.getStackTrace(), MAX_FRAMES);
    Throwable cause = throwable.getCause();
    for (int depth = 0; cause != null && depth < MAX_CAUSES && cause != throwable; depth++) {
      frames.add(new Frame("Caused by: " + cause.getClass().getName(), null, -1));
      addFrames(frames, cause.getStackTrace(), MAX_CAUSE_FRAMES);
      final Throwable next = cause.getCause();
      if (next == cause) break;
      cause = next;
    }

    final String errorType = throwable.getClass().getName();
    String message = throwable.getMessage();
    if (message == null) message = "";
    if (message.length() > MAX_MESSAGE) message = message.substring(0, MAX_MESSAGE);

    final SimpleDateFormat format =
        new SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss.SSS'Z'", Locale.US);
    format.setTimeZone(TimeZone.getTimeZone("UTC"));

    final StringBuilder out = new StringBuilder();
    out.append("{\"v\":1,\"id\":").append(quote(id));
    out.append(",\"kind\":\"fatal\",\"errorType\":").append(quote(errorType));
    out.append(",\"message\":").append(quote(message));
    out.append(",\"frames\":[");
    for (int i = 0; i < frames.size(); i++) {
      final Frame frame = frames.get(i);
      if (i > 0) out.append(',');
      out.append("{\"function\":").append(quote(frame.function));
      if (frame.uri != null) out.append(",\"uri\":").append(quote(frame.uri));
      if (frame.line >= 0) out.append(",\"line\":").append(frame.line);
      out.append('}');
    }
    out.append("],\"fingerprint\":").append(quote(fingerprint(errorType, frames)));
    out.append(",\"context\":{\"release\":").append(quote(release));
    out.append(",\"installId\":").append(quote(installId));
    out.append(",\"platform\":\"android\",\"locale\":")
        .append(quote(Locale.getDefault().toString().replace('_', '-')));
    out.append("},\"occurredAt\":").append(quote(format.format(new Date(now))));
    out.append(",\"breadcrumbs\":[]}");
    return out.toString();
  }

  private static void addFrames(List<Frame> into, StackTraceElement[] stack, int limit) {
    final int count = Math.min(stack.length, limit);
    for (int i = 0; i < count; i++) {
      final StackTraceElement element = stack[i];
      into.add(new Frame(element.getMethodName(), "jvm:" + element.getClassName(),
          element.getLineNumber()));
    }
  }

  private static boolean isFramework(Frame frame) {
    if (frame.uri == null || !frame.uri.startsWith("jvm:")) return false;
    final String className = frame.uri.substring(4);
    for (String prefix : FRAMEWORK_PREFIXES) {
      if (className.startsWith(prefix)) return true;
    }
    return false;
  }

  /// DVCrashFingerprint.of, in Java: the error type and the first five frames
  /// that are the application's (all of them when none are), hashed with two
  /// FNV-1a passes. The same group in Java and in Dart, or one bug is two.
  private static String fingerprint(String errorType, List<Frame> frames) {
    final List<Frame> own = new ArrayList<Frame>();
    for (Frame frame : frames) if (!isFramework(frame)) own.add(frame);
    final List<Frame> used = own.isEmpty() ? frames : own;
    final StringBuilder text = new StringBuilder(errorType);
    for (int i = 0; i < Math.min(5, used.size()); i++) {
      final Frame frame = used.get(i);
      text.append('\n').append(frame.uri == null ? "" : frame.uri)
          .append('#').append(frame.function);
    }
    int a = 0x811c9dc5;
    int b = 0x01234567;
    final int prime = 0x01000193;
    for (int i = 0; i < text.length(); i++) {
      final int unit = text.charAt(i);
      a = (a ^ (unit & 0xff)) * prime;
      a = (a ^ (unit >> 8)) * prime;
      b = (b ^ (unit & 0xff)) * prime;
      b = (b ^ (unit >> 8)) * prime;
    }
    return String.format("%08x%08x", a, b);
  }

  /// [value] as a JSON string: ASCII only, so no encoding can change it.
  private static String quote(String value) {
    final StringBuilder out = new StringBuilder("\"");
    for (int i = 0; i < value.length(); i++) {
      final char c = value.charAt(i);
      switch (c) {
        case '"': out.append("\\\""); break;
        case '\\': out.append("\\\\"); break;
        case '\n': out.append("\\n"); break;
        case '\r': out.append("\\r"); break;
        case '\t': out.append("\\t"); break;
        default:
          if (c < 0x20 || c > 0x7e) out.append(String.format("\\u%04x", (int) c));
          else out.append(c);
      }
    }
    return out.append('"').toString();
  }
}
''';
