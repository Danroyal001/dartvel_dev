/// The Apple half of a home widget: a WidgetKit extension, generated.
///
/// Android's half is four things that cannot be added at run time, and this
/// is the same shape for a different platform: a separate bundle with its own
/// Info.plist, its own entitlements, and Swift that WidgetKit loads. None of
/// it can be created while the application is running, so all of it is the
/// build's.
///
/// What WidgetKit will and will not do is worth stating, because the
/// temptation is to claim more. A widget's view is SwiftUI drawn by the
/// system, in a process that is not the application and cannot host a
/// Flutter engine — the same wall Android's RemoteViews puts up, for the
/// same reason. So the generated widget draws its own small view from data
/// the application left in a shared container, and the tap opens the page
/// the widget was generated for. That is what the specification asks of a
/// home widget, and it is all this claims.
library;

import 'package:dartvel_core/dartvel.dart' show DVHomeWidgetSpec;

/// The extension target's name, used for its directory, its bundle and its
/// build settings. Named once because the pbxproj, the Info.plist path and
/// the embed phase must agree and there is nothing to notice if they drift.
const String dvAppleWidgetExtensionName = 'DartvelWidgets';

/// The build setting the Info.plist reads the App Group out of.
///
/// The group is per application, so it cannot be a constant in the plist;
/// and the Swift cannot take it as an argument, because an extension is
/// launched by the system rather than called by the app. A build setting
/// substituted into the plist and read back at run time is how Apple's own
/// templates carry a value that varies by project.
const String dvAppleAppGroupSetting = 'DARTVEL_APP_GROUP';

/// The App Group [bundleId]'s application and its widgets share.
///
/// Per application, for the reason an Android provider authority is: a
/// constant here means the second Dartvel app installed reads the first
/// one's container, or is refused the entitlement and shows a placeholder
/// nobody can explain.
String dvAppleAppGroup(String bundleId) => 'group.$bundleId.dartvelwidgets';

/// The kind string WidgetKit addresses this widget by.
///
/// Two widgets sharing a kind is a reload of the wrong one and a timeline
/// written into the wrong one, with no error at either end.
String dvAppleWidgetKind(String id) =>
    'dartvel.widget.${id.replaceAll(RegExp('[^A-Za-z0-9]'), '_')}';

/// [value] as the body of a Swift string literal.
///
/// A widget's title is a person's words and can hold a quote or a backslash.
/// Either one written straight into the generated Swift is a file that does
/// not compile, at the end of a build that reported success until Xcode ran.
String _swift(String value) => value
    .replaceAll(r'\', r'\\')
    .replaceAll('"', r'\"')
    .replaceAll('\n', r'\n');

/// [widget]'s name as a Swift type.
///
/// Widget ids and names come from Dart and may carry characters Swift will
/// not take. `struct next-shiftWidget` is a file that does not parse, from a
/// build that reported success right up to the moment Xcode ran.
String dvAppleWidgetSwiftName(DVHomeWidgetSpec widget) {
  final StringBuffer out = StringBuffer();
  bool upperNext = true;
  for (final String character in widget.name.split('')) {
    final bool allowed = RegExp('[A-Za-z0-9]').hasMatch(character);
    if (!allowed) {
      upperNext = true;
      continue;
    }
    out.write(upperNext ? character.toUpperCase() : character);
    upperNext = false;
  }
  final String name = out.toString();
  // A Swift identifier may not begin with a digit, and a name that does is
  // a compile error rather than a rename.
  return RegExp('^[0-9]').hasMatch(name) ? 'Widget$name' : name;
}

/// The whole extension, as one Swift file.
///
/// One file rather than one per widget because a WidgetBundle has to name
/// them all in one place anyway, and two files that disagree about the set
/// is the failure this shape removes.
///
/// [scheme] is the application's own URL scheme. A constant here would have
/// two Dartvel applications on one device both registering it, which is a
/// race the second one loses without saying so.
String dvAppleHomeWidgetSource(List<DVHomeWidgetSpec> widgets, String scheme) {
  // An @main WidgetBundle with nothing in it is an extension that installs,
  // takes a place in the gallery, and offers nothing.
  if (widgets.isEmpty) return '';

  final StringBuffer out = StringBuffer()
    ..writeln('// GENERATED by dartvel build from @DVHomeWidget. Do not edit:')
    ..writeln('// the next build writes it again.')
    ..writeln('//')
    ..writeln('// SwiftUI rather than the Flutter tree, because a widget is')
    ..writeln('// drawn by the system in a process that is not the')
    ..writeln('// application and cannot host a Flutter engine. What the')
    ..writeln('// specification asks -- that a home widget can launch and')
    ..writeln('// navigate to a page -- is what the tap does.')
    ..writeln('import SwiftUI')
    ..writeln('import WidgetKit')
    ..writeln()
    ..writeln('/// The container the application and this extension share.')
    ..writeln('///')
    ..writeln('/// Read from the bundle rather than written in, because the')
    ..writeln('/// group is per application and this file is not.')
    ..writeln('let dartvelAppGroup: String = (Bundle.main.object(')
    ..writeln('    forInfoDictionaryKey: "$dvAppleAppGroupSetting")')
    ..writeln('    as? String) ?? ""')
    ..writeln()
    ..writeln('/// What the application last wrote for a widget, or nothing.')
    ..writeln('///')
    ..writeln('/// UserDefaults(suiteName:) is the group container. The')
    ..writeln('/// standard defaults in an extension are the extension\'s own,')
    ..writeln('/// which the application never writes to, so a widget reading')
    ..writeln('/// them shows its placeholder forever.')
    ..writeln('func dartvelWidgetText(_ kind: String) -> String? {')
    ..writeln('    UserDefaults(suiteName: dartvelAppGroup)?')
    ..writeln('        .string(forKey: "dartvel.widget.text.\\(kind)")')
    ..writeln('}')
    ..writeln()
    ..writeln('/// The widget background, on the two eras of WidgetKit.')
    ..writeln('///')
    ..writeln('/// iOS 17 requires a widget built against its SDK to declare')
    ..writeln('/// its background through containerBackground; a widget that')
    ..writeln('/// does not is drawn without one. The API does not exist')
    ..writeln('/// before 17, so both are here rather than one and a')
    ..writeln('/// deployment target raised to exclude the devices this is')
    ..writeln('/// most likely to run on.')
    ..writeln('extension View {')
    ..writeln('    ')
    ..writeln('    func dartvelWidgetSurface() -> some View {')
    ..writeln('        if #available(iOS 17.0, macOS 14.0, *) {')
    ..writeln('            self.containerBackground(.fill.tertiary, for: .widget)')
    ..writeln('        } else {')
    ..writeln('            self.padding()')
    ..writeln('        }')
    ..writeln('    }')
    ..writeln('}')
    ..writeln()
    ..writeln('struct DartvelEntry: TimelineEntry {')
    ..writeln('    let date: Date')
    ..writeln('    let text: String')
    ..writeln('}')
    ..writeln();

  for (final DVHomeWidgetSpec widget in widgets) {
    final String type = dvAppleWidgetSwiftName(widget);
    final String kind = dvAppleWidgetKind(widget.id);
    out
      ..writeln('struct ${type}Provider: TimelineProvider {')
      ..writeln('    func placeholder(in context: Context) -> DartvelEntry {')
      ..writeln('        DartvelEntry(date: Date(), text: "${_swift(widget.label)}")')
      ..writeln('    }')
      ..writeln()
      ..writeln('    func getSnapshot(in context: Context,')
      ..writeln('                     completion: @escaping (DartvelEntry) -> Void) {')
      ..writeln('        completion(DartvelEntry(date: Date(),')
      ..writeln('            text: dartvelWidgetText("$kind") ?? "${_swift(widget.label)}"))')
      ..writeln('    }')
      ..writeln()
      ..writeln('    func getTimeline(in context: Context,')
      ..writeln('                     completion: @escaping (Timeline<DartvelEntry>) -> Void) {')
      ..writeln('        let entry = DartvelEntry(date: Date(),')
      ..writeln('            text: dartvelWidgetText("$kind") ?? "${_swift(widget.label)}")')
      // Not .never: a widget that shows what it showed the day it was
      // placed is a legitimate policy and the wrong default for an
      // application's own data. WidgetKit treats this as a request, not a
      // guarantee, which is the platform and not a shortcut.
      ..writeln('        let next = Calendar.current.date(')
      ..writeln('            byAdding: .minute, value: 15, to: Date()) ?? Date()')
      ..writeln('        completion(Timeline(entries: [entry], policy: .after(next)))')
      ..writeln('    }')
      ..writeln('}')
      ..writeln()
      ..writeln('struct ${type}View: View {')
      ..writeln('    var entry: DartvelEntry')
      ..writeln()
      ..writeln('    var body: some View {')
      ..writeln('        VStack(alignment: .leading, spacing: 4) {')
      ..writeln('            Text("${_swift(widget.label)}")')
      ..writeln('                .font(.caption)')
      ..writeln('                .foregroundColor(Color.secondary)')
      ..writeln('            Text(entry.text)')
      ..writeln('                .font(.headline)')
      ..writeln('        }')
      ..writeln('        .frame(maxWidth: .infinity, maxHeight: .infinity,')
      ..writeln('               alignment: .topLeading)')
      ..writeln('        .dartvelWidgetSurface()')
      // The route this widget was generated for. A widgetURL with no path
      // opens the application's home screen, which looks like it worked.
      ..writeln('        .widgetURL(URL(string:')
      ..writeln('            "$scheme://widget${widget.route}"))')
      ..writeln('    }')
      ..writeln('}')
      ..writeln()
      ..writeln('struct $type: Widget {')
      ..writeln('    var body: some WidgetConfiguration {')
      ..writeln('        StaticConfiguration(kind: "$kind",')
      ..writeln('                            provider: ${type}Provider()) { entry in')
      ..writeln('            ${type}View(entry: entry)')
      ..writeln('        }')
      ..writeln('        .configurationDisplayName("${_swift(widget.label)}")')
      ..writeln('        .supportedFamilies([.systemSmall, .systemMedium])')
      ..writeln('    }')
      ..writeln('}')
      ..writeln();
  }

  out
    ..writeln('@main')
    ..writeln('struct DartvelWidgetBundle: WidgetBundle {')
    ..writeln('    var body: some Widget {');
  for (final DVHomeWidgetSpec widget in widgets) {
    out.writeln('        ${dvAppleWidgetSwiftName(widget)}()');
  }
  out
    ..writeln('    }')
    ..writeln('}');

  return out.toString();
}

/// The extension bundle's Info.plist.
///
/// NSExtensionPointIdentifier is the line that matters and the one with no
/// symptom when it is missing: the target compiles, links, embeds and
/// installs, and the widget never appears in the gallery, because the system
/// never asks a bundle it does not recognise for anything.
String dvAppleHomeWidgetInfoPlist() => '''
<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by dartvel build. Do not edit: the next build writes it
     again. -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key>
    <string>\$(DEVELOPMENT_LANGUAGE)</string>
    <key>CFBundleDisplayName</key>
    <string>$dvAppleWidgetExtensionName</string>
    <key>CFBundleExecutable</key>
    <string>\$(EXECUTABLE_NAME)</string>
    <key>CFBundleIdentifier</key>
    <string>\$(PRODUCT_BUNDLE_IDENTIFIER)</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleName</key>
    <string>\$(PRODUCT_NAME)</string>
    <!-- XPC!, not APPL. An extension declaring itself an application is a
         bundle the installer refuses, with a message about the containing
         app rather than about this line. -->
    <key>CFBundlePackageType</key>
    <string>XPC!</string>
    <key>CFBundleShortVersionString</key>
    <string>\$(FLUTTER_BUILD_NAME)</string>
    <key>CFBundleVersion</key>
    <string>\$(FLUTTER_BUILD_NUMBER)</string>
    <!-- The App Group, substituted from the build setting because it is per
         application and this file is not. The Swift reads it back from
         here. -->
    <key>$dvAppleAppGroupSetting</key>
    <string>\$($dvAppleAppGroupSetting)</string>
    <key>NSExtension</key>
    <dict>
        <key>NSExtensionPointIdentifier</key>
        <string>com.apple.widgetkit-extension</string>
    </dict>
</dict>
</plist>
''';

/// The entitlements the extension is signed with.
///
/// Without the group, the extension reads its own container -- which is
/// empty, because the application writes to the group's -- and renders the
/// placeholder forever, on somebody's home screen rather than in the build.
String dvAppleHomeWidgetEntitlements(String appGroup) => '''
<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by dartvel build. Do not edit: the next build writes it
     again. -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>com.apple.security.application-groups</key>
    <array>
        <string>$appGroup</string>
    </array>
</dict>
</plist>
''';
