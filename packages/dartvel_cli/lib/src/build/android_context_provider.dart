/// How Dart gets hold of the Android application Context.
///
/// Everything worth binding on Android is reached through
/// `Context.getSystemService`, and Dart has no Activity to ask.
///
/// The bindings were written against `GetApplicationContext()`, which
/// package:jni declares in `dartjni.h` and never defines -- the header has
/// the declaration, the C file has no implementation, and an emulator run
/// said so in the end: "undefined symbol: GetApplicationContext". Reading a
/// header without checking there was a body behind it is how every Android
/// binding shipped dead while the capability list claimed them.
///
/// A ContentProvider is the supported answer, and it is what androidx.startup
/// is built on: Android creates every declared provider before
/// `Application.onCreate` returns and hands it a Context. No hidden API, no
/// `ActivityThread` -- which is absent from the public android.jar and is why
/// jnigen could not bind it -- and nothing that waits for an Activity.
library dartvel_cli.build.android_context_provider;

/// Where the provider's source is written, relative to the project root.
const String dvAndroidContextProviderPath =
    'android/app/src/main/java/dev/dartvel/jni/DartvelContext.java';

/// The class Dart looks up at run time, in JNI's slash-separated form.
///
/// A fixed package rather than the application's own: Dart finds this class
/// by name, so the name has to be the same in every application, and the
/// application's package is an applicationId the framework cannot know at
/// the point the lookup is compiled.
const String dvAndroidContextClass = 'dev/dartvel/jni/DartvelContext';

/// The provider itself.
String dvAndroidContextProviderSource() => '''
package dev.dartvel.jni;

// GENERATED by dartvel build. Holds the application Context so Dart can
// reach it over JNI.
//
// A ContentProvider because Android creates every declared provider before
// Application.onCreate returns, and hands it a Context. That is earlier than
// any Activity and earlier than the Flutter engine, so a binding registered
// during startup has something to bind to.

import android.content.ContentProvider;
import android.content.ContentValues;
import android.content.Context;
import android.database.Cursor;
import android.net.Uri;

public final class DartvelContext extends ContentProvider {
  private static Context sContext;

  /// The application Context, or null before Android has created this.
  public static Context context() {
    return sContext;
  }

  @Override
  public boolean onCreate() {
    Context context = getContext();
    // The application's, not the provider's. They are the same object on
    // every version anyone runs, but not by contract, and asking is one word.
    sContext = context == null ? null : context.getApplicationContext();
    return true;
  }

  // A ContentProvider is abstract and these are why. Nothing queries this
  // one -- it is not exported and has no data -- but it has to compile.

  @Override
  public Cursor query(Uri uri, String[] projection, String selection,
      String[] selectionArgs, String sortOrder) {
    return null;
  }

  @Override
  public String getType(Uri uri) {
    return null;
  }

  @Override
  public Uri insert(Uri uri, ContentValues values) {
    return null;
  }

  @Override
  public int delete(Uri uri, String selection, String[] selectionArgs) {
    return 0;
  }

  @Override
  public int update(Uri uri, ContentValues values, String selection,
      String[] selectionArgs) {
    return 0;
  }
}
''';

const String _markStart = '        <!-- dartvel.context: start -->\n';
const String _markEnd = '        <!-- dartvel.context: end -->\n';

/// [manifest] with the provider declared inside its `<application>`.
///
/// Marked and rewritten rather than appended, so running the build twice
/// leaves one provider rather than two -- Android refuses a package that
/// declares the same authority twice.
String dvAndroidContextProviderManifest(String manifest) {
  final int existing = manifest.indexOf(_markStart);
  final String stripped = existing < 0
      ? manifest
      : manifest.substring(0, existing) +
          manifest.substring(
              manifest.indexOf(_markEnd, existing) + _markEnd.length);

  // Inside <application>: a provider declared outside it is a manifest the
  // packager refuses, with an error about the XML rather than about this.
  final int close = stripped.indexOf('</application>');
  if (close < 0) return stripped;
  final int lineStart = stripped.lastIndexOf('\n', close) + 1;

  final StringBuffer out = StringBuffer()
    ..write(_markStart)
    ..writeln('        <!-- Holds the application Context for Dartvel\'s JNI')
    ..writeln('             bindings. Created before Application.onCreate')
    ..writeln('             returns, which is earlier than any Activity. -->')
    ..writeln('        <provider')
    ..writeln('            android:name="dev.dartvel.jni.DartvelContext"')
    // Per application, or two Dartvel apps cannot be installed side by side:
    // Android refuses the second with a conflicting-provider error that
    // names neither of them helpfully.
    ..writeln(r'            android:authorities="${applicationId}.dartvel'
        r'context"')
    // It exists to hold a Context. A provider other applications can reach
    // is an attack surface for nothing.
    ..writeln('            android:exported="false"')
    // Before anything else Dartvel might add.
    ..writeln('            android:initOrder="1000"/>')
    ..write(_markEnd);

  return '${stripped.substring(0, lineStart)}${out.toString()}'
      '${stripped.substring(lineStart)}';
}
