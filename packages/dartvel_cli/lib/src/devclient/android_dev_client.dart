/// What `dartvel build android --profile development` writes so the build can
/// be paired with `dartvel dev --dev-client` and hot reloaded over the network.
///
/// A Flutter debug build already runs the Dart VM service: it is how
/// `flutter run` reloads an app over USB. On a phone scanning a QR code there
/// is no USB, and the VM service listens only on the phone's loopback. So the
/// build gets a small tunnel: the phone dials out to the dev server, proves
/// nothing, and asks the server to prove it holds the key from the pairing
/// link; then the dev server reaches the VM service back through that
/// connection, and `flutter attach` does the rest -- incremental kernel,
/// hot reload, hot restart -- exactly as it does over USB.
///
/// The tunnel is Java on a Java thread, not Dart, because a hot restart kills
/// every Dart isolate and a tunnel inside one would cut the connection the
/// restart is travelling over. It lives in the debug source set, so a profile
/// or release build does not compile it.
library dartvel_cli.devclient.android_dev_client;

import 'dart:convert';

