// Called from Dart with this app's VM service URI. Returns the status, in a
// buffer this file owns.
__declspec(dllexport) const char* @@VM_SERVICE@@(const char* uri) {
  std::lock_guard<std::recursive_mutex> guard(Lock());
  // The first URI this process reported: a restarted isolate can report the
  // dev machine's DDS address instead of this app's own service.
  if (VmService().empty() && uri != nullptr) VmService() = uri;
  if (Link().empty()) Link() = LaunchLink();
  if (!Link().empty() && !VmService().empty() && CurrentTunnel() == nullptr) {
    std::string error;
    std::shared_ptr<Tunnel> tunnel = Tunnel::FromLink(Link(), VmService(), &error);
    if (tunnel == nullptr) {
      SetStatus("the pairing link could not be used: " + error);
    } else {
      CurrentTunnel() = tunnel;
      tunnel->Start();
    }
  }
  static char status[2048];
  std::lock_guard<std::mutex> status_guard(StatusLock());
  strncpy_s(status, sizeof(status), StatusText().c_str(), _TRUNCATE);
  return status;
}

// The dev server's host, for reaching the backend it runs beside; NULL
// before a tunnel starts.
__declspec(dllexport) const char* @@SERVER_HOST@@(void) {
  std::lock_guard<std::recursive_mutex> guard(Lock());
  if (CurrentTunnel() == nullptr) return nullptr;
  static char host[512];
  strncpy_s(host, sizeof(host), CurrentTunnel()->host().c_str(), _TRUNCATE);
  return host;
}

