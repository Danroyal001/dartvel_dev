// The pairing link the process was launched with, or empty.
std::string LaunchLink() {
  int count = 0;
  LPWSTR* arguments = CommandLineToArgvW(GetCommandLineW(), &count);
  std::string link;
  if (arguments == nullptr) return link;
  for (int i = 1; i < count; i++) {
    const std::string argument = Narrow(arguments[i]);
    if (IsPairLink(argument)) link = argument;
  }
  LocalFree(arguments);
  return link;
}

