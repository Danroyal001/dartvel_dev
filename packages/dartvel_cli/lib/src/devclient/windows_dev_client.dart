/// What `dartvel build windows --profile development` writes so the build
/// pairs with `dartvel dev` and hot reloads over the network.
///
/// The design is the other platforms' (see android_dev_client.dart): the app
/// dials out to the dev server over TLS pinned to the key in the pairing link,
/// and the dev server reaches the app's Dart VM service back through the
/// connection so `flutter attach` can reload it. Here the tunnel is C++ on
/// Winsock and Schannel, on threads of its own, which a hot restart -- that
/// kills every Dart isolate -- does not touch.
///
/// As on Linux, the link is the launch flag: the `dartvel-dev://pair?...` link
/// `dartvel dev` prints, passed as an argument.
///
/// Two things are written: `windows/runner/dartvel_dev_client.cpp`, whose body
/// is inside `#ifdef _DEBUG`, and a marked line in the runner's
/// CMakeLists.txt that adds it to the Debug configuration only. Windows builds
/// with a multi-configuration generator, so the configuration is chosen by a
/// generator expression; CMAKE_BUILD_TYPE is empty there. A profile or release
/// build takes the line back out.
library dartvel_cli.devclient.windows_dev_client;

