/// Where the tunnel is written, relative to the project root.
const String dvWindowsDevTunnelPath = 'windows/runner/dartvel_dev_client.cpp';

/// The runner's CMake file the line goes into.
const String dvWindowsRunnerCmakePath = 'windows/runner/CMakeLists.txt';

const String _cmakeStart = '# dartvel.devclient: begin\n';
const String _cmakeEnd = '# dartvel.devclient: end\n';

/// [cmake], the runner's CMakeLists.txt, with the tunnel compiled into the
/// Debug configuration -- or, when not [enabled], without it.
String dvWindowsRunnerCmakeWithDevClient(
  String cmake, {
  required bool enabled,
}) {
  final RegExp block = RegExp(
    '${RegExp.escape(_cmakeStart)}.*?${RegExp.escape(_cmakeEnd)}',
    dotAll: true,
  );
  final String stripped = cmake.replaceAll(block, '');
  if (!enabled) return stripped;
  const String insert =
      '$_cmakeStart'
      '# A development build pairs with `dartvel dev`. The Debug configuration\n'
      '# only: a generator expression, because this generator builds every\n'
      '# configuration from one project.\n'
      r'target_sources(${BINARY_NAME} PRIVATE "$<$<CONFIG:Debug>:dartvel_dev_client.cpp>")'
      '\n'
      '$_cmakeEnd';
  final int start = stripped.indexOf(r'add_executable(${BINARY_NAME}');
  if (start < 0) return stripped;
  final int close = stripped.indexOf('\n)\n', start);
  if (close < 0) return stripped;
  final int at = close + 3;
  return '${stripped.substring(0, at)}$insert${stripped.substring(at)}';
}

String _cString(String value) =>
    value.replaceAll(r'\', r'\\').replaceAll('"', r'\"');

/// The C++ tunnel, recording [manifest]: what this build compiled in.
String dvWindowsDevTunnelSource(DVDevClientManifest manifest) => _source
    .replaceAll('@@MANIFEST@@', _cString(jsonEncode(manifest.toJson())))
    .replaceAll('@@PATH@@', dvDevClientTunnelPath)
