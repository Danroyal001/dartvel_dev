// The pairing link the process was launched with, or empty.
std::string LaunchLink() {
  std::ifstream cmdline("/proc/self/cmdline", std::ios::binary);
  std::string argument;
  std::string link;
  while (std::getline(cmdline, argument, '\\0')) {
    if (IsPairLink(argument)) link = argument;
  }
  return link;
}

