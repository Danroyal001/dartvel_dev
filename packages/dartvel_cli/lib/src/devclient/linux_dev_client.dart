/// What `dartvel build linux --profile development` writes so the build pairs
/// with `dartvel dev` and hot reloads over the network.
///
/// The design is Android's and iOS's (see android_dev_client.dart and
/// apple_dev_client.dart): the app dials out to the dev server over TLS pinned
/// to the key in the pairing link, and the dev server reaches the app's Dart
/// VM service back through the connection so `flutter attach` can reload it.
/// Here the tunnel is C++ on GIO, running on threads of its own, which a hot
/// restart -- that kills every Dart isolate -- does not touch.
///
/// A desktop application is not opened by scanning a code, so the link is its
/// launch flag: the `dartvel-dev://pair?...` link `dartvel dev` prints, passed
/// as an argument, which is also how a desktop environment hands an
/// application a URL it is registered for.
///
///     ./build/linux/x64/debug/bundle/<app> 'dartvel-dev://pair?...'
///
/// Two things are written, both Debug-only: `linux/runner/dartvel_dev_client.cc`,
/// whose body is inside `#ifndef NDEBUG`, and a marked block in
/// `linux/runner/CMakeLists.txt` that compiles it, and exports its functions to
/// Dart's FFI lookup, only when CMAKE_BUILD_TYPE is Debug. A profile or
/// release build takes the block back out.
