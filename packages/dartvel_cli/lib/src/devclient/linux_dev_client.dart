const String _cmakeEnd = '# dartvel.devclient: end\n';

/// [cmake], the runner's CMakeLists.txt, with the tunnel compiled into a
/// Debug build -- or, when not [enabled], without it.
String dvLinuxRunnerCmakeWithDevClient(String cmake, {required bool enabled}) {
  final RegExp block = RegExp(
    '${RegExp.escape(_cmakeStart)}.*?${RegExp.escape(_cmakeEnd)}',
    dotAll: true,
  );
  final String stripped = cmake.replaceAll(block, '');
  if (!enabled) return stripped;
  const String insert =
      '$_cmakeStart'
      '# A development build pairs with `dartvel dev`: the tunnel, and its\n'
      '# functions exported to Dart\'s FFI lookup. Debug builds only.\n'
      'if(CMAKE_BUILD_TYPE STREQUAL "Debug")\n'
      '  target_sources(\${BINARY_NAME} PRIVATE "dartvel_dev_client.cc")\n'
      '  set_target_properties(\${BINARY_NAME} PROPERTIES ENABLE_EXPORTS ON)\n'
      'endif()\n'
      '$_cmakeEnd';
  // After the application target exists, and before anything else touches
  // it: the line after add_executable's closing parenthesis.
  final int start = stripped.indexOf(r'add_executable(${BINARY_NAME}');
  if (start < 0) return stripped;
  final int close = stripped.indexOf('\n)\n', start);
  if (close < 0) return stripped;
  final int at = close + 3;
  return '${stripped.substring(0, at)}$insert${stripped.substring(at)}';
}

String _cString(String value) =>
    value.replaceAll(r'\', r'\\').replaceAll('"', r'\"');

