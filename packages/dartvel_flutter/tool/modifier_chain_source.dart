// Reads DVModifier's public chain methods out of dartvel_flutter.dart, and
// writes lib/src/primitives/modifier_chain.dart from them:
//
//   dart run tool/modifier_chain_source.dart
//
// test/modifier_chain_test.dart fails when the checked-in mixin and
// DVModifier disagree, so the chain on DVText/DVBox never drifts from it.
import 'dart:io';

/// One `DVModifier name(params)` method of DVModifier.
class ChainMethod {
  ChainMethod(this.name, this.parameters);

  final String name;

  /// The parameter list as written, whitespace collapsed, without the
  /// outer parentheses.
  final String parameters;

  /// The call forwarding every parameter: `value`, `horizontal: horizontal`.
  String get arguments => splitParameters(parameters).map((ChainParameter p) => p.named ? '${p.name}: ${p.name}' : p.name).join(', ');
}

class ChainParameter {
  ChainParameter(this.name, {required this.named});
  final String name;
  final bool named;
}

/// Methods that are not a step in a chain.
const Set<String> notChained = <String>{'merge'};

/// Every public method of `class DVModifier` returning DVModifier.
List<ChainMethod> modifierMethods(String librarySource) {
  final int start = librarySource.indexOf('\nclass DVModifier {');
  if (start < 0) throw StateError('class DVModifier not found');
  final int end = _matching(librarySource, librarySource.indexOf('{', start));
  final String body = librarySource.substring(start, end);
  final List<ChainMethod> methods = <ChainMethod>[];
  for (final RegExpMatch match in RegExp(r'\n  DVModifier ([a-z][A-Za-z0-9]*)\(').allMatches(body)) {
    final String name = match.group(1)!;
    if (notChained.contains(name)) continue;
    final int open = match.end - 1;
    final int close = _matching(body, open);
    final String parameters = body
        .substring(open + 1, close)
        .split('\n')
        .map((String line) => line.replaceFirst(RegExp(r'//.*$'), ''))
        .join(' ')
        .replaceAll(RegExp(r'\s+'), ' ')
        .replaceAllMapped(RegExp(r',\s*([}\]])'), (Match m) => m.group(1)!)
        .replaceAllMapped(RegExp(r'([{\[])\s+'), (Match m) => m.group(1)!)
        .replaceAllMapped(RegExp(r'\s+([}\]])'), (Match m) => m.group(1)!)
        .trim()
        .replaceFirst(RegExp(r',$'), '');
    methods.add(ChainMethod(name, parameters));
  }
  return methods;
}

/// The index of the bracket closing the one at [open].
int _matching(String source, int open) {
  const Map<String, String> pairs = <String, String>{'(': ')', '{': '}', '[': ']'};
  final List<String> stack = <String>[];
  String? quote;
  for (int i = open; i < source.length; i++) {
    final String c = source[i];
    if (quote != null) {
      if (c == '\\') {
        i++;
      } else if (c == quote) {
        quote = null;
      }
      continue;
    }
    if (c == "'" || c == '"') {
      quote = c;
    } else if (c == '/' && i + 1 < source.length && source[i + 1] == '/') {
      i = source.indexOf('\n', i);
    } else if (pairs.containsKey(c)) {
      stack.add(pairs[c]!);
    } else if (stack.isNotEmpty && c == stack.last) {
      stack.removeLast();
      if (stack.isEmpty) return i;
    }
  }
  throw StateError('unbalanced bracket at $open');
}

/// Splits a parameter list at its top-level commas.
List<ChainParameter> splitParameters(String parameters) {
  final List<ChainParameter> result = <ChainParameter>[];
  int depth = 0;
  bool named = false;
  final StringBuffer current = StringBuffer();
  void flush() {
    String text = current.toString().trim();
    current.clear();
    if (text.isEmpty) return;
    // Drop a default value at depth zero.
    int d = 0;
    for (int i = 0; i < text.length; i++) {
      final String c = text[i];
      if ('(<{['.contains(c)) d++;
      if (')>}]'.contains(c)) d--;
      if (c == '=' && d == 0 && (i + 1 >= text.length || text[i + 1] != '>')) {
        text = text.substring(0, i).trim();
        break;
      }
    }
    result.add(ChainParameter(RegExp(r'([A-Za-z_][A-Za-z0-9_]*)$').firstMatch(text)!.group(1)!, named: named));
  }

  for (int i = 0; i < parameters.length; i++) {
    final String c = parameters[i];
    if (depth == 0 && (c == '{' || c == '[') && current.toString().trim().isEmpty) {
      flush();
      named = c == '{';
      continue;
    }
    if (depth == 0 && (c == '}' || c == ']') && !_opensInside(current.toString())) continue;
    if ('(<{['.contains(c)) depth++;
    if (')>}]'.contains(c) && !(c == '>' && i > 0 && parameters[i - 1] == '=')) depth--;
    if (c == ',' && depth == 0) {
      flush();
      continue;
    }
    current.write(c);
  }
  flush();
  return result;
}

String mixinSource(List<ChainMethod> methods) {
  final StringBuffer out = StringBuffer()
    ..writeln('// GENERATED by tool/modifier_chain_source.dart from DVModifier. Do not edit by')
    ..writeln('// hand: change DVModifier and run `dart run tool/modifier_chain_source.dart`.')
    ..writeln('// test/modifier_chain_test.dart fails when the two disagree.')
    ..writeln('//')
    ..writeln('// Every DVModifier step, on the widget itself, the way the spec writes it:')
    ..writeln('//')
    ..writeln("//   DVText('Where voice mode sits').fontSize(17).fontWeight(.w700).color(ink)")
    ..writeln('//')
    ..writeln('// Each step applies to the modifier the widget already has, exactly as the')
    ..writeln('// same step on a DVModifier would, so a chain on the widget and a chain on a')
    ..writeln('// DVModifier handed to it draw the same thing.')
    ..writeln('// ignore_for_file: public_member_api_docs')
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln("import '../../dartvel_flutter.dart';")
    ..writeln()
    ..writeln('/// The DVModifier chain on a widget: [DVText], [DVBox], [DVChoice], [DVSwitch].')
    ..writeln('mixin DVModifierChain<W extends Widget> {')
    ..writeln('  /// The modifier the widget has so far, or null.')
    ..writeln('  DVModifier? get chainModifier;')
    ..writeln()
    ..writeln('  /// The same widget with [modifier] in place of its own.')
    ..writeln('  W withModifier(DVModifier modifier);')
    ..writeln()
    ..writeln('  DVModifier get _base => chainModifier ?? const DVModifier();');
  for (final ChainMethod method in methods) {
    out
      ..writeln()
      ..writeln('  /// [DVModifier.${method.name}] on this widget.')
      ..writeln('  W ${method.name}(${method.parameters}) => withModifier(_base.${method.name}(${method.arguments}));');
  }
  out.writeln('}');
  return out.toString();
}

void main() {
  final String library = File('lib/dartvel_flutter.dart').readAsStringSync();
  File('lib/src/primitives/modifier_chain.dart')
    ..createSync(recursive: true)
    ..writeAsStringSync(mixinSource(modifierMethods(library)));
  stdout.writeln('wrote lib/src/primitives/modifier_chain.dart');
}

/// Whether [text] has an unclosed `{` or `[` of its own (a default value's
/// literal), so the closing one belongs to it, not to the section.
bool _opensInside(String text) {
  int open = 0;
  for (final int unit in text.codeUnits) {
    final String c = String.fromCharCode(unit);
    if (c == '{' || c == '[') open++;
    if (c == '}' || c == ']') open--;
  }
  return open > 0;
}
