// Generates src/src/diagnostic/diagnostic_g.rs and
// src/src/diagnostic/diagnostic_code_values_g.rs (see ../README.md): the
// analyzer's diagnostic codes, and how the parser's codes map to them.
//
// Reflects with `dart:mirrors` on the analyzer's diagnostic library (every
// top-level `DiagnosticCode`, by its Dart name: its `name` and
// `uniqueName`), on `sharedAnalyzerCodes`, and on every `Code` of
// _fe_analyzer_shared's diagnostic library (its `sharedCode` and
// `pseudoSharedCode`, which the Rust port of that library does not carry).
//
// Run it again when the messages change:
//   dart --packages=<package_config.json> \
//     pkg/analyzer/rust/oracle/generate_codes.dart pkg/analyzer/rust/src/src/diagnostic

// ignore_for_file: deprecated_member_use

import 'dart:io';
import 'dart:mirrors';

import 'package:_fe_analyzer_shared/src/base/errors.dart';
import 'package:_fe_analyzer_shared/src/messages/codes.dart';
import 'package:_fe_analyzer_shared/src/messages/diagnostic.dart' as fe;
import 'package:analyzer/src/diagnostic/diagnostic.dart' as diag;
import 'package:analyzer/src/diagnostic/diagnostic_code_values.dart';

Map<String, Object?> topLevelValues(Uri uri) {
  LibraryMirror library = currentMirrorSystem().libraries[uri]!;
  Map<String, Object?> result = {};
  for (var entry in library.declarations.entries) {
    var d = entry.value;
    String name = MirrorSystem.getName(entry.key);
    if (name.startsWith('_')) continue;
    if ((d is VariableMirror && d.isStatic) ||
        (d is MethodMirror && d.isGetter)) {
      try {
        result[name] = library.getField(entry.key).reflectee;
      } catch (_) {}
    }
  }
  return result;
}

LibraryMirror libraryOf(Object o) =>
    (reflect(o).type.owner is LibraryMirror
        ? reflect(o).type.owner
        : null) as LibraryMirror;

void main(List<String> args) {
  // The libraries holding the codes (diagnostic.dart parts in
  // diagnostic.g.dart).
  Uri analyzerDiag = Uri.parse(
    'package:analyzer/src/diagnostic/diagnostic.dart',
  );
  Uri feDiag = Uri.parse(
    'package:_fe_analyzer_shared/src/messages/diagnostic.dart',
  );
  // Touch the imports so they are loaded.
  diag.expectedToken;
  fe.expectedToken;

  Map<String, DiagnosticCode> analyzerCodes = {};
  topLevelValues(analyzerDiag).forEach((name, value) {
    if (value is DiagnosticCode) analyzerCodes[name] = value;
  });
  List<String> names = analyzerCodes.keys.toList()..sort();
  Map<DiagnosticCode, String> dartNameOf = {
    for (String n in names) analyzerCodes[n]!: n,
  };

  StringBuffer g = StringBuffer();
  g.write('''
// Port of lib/src/diagnostic/diagnostic.g.dart (the codes' names).
//
// Generated by oracle/generate_codes.dart: do not edit. Each analyzer
// diagnostic code is a constant with its Dart name; only `name` and
// `uniqueName` are carried, not the messages.

use crate::src::diagnostic::diagnostic::DiagnosticCode;

''');
  for (String n in names) {
    var code = analyzerCodes[n]!;
    g.writeln(
      'pub const $n: DiagnosticCode = DiagnosticCode { '
      'name: "${code.name}", unique_name: "${code.uniqueName}" };',
    );
  }
  File('${args[0]}/diagnostic_g.rs').writeAsStringSync(g.toString());

  StringBuffer v = StringBuffer();
  v.write('''
// Port of lib/src/diagnostic/diagnostic_code_values.g.dart
// (`sharedAnalyzerCodes`), and of the `sharedCode` and `pseudoSharedCode`
// of every code in _fe_analyzer_shared's lib/src/messages/diagnostic.g.dart,
// which the Rust port of that library does not carry.
//
// Generated by oracle/generate_codes.dart: do not edit.
#![allow(non_camel_case_types)]

use crate::src::diagnostic::diagnostic::DiagnosticCode;
use crate::src::diagnostic::diagnostic_g as diag;

/// `sharedAnalyzerCodes`, indexed by `SharedCode.index`.
pub const sharedAnalyzerCodes: [DiagnosticCode; ${sharedAnalyzerCodes.length}] = [
''');
  for (var code in sharedAnalyzerCodes) {
    v.writeln('    diag::${dartNameOf[code]!},');
  }
  v.writeln('];');
  v.writeln();
  v.writeln('/// `enum PseudoSharedCode`.');
  v.writeln('#[derive(Clone, Copy, PartialEq, Eq, Debug)]');
  v.writeln('pub enum PseudoSharedCode {');
  for (var c in fe.PseudoSharedCode.values) {
    v.writeln('    ${c.name},');
  }
  v.writeln('}');
  v.writeln();

  List<(String, int?, String?)> rows = [];
  topLevelValues(feDiag).forEach((name, value) {
    if (value is Code) {
      rows.add((value.name, value.sharedCode?.index, value.pseudoSharedCode?.name));
    }
  });
  rows.sort((a, b) => a.$1.compareTo(b.$1));
  v.writeln('/// `Code.sharedCode` (as its index) of the code named [name].');
  v.writeln('pub fn shared_code(name: &str) -> Option<usize> {');
  v.writeln('    match name {');
  for (var (n, s, _) in rows) {
    if (s != null) v.writeln('        "$n" => Some($s),');
  }
  v.writeln('        _ => None,');
  v.writeln('    }');
  v.writeln('}');
  v.writeln();
  v.writeln('/// `Code.pseudoSharedCode` of the code named [name].');
  v.writeln(
    'pub fn pseudo_shared_code(name: &str) -> Option<PseudoSharedCode> {',
  );
  v.writeln('    match name {');
  for (var (n, _, p) in rows) {
    if (p != null) v.writeln('        "$n" => Some(PseudoSharedCode::$p),');
  }
  v.writeln('        _ => None,');
  v.writeln('    }');
  v.writeln('}');
  File(
    '${args[0]}/diagnostic_code_values_g.rs',
  ).writeAsStringSync(v.toString());
  stdout.writeln(
    '${names.length} analyzer codes, ${rows.length} parser codes, '
    '${sharedAnalyzerCodes.length} shared',
  );
}
