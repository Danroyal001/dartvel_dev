// Generates the Rust port of the V2 visitors (see ../README.md):
//
// - src/src/dart/ast/ast_g.rs, the port of `AstVisitor2` in
//   lib/src/dart/ast/ast.g.dart;
// - src/dart/ast/visitor_g.rs, the port of `RecursiveAstVisitor2`,
//   `SimpleAstVisitor2`, `ThrowingAstVisitor2` and `UnifyingAstVisitor2` in
//   lib/dart/ast/visitor.g.dart;
// - the recording visitors the API oracle uses on both sides:
//   oracle/ast_api_recorders.g.dart and src/bin/ast_dump/recorders.rs.
//
// Upstream generates both Dart files (pkg/analyzer/tool/ast/generate.dart);
// this program reads them with the analyzer and translates every method,
// failing on a body whose shape it does not know.
//
// Run it again when ast.g.dart or visitor.g.dart changes:
//   dart --packages=<package_config.json> \
//     pkg/analyzer/rust/oracle/generate_visitors.dart pkg/analyzer
//
// Only the V2 visitors are ported. The V1 ones (`AstVisitor`,
// `GeneralizingAstVisitor`, `BreadthFirstVisitor`, ...) visit the V1 view
// of the tree, which the port does not build.

import 'dart:io';

import 'package:analyzer/dart/analysis/utilities.dart';
import 'package:analyzer/dart/ast/ast.dart';

/// The visitor classes of visitor.g.dart that are ported.
const List<String> portedClasses = [
  'GeneralizingAstVisitor',
  'RecursiveAstVisitor',
  'RecursiveAstVisitor2',
  'SimpleAstVisitor',
  'SimpleAstVisitor2',
  'ThrowingAstVisitor',
  'ThrowingAstVisitor2',
  'UnifyingAstVisitor',
  'UnifyingAstVisitor2',
];

/// Hand translations of the bodies that are not one of the generated
/// shapes: Rust, with `v` the visitor.
const Map<String, String> handBodies = {
  'GeneralizingAstVisitor.visitFunctionDeclaration': '''
let parent = ast.parent(node);
        if parent != crate::src::dart::ast::ast_store::NO_NODE
            && matches!(
                ast.node(parent),
                crate::src::dart::ast::ast::AstNodeImpl::FunctionDeclarationStatementImpl(_)
            )
        {
            return <V as GeneralizingAstVisitor>::visit_node(v, ast, node);
        }
        <V as GeneralizingAstVisitor>::visit_compilation_unit_member(v, ast, node)''',
};

String snake(String name) {
  StringBuffer sb = StringBuffer();
  for (int i = 0; i < name.length; i++) {
    String c = name[i];
    if (c.toUpperCase() == c && c.toLowerCase() != c) {
      if (i > 0) sb.write('_');
      sb.write(c.toLowerCase());
    } else {
      sb.write(c);
    }
  }
  return sb.toString();
}

ClassDeclaration classNamed(CompilationUnit unit, String name) {
  for (var d in unit.declarations) {
    if (d is ClassDeclaration && d.namePart.typeName.lexeme == name) return d;
  }
  throw StateError('no class $name');
}

List<MethodDeclaration> methodsOf(ClassDeclaration c) => [
  for (var m in (c.body as BlockClassBody).members)
    if (m is MethodDeclaration) m,
];

/// A method of a ported visitor class, translated.
class Method {
  final String name;

  /// `visitChildren` (recurse and return null), `null`, `throw` or the name
  /// of the method it forwards to.
  final String body;

  new(this.name, this.body);
}

Method translate(String className, MethodDeclaration m) {
  String name = m.name.lexeme;
  Never fail() =>
      throw StateError('$className.$name: unknown body ${m.body.toSource()}');
  var params = m.parameters!.parameters;
  if (params.length != 1 || params.single.name?.lexeme != 'node') fail();
  var body = m.body;
  if (handBodies.containsKey('$className.$name')) {
    return Method(name, 'hand');
  }
  if (body is BlockFunctionBody) {
    var s = body.block.statements;
    if (s.length == 2 &&
        (s[0].toSource() == 'node.visitChildren2(this);' ||
            s[0].toSource() == 'node.visitChildren(this);') &&
        s[1].toSource() == 'return null;') {
      return Method(name, 'visitChildren');
    }
    fail();
  }
  if (body is ExpressionFunctionBody) {
    var e = body.expression;
    if (e is NullLiteral) return Method(name, 'null');
    if (e is MethodInvocation &&
        e.target == null &&
        e.argumentList.arguments.length == 1 &&
        e.argumentList.arguments.single.toSource() == 'node') {
      if (e.methodName.name == '_throw') return Method(name, 'throw');
      return Method(name, e.methodName.name);
    }
  }
  fail();
}

const String rustHeaderNote = '''
// Generated by oracle/generate_visitors.dart: do not edit. Run the generator
// again when upstream's generated visitors change (see
// ../../../../README.md).''';

void main(List<String> args) {
  String root = args[0];
  CompilationUnit astG = parseString(
    content: File('$root/lib/src/dart/ast/ast.g.dart').readAsStringSync(),
    throwIfDiagnostics: false,
  ).unit;
  CompilationUnit visitorG = parseString(
    content: File('$root/lib/dart/ast/visitor.g.dart').readAsStringSync(),
    throwIfDiagnostics: false,
  ).unit;

  // AstVisitor2: every method, in order.
  List<String> visits2 = [
    for (var m in methodsOf(classNamed(astG, 'AstVisitor2'))) m.name.lexeme,
  ];

  List<MethodDeclaration> visitor2Methods = methodsOf(
    classNamed(astG, 'AstVisitor2'),
  );
  List<MethodDeclaration> visitor1Methods = methodsOf(
    classNamed(astG, 'AstVisitor'),
  );
  Set<String> visitor1Names = {for (var m in visitor1Methods) m.name.lexeme};
  List<MethodDeclaration> generalizingMethods = [
    for (var m in methodsOf(classNamed(visitorG, 'GeneralizingAstVisitor')))
      if (!m.name.lexeme.startsWith('_')) m,
  ];

  List<String> visits1 = [for (var m in visitor1Methods) m.name.lexeme];

  StringBuffer a = StringBuffer();
  a.writeln('// Port of lib/src/dart/ast/ast.g.dart (`AstVisitor`, `AstVisitor2`).');
  a.writeln('//');
  a.writeln(rustHeaderNote.replaceAll('../../../../', '../../../../../'));
  a.writeln('//');
  a.writeln('// A visit method takes the tree (`Ast`) and the node\'s id, as');
  a.writeln('// upstream\'s takes the node. `R? visitX(X node)` returns');
  a.writeln('// `Option<Self::R>`. `AstVisitor` visits the V1 view of the tree,');
  a.writeln('// `AstVisitor2` the V2 view.');
  a.writeln('#![allow(clippy::all)]');
  a.writeln();
  a.writeln('use crate::src::dart::ast::ast_store::{Ast, NodeId};');
  for (var (String trait, List<String> list) in [
    ('AstVisitor', visits1),
    ('AstVisitor2', visits2),
  ]) {
    a.writeln();
    a.writeln('/// `abstract class $trait<R>`.');
    a.writeln('pub trait $trait {');
    a.writeln('    type R;');
    for (String v in list) {
      a.writeln();
      a.writeln('    /// `$v`.');
      a.writeln(
        "    fn ${snake(v)}(&mut self, ast: Ast<'_>, node: NodeId) -> Option<Self::R>;",
      );
    }
    a.writeln('}');
  }
  File('$root/rust/src/src/dart/ast/ast_g.rs').writeAsStringSync(a.toString());

  StringBuffer v = StringBuffer();
  v.writeln('// Port of lib/dart/ast/visitor.g.dart.');
  v.writeln('//');
  v.writeln(rustHeaderNote);
  v.writeln('//');
  v.writeln('// A visitor class `XAstVisitor2<R>` is a trait `XAstVisitor2` whose');
  v.writeln('// methods default to upstream\'s bodies, which are also the free');
  v.writeln('// functions of the module `x_ast_visitor2`, so that an override can');
  v.writeln('// call the overridden method (`super.visitX(node)`). A type that');
  v.writeln('// implements the trait becomes an `AstVisitor2` with the macro of the');
  v.writeln('// same name, which forwards every `AstVisitor2` method to the trait:');
  v.writeln('//');
  v.writeln('//     impl RecursiveAstVisitor2 for Counter { ... }');
  v.writeln('//     recursive_ast_visitor2!(Counter, ());');
  v.writeln('//');
  v.writeln('// The V1 visitors (`GeneralizingAstVisitor`, `RecursiveAstVisitor`,');
  v.writeln('// ...) are the same over `AstVisitor` and the V1 view.');
  v.writeln('#![allow(clippy::all)]');
  v.writeln();
  v.writeln('use crate::src::dart::ast::ast_g::{AstVisitor, AstVisitor2};');
  v.writeln('use crate::src::dart::ast::ast_store::{Ast, NodeId};');
  for (String className in portedClasses) {
    bool v2 = className.endsWith('2');
    String base = v2 ? 'AstVisitor2' : 'AstVisitor';
    List<String> visits = v2 ? visits2 : visits1;
    var c = classNamed(visitorG, className);
    List<Method> methods = [
      for (var m in methodsOf(c))
        if (m.name.lexeme != '_throw') translate(className, m),
    ];
    Set<String> names = {for (var m in methods) m.name};
    for (String visit in visits) {
      if (!names.contains(visit)) {
        throw StateError('$className does not implement $visit');
      }
    }
    String module = snake(className);
    String body(Method m, String self) => switch (m.body) {
      'visitChildren' =>
        'ast.${v2 ? 'visit_children2' : 'visit_children'}(node, $self);\n        None',
      'hand' => handBodies['$className.${m.name}']!,
      'null' => 'let _ = ($self, ast, node);\n        None',
      'throw' => 'let _ = $self;\n        throw_(ast, node)',
      String other =>
        '<V as $className>::${snake(other)}($self, ast, node)',
    };
    v.writeln();
    v.writeln('/// The bodies of `$className`\'s methods.');
    v.writeln('pub mod $module {');
    v.writeln('    use super::*;');
    if (methods.any((m) => m.body == 'throw')) {
      v.writeln();
      v.writeln('    /// `_throw(node)`.');
      v.writeln("    pub fn throw_<R>(ast: Ast<'_>, node: NodeId) -> R {");
      v.writeln('        let mut type_name = ast.node(node).runtime_type();');
      v.writeln('        if let Some(name) = type_name.strip_suffix("Impl") {');
      v.writeln('            type_name = name;');
      v.writeln('        }');
      v.writeln(
        '        panic!("Exception: Missing implementation of visit{type_name}");',
      );
      v.writeln('    }');
    }
    for (Method m in methods) {
      v.writeln();
      v.writeln('    /// `$className.${m.name}`.');
      v.writeln(
        "    pub fn ${snake(m.name)}<V: $className + ?Sized>(v: &mut V, ast: Ast<'_>, node: NodeId) -> Option<V::R> {",
      );
      v.writeln('        ${body(m, 'v')}');
      v.writeln('    }');
    }
    v.writeln('}');
    v.writeln();
    v.writeln('/// `class $className<R> implements $base<R>`.');
    v.writeln('pub trait $className: $base {');
    for (Method m in methods) {
      v.writeln(
        "    fn ${snake(m.name)}(&mut self, ast: Ast<'_>, node: NodeId) -> Option<Self::R> {",
      );
      v.writeln('        $module::${snake(m.name)}(self, ast, node)');
      v.writeln('    }');
      v.writeln();
    }
    v.writeln('}');
    v.writeln();
    v.writeln('/// Implements `$base` for a type that implements');
    v.writeln('/// `$className`: `$module!(Type, R)`, or');
    v.writeln("/// `$module!(['a, T] Type<'a, T>, R)` for a generic type.");
    v.writeln('#[macro_export]');
    v.writeln('macro_rules! $module {');
    for (var (String pattern, String generics) in [
      (r'([$($g:tt)*] $t:ty, $r:ty)', r'<$($g)*>'),
      (r'($t:ty, $r:ty)', ''),
    ]) {
    v.writeln('    $pattern => {');
    v.writeln(
      '        impl$generics \$crate::src::dart::ast::ast_g::$base for \$t {',
    );
    v.writeln(r'            type R = $r;');
    for (String visit in visits) {
      v.writeln(
        "            fn ${snake(visit)}(&mut self, ast: \$crate::src::dart::ast::ast_store::Ast<'_>, node: \$crate::src::dart::ast::ast_store::NodeId) -> Option<\$r> {",
      );
      v.writeln(
        '                <\$t as \$crate::dart::ast::visitor_g::$className>::${snake(visit)}(self, ast, node)',
      );
      v.writeln('            }');
    }
    v.writeln('        }');
    v.writeln('    };');
    }
    v.writeln('}');
  }
  File('$root/rust/src/dart/ast/visitor_g.rs').writeAsStringSync(v.toString());

  // The recorders of the API oracle: a RecursiveAstVisitor2 and a
  // SimpleAstVisitor2 that log every visit method called, with its node.
  StringBuffer d = StringBuffer();
  d.writeln('// Recording visitors for the API oracle (ast_dump.dart --api).');
  d.writeln('//');
  d.writeln('// Generated by generate_visitors.dart: do not edit.');
  d.writeln();
  d.writeln("import 'package:analyzer/dart/ast/visitor.dart';");
  d.writeln("import 'package:analyzer/src/dart/ast/ast.dart';");
  for (var (String name, String base, bool callSuper, List<MethodDeclaration> ms)
      in [
        ('RecursiveRecorder', 'RecursiveAstVisitor2', true, visitor2Methods),
        ('SimpleRecorder', 'SimpleAstVisitor2', false, visitor2Methods),
        ('RecursiveRecorder1', 'RecursiveAstVisitor', true, visitor1Methods),
        ('SimpleRecorder1', 'SimpleAstVisitor', false, visitor1Methods),
        (
          'GeneralizingRecorder',
          'GeneralizingAstVisitor',
          true,
          generalizingMethods,
        ),
      ]) {
    d.writeln();
    d.writeln('class $name extends $base<void> {');
    d.writeln('  final void Function(String, AstNode) log;');
    d.writeln();
    d.writeln('  $name(this.log);');
    for (var m in ms) {
      String type = m.parameters!.parameters.single.toSource().split(' ').first;
      String visit = m.name.lexeme;
      d.writeln();
      if (base != 'GeneralizingAstVisitor' ||
          visitor1Names.contains(visit) ||
          visit == 'visitNode') {
        d.writeln('  @override');
      }
      d.writeln('  void $visit($type node) {');
      d.writeln("    log('$visit', node);");
      if (callSuper) d.writeln('    super.$visit(node);');
      d.writeln('  }');
    }
    d.writeln('}');
  }
  File('$root/rust/oracle/ast_api_recorders.g.dart').writeAsStringSync(
    d.toString(),
  );

  StringBuffer r = StringBuffer();
  r.writeln('// Port of rust/oracle/ast_api_recorders.g.dart: the recording');
  r.writeln('// visitors of the API oracle.');
  r.writeln('//');
  r.writeln('// Generated by oracle/generate_visitors.dart: do not edit.');
  r.writeln();
  r.writeln('use analyzer::dart::ast::visitor_g::{');
  r.writeln('    GeneralizingAstVisitor, RecursiveAstVisitor, RecursiveAstVisitor2, SimpleAstVisitor,');
  r.writeln('    SimpleAstVisitor2, generalizing_ast_visitor, recursive_ast_visitor, recursive_ast_visitor2,');
  r.writeln('};');
  r.writeln('use analyzer::src::dart::ast::ast_store::{Ast, NodeId};');
  r.writeln('use analyzer::{');
  r.writeln('    generalizing_ast_visitor, recursive_ast_visitor, recursive_ast_visitor2, simple_ast_visitor,');
  r.writeln('    simple_ast_visitor2,');
  r.writeln('};');
  List<String> generalizing = [for (var m in generalizingMethods) m.name.lexeme];
  for (var (String name, String base, bool callSuper, List<String> list) in [
    ('RecursiveRecorder', 'RecursiveAstVisitor2', true, visits2),
    ('SimpleRecorder', 'SimpleAstVisitor2', false, visits2),
    ('RecursiveRecorder1', 'RecursiveAstVisitor', true, visits1),
    ('SimpleRecorder1', 'SimpleAstVisitor', false, visits1),
    ('GeneralizingRecorder', 'GeneralizingAstVisitor', true, generalizing),
  ]) {
    r.writeln();
    r.writeln("pub struct $name<'l> {");
    r.writeln("    pub log: &'l mut dyn FnMut(&'static str, NodeId),");
    r.writeln('}');
    r.writeln();
    r.writeln("impl $base for $name<'_> {");
    for (String visit in list) {
      r.writeln(
        "    fn ${snake(visit)}(&mut self, ast: Ast<'_>, node: NodeId) -> Option<()> {",
      );
      r.writeln("        (self.log)(\"$visit\", node);");
      if (callSuper) {
        r.writeln('        ${snake(base)}::${snake(visit)}(self, ast, node)');
      } else {
        r.writeln('        let _ = ast;');
        r.writeln('        None');
      }
      r.writeln('    }');
      r.writeln();
    }
    r.writeln('}');
    r.writeln();
    r.writeln("${snake(base)}!($name<'_>, ());");
  }
  File('$root/rust/src/bin/ast_dump/recorders.rs').writeAsStringSync(
    r.toString(),
  );
  stdout.writeln('${visits2.length} visit methods');
}
