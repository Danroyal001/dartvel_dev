// Generates src/src/dart/analysis/experiments_g.rs, the Rust port of the
// feature table in lib/src/dart/analysis/experiments.g.dart (see
// ../README.md), from the analyzer's own `ExperimentStatus.knownFeatures`.
//
// Run it again when experiments.g.dart changes:
//   dart --packages=<package_config.json> \
//     pkg/analyzer/rust/oracle/generate_experiments.dart \
//     pkg/analyzer/rust/src/src/dart/analysis/experiments_g.rs

import 'dart:io';

import 'package:_fe_analyzer_shared/src/experiments/flags.dart' as shared;
import 'package:analyzer/src/dart/analysis/experiments.dart';
import 'package:pub_semver/pub_semver.dart';

String version(Version? v) {
  if (v == null) return 'None';
  if (v.patch != 0) throw StateError('patch version $v');
  return 'Some(Version::new(${v.major}, ${v.minor}))';
}

void main(List<String> args) {
  var features = ExperimentStatus.knownFeatures.values.toList()
    ..sort((a, b) => a.index.compareTo(b.index));
  StringBuffer out = StringBuffer();
  out.write('''
// Port of lib/src/dart/analysis/experiments.g.dart, the feature table.
//
// Generated by oracle/generate_experiments.dart from the analyzer's
// `ExperimentStatus.knownFeatures`: do not edit. A feature is its index;
// only the members that decide which features a language version enables
// are kept.

use fe_analyzer_shared::experiments::flags::{ExperimentalFlag, Version};

use crate::src::dart::analysis::experiments_impl::ExperimentalFeature;

/// `_currentVersion`.
pub const currentVersion: Version = Version::new(${ExperimentStatus.currentVersion.major}, ${ExperimentStatus.currentVersion.minor});

/// `_knownFeatures`, by index.
pub const knownFeatures: [ExperimentalFeature; ${features.length}] = [
''');
  for (var f in features) {
    out.writeln('    ExperimentalFeature {');
    out.writeln('        index: ${f.index},');
    out.writeln('        enable_string: "${f.enableString}",');
    out.writeln('        is_enabled_by_default: ${f.isEnabledByDefault},');
    out.writeln(
      '        experimental_release_version: '
      '${version(f.experimentalReleaseVersion)},',
    );
    out.writeln('        release_version: ${version(f.releaseVersion)},');
    out.writeln('    },');
  }
  out.writeln('];');
  out.writeln();
  out.writeln('/// `fromSharedExperimentalFlags`: the index of the feature.');
  out.writeln(
    'pub fn from_shared_experimental_flags(flag: ExperimentalFlag) -> usize {',
  );
  out.writeln('    match flag {');
  for (var flag in shared.ExperimentalFlag.values) {
    var feature = fromSharedExperimentalFlags(flag) as ExperimentalFeature;
    out.writeln('        ExperimentalFlag::${flag.toString().split(".").last} => ${feature.index},');
  }
  out.writeln('    }');
  out.writeln('}');
  out.writeln();
  out.writeln('/// The `Feature` constants the parser and the AstBuilder read,');
  out.writeln('/// as indices (`Feature.x`).');
  out.writeln('pub mod Feature {');
  for (var f in features) {
    String name = f.enableString.replaceAll('-', '_');
    out.writeln('    pub const $name: usize = ${f.index};');
  }
  out.writeln('}');
  File(args[0]).writeAsStringSync(out.toString());
}
