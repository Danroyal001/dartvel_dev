// Generator for the parser oracle's tracing listeners (see ../README.md).
//
// Reflects on the upstream `Listener` and writes two listeners that log
// every event with its arguments, one line per event, in one format:
//
//   oracle/parser_trace_listener.dart        (on the upstream parser)
//   src/bin/parser_dump/trace_listener.rs    (on the Rust port)
//
// Run it from the SDK root after `listener.dart` changes:
//
//   dart --packages=pkg/_fe_analyzer_shared/rust/oracle/package_config.json \
//     pkg/_fe_analyzer_shared/rust/oracle/generate_parser_trace.dart
//
// It needs `dart:mirrors`, so it runs on the JIT VM only.

import 'dart:io';
import 'dart:mirrors';

import 'package:_fe_analyzer_shared/src/parser/listener.dart';

const String rustDir = 'pkg/_fe_analyzer_shared/rust';

class Param {
  final String name;
  final String type;
  final bool isNamed;
  new(this.name, this.type, this.isNamed);
}

class Method {
  final String name;
  final List<Param> params;
  final int line;
  new(this.name, this.params, this.line);
}

void main() {
  ClassMirror listener = reflectClass(Listener);
  List<Method> methods = [];
  listener.declarations.forEach((Symbol symbol, DeclarationMirror d) {
    if (d is! MethodMirror || !d.isRegularMethod || d.isStatic) return;
    String name = MirrorSystem.getName(symbol);
    if (name == 'logEvent') return;
    methods.add(
      new Method(name, [
        for (ParameterMirror p in d.parameters)
          new Param(
            MirrorSystem.getName(p.simpleName),
            MirrorSystem.getName(p.type.simpleName),
            p.isNamed,
          ),
      ], d.location!.line),
    );
  });
  methods.sort((a, b) => a.line - b.line);
  new File(
    '$rustDir/oracle/parser_trace_listener.dart',
  ).writeAsStringSync(dartListener(methods));
  new File(
    '$rustDir/src/bin/parser_dump/trace_listener.rs',
  ).writeAsStringSync(rustListener(methods));
}

const String header =
    'GENERATED by oracle/generate_parser_trace.dart from the upstream '
    'Listener; do not edit.';

String dartListener(List<Method> methods) {
  StringBuffer sb = new StringBuffer();
  sb.writeln('// $header');
  sb.writeln('//');
  sb.writeln('// A listener that logs every parser event, one line each.');
  sb.writeln();
  sb.writeln("import 'package:_fe_analyzer_shared/src/experiments/flags.dart';");
  sb.writeln("import 'package:_fe_analyzer_shared/src/messages/codes.dart';");
  for (String lib in [
    'assert',
    'block_kind',
    'constructor_reference_context',
    'declaration_kind',
    'formal_parameter_kind',
    'identifier_context',
    'listener',
    'member_kind',
  ]) {
    sb.writeln("import 'package:_fe_analyzer_shared/src/parser/$lib.dart';");
  }
  sb.writeln(
    "import 'package:_fe_analyzer_shared/src/scanner/error_token.dart';",
  );
  sb.writeln("import 'package:_fe_analyzer_shared/src/scanner/token.dart';");
  sb.writeln();
  sb.writeln("import 'parser_trace_format.dart';");
  sb.writeln();
  sb.writeln('class TraceListener extends Listener {');
  sb.writeln('  final StringBuffer sb = new StringBuffer();');
  for (Method m in methods) {
    sb.writeln();
    sb.writeln('  @override');
    List<String> positional = [], named = [];
    for (Param p in m.params) {
      String decl = '${p.type}? ${p.name}';
      (p.isNamed ? named : positional).add(decl);
    }
    String params = [
      ...positional,
      if (named.isNotEmpty) '{${named.join(', ')}}',
    ].join(', ');
    sb.writeln('  void ${m.name}($params) {');
    sb.write("    sb.write('${m.name}");
    for (Param p in m.params) {
      sb.write(' \${${dartFormat(p)}}');
    }
    if (m.name == 'handleErrorToken') {
      sb.write(' \${formatMessage(token!.assertionMessage)}');
    }
    sb.writeln(r"\n');");
    sb.writeln('  }');
  }
  sb.writeln('}');
  return sb.toString();
}

String dartFormat(Param p) {
  switch (p.type) {
    case 'Token':
    case 'ErrorToken':
      return 'formatToken(${p.name})';
    case 'String':
      return 'formatString(${p.name})';
    case 'Message':
    case 'MessageCode':
      return 'formatMessage(${p.name})';
    default:
      return p.name;
  }
}

String snake(String name) {
  StringBuffer sb = new StringBuffer();
  for (int i = 0; i < name.length; i++) {
    String c = name[i];
    if (c.toUpperCase() == c && c.toLowerCase() != c) {
      sb.write('_${c.toLowerCase()}');
    } else {
      sb.write(c);
    }
  }
  return sb.toString();
}

String rustType(Param p) {
  switch (p.type) {
    case 'Token':
    case 'ErrorToken':
      return 'TokenId';
    case 'int':
      return 'i32';
    case 'bool':
      return 'bool';
    case 'String':
      return 'Option<&str>';
    case 'Message':
      return '&Message';
    case 'MessageCode':
      return '&\'static MessageCode';
    case 'IdentifierContext':
      return '&\'static IdentifierContext';
    default:
      return p.type;
  }
}

String rustFormat(Param p) {
  String name = snake(p.name);
  switch (p.type) {
    case 'Token':
    case 'ErrorToken':
      return 'self.token(tokens, $name)';
    case 'int':
    case 'bool':
      return 'self.value($name)';
    case 'String':
      return 'self.string($name)';
    case 'Message':
      return 'self.message($name)';
    case 'MessageCode':
      return 'self.message(&$name.message())';
    default:
      return 'self.value($name)';
  }
}

String rustListener(List<Method> methods) {
  StringBuffer sb = new StringBuffer();
  sb.writeln('// Port of rust/oracle/parser_trace_listener.dart. $header');
  sb.writeln();
  sb.writeln('use fe_analyzer_shared::experiments::flags::ExperimentalFlag;');
  sb.writeln(
    'use fe_analyzer_shared::messages::codes::{Message, MessageCode};',
  );
  sb.writeln('use fe_analyzer_shared::parser::assert::Assert;');
  sb.writeln('use fe_analyzer_shared::parser::block_kind::BlockKind;');
  sb.writeln(
    'use fe_analyzer_shared::parser::constructor_reference_context::'
    'ConstructorReferenceContext;',
  );
  sb.writeln(
    'use fe_analyzer_shared::parser::declaration_kind::'
    '{DeclarationHeaderKind, DeclarationKind};',
  );
  sb.writeln(
    'use fe_analyzer_shared::parser::formal_parameter_kind::'
    'FormalParameterKind;',
  );
  sb.writeln(
    'use fe_analyzer_shared::parser::identifier_context::IdentifierContext;',
  );
  sb.writeln('use fe_analyzer_shared::parser::listener::Listener;');
  sb.writeln('use fe_analyzer_shared::parser::member_kind::MemberKind;');
  sb.writeln(
    'use fe_analyzer_shared::scanner::token::{TokenId, TokenStore};',
  );
  sb.writeln();
  sb.writeln('use super::TraceListener;');
  sb.writeln();
  sb.writeln('impl Listener for TraceListener {');
  bool first = true;
  for (Method m in methods) {
    if (!first) sb.writeln();
    first = false;
    List<String> params = ['&mut self', 'tokens: &TokenStore'];
    for (Param p in m.params) {
      params.add('${snake(p.name)}: ${rustType(p)}');
    }
    bool usesTokens =
        m.params.any((p) => p.type == 'Token' || p.type == 'ErrorToken');
    if (!usesTokens) params[1] = '_tokens: &TokenStore';
    sb.writeln('    fn ${snake(m.name)}(${params.join(', ')}) {');
    sb.writeln('        self.start("${m.name}");');
    for (Param p in m.params) {
      sb.writeln('        ${rustFormat(p)};');
    }
    if (m.name == 'handleErrorToken') {
      sb.writeln(
        '        self.message(&tokens.assertion_message_of(token));',
      );
    }
    sb.writeln('        self.end();');
    sb.writeln('    }');
  }
  sb.writeln('}');
  return sb.toString();
}
